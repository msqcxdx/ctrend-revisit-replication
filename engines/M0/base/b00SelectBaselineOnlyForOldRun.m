% Execution-scope adapter for the old pipeline.
%
% Do not alter any old estimation formula.  The requested comparison uses
% only the published baseline, so retain exactly that row from the design
% grid produced by the unchanged b00GenerateDesignChoices.m.  This prevents
% b02 from rebuilding three unused data variants and keeps b09/b10 outside
% the old baseline run.

load('DesignChoices.mat', 'tDataCombos', 'tCombos');

lBaseline = strcmpi(tCombos.cOutlierTreatment, 'trunc') & ...
    tCombos.vThreshold == 0.005 & ...
    logical(tCombos.vExclStable) & ...
    tCombos.vMinMCAP == 1e6 & ...
    tCombos.vMinPRC == 0 & ...
    tCombos.vRetLead == 0 & ...
    logical(tCombos.vRoll) & ...
    tCombos.vNumIn == 52 & ...
    logical(tCombos.vUseValueWts) & ...
    logical(tCombos.vUseVolume);
assert(nnz(lBaseline) == 1, ...
    'Old design grid must contain exactly one published baseline row');

tCombos = tCombos(lBaseline,:);
iBaselineDataSetting = tCombos.data_setting(1);
tDataCombos = tDataCombos(tDataCombos.data_setting == ...
    iBaselineDataSetting,:);
assert(height(tDataCombos) == 1, ...
    'Old baseline must map to exactly one preprocessing setting');

sPipelineMode = 'old-baseline-only';
save('DesignChoices.mat', 'tDataCombos', 'tCombos', 'sPipelineMode');
