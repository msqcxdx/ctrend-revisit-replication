function [mOpen,mHigh,mLow,mClose,mME,mVolume,rAudit] = ...
    fApplyV2RawDataCorrections( ...
    mOpen,mHigh,mLow,mClose,mME,mVolume,dtDate,vAssetID,rMetaData)
% Apply the frozen, field/date-specific unit-continuity registry.
%
% This isolated sensitivity helper has two explicit modes selected by
% CTREND_RAW_ADJUSTMENT_MODE:
%   none                       - return all six panels bit-for-bit unchanged;
%   event_registry_v20260810   - apply raw_panel_adjustments.csv.
%
% A row changes exactly one CMCID/panel/date interval.  Rows are applied in
% Sequence order so repeated unit events compound.  Open, High, Low, Close,
% MarketCap and Volume have independent intervals.  A verified within-day
% unit switch whose complete trade-level extrema cannot be recovered uses an
% explicit mask_auxiliary_to_nan operation for O/H/L only.  The economic
% close and P&L are never masked.  volume_cmc.csv is USD trading value, so
% the frozen registry contains no volume scaling unless direct field-level
% evidence (not a token split alone) supports it.

arguments
    mOpen (:,:) double
    mHigh (:,:) double
    mLow (:,:) double
    mClose (:,:) double
    mME (:,:) double
    mVolume (:,:) double
    dtDate (:,1) datetime
    vAssetID (:,:) double
    rMetaData struct
end

cBefore = {mOpen,mHigh,mLow,mClose,mME,mVolume};
cPanelName = ["Open","High","Low","Close","MarketCap","Volume"];
rSizes = cellfun(@size,cBefore,'UniformOutput',false);
assert(all(cellfun(@(x)isequal(x,rSizes{1}),rSizes)), ...
    'Every raw panel must have the same dimensions before event treatment');
vAssetID = vAssetID(:);
assert(rSizes{1}(1) == numel(dtDate) && ...
    rSizes{1}(2) == numel(vAssetID), ...
    'Raw treatment date and asset keys do not match the panels');
assert(all(diff(dtDate) > days(0)) && ...
    numel(unique(vAssetID)) == numel(vAssetID), ...
    'Raw treatment keys must be unique and strictly ordered');
assert(isfield(rMetaData,'vID') && isfield(rMetaData,'cSymbol') && ...
    isequal(vAssetID,rMetaData.vID(:)), ...
    'Raw treatment metadata does not match the CMC asset key');

sMode = lower(strtrim(string(getenv('CTREND_RAW_ADJUSTMENT_MODE'))));
assert(isscalar(sMode) && ismember(sMode, ...
    ["none","event_registry_v20260810"]), ...
    ['CTREND_RAW_ADJUSTMENT_MODE must be explicitly set to none or ' ...
     'event_registry_v20260810']);
sExperimentID = strtrim(string(getenv('CTREND_CORE_EXPERIMENT_ID')));
assert(isscalar(sExperimentID) && strlength(sExperimentID) > 0, ...
    'CTREND_CORE_EXPERIMENT_ID must be explicit');

sTransformer = [mfilename('fullpath'),'.m'];
sTransformerSHA256 = string(fFileSHA256(sTransformer));
sRegistry = strtrim(string(getenv('CTREND_EVENT_REGISTRY_FILE')));

rAudit = struct();
rAudit.sFormat = 'cttrend-core-event-treatment-audit-v1';
rAudit.sExperimentID = char(sExperimentID);
rAudit.sMode = char(sMode);
rAudit.sTransformerSHA256 = char(sTransformerSHA256);
rAudit.sPolicy = [ ...
    'same-CMCID fixed-unit continuity in newer units before every return ' ...
    'or indicator; separate field/date switches; different CMCIDs are not ' ...
    'spliced; mixed-unit transition O/H/L can be explicitly unavailable; ' ...
    'economic close/P&L are never masked and no missing value is filled'];
rAudit.iNumAssetsRemoved = 0;
rAudit.iNumMissingPriceDates = 0;
rAudit.iNumExternalCorruptPriceDates = 0;
rAudit.tMissingPriceRules = table();
rAudit.tExternalCorruptCellEvidence = table();
rAudit.tSeparateCMCIDEvents = table();

if sMode == "none"
    assert(all(cellfun(@(a,b)isequaln(a,b), ...
        cBefore,{mOpen,mHigh,mLow,mClose,mME,mVolume})), ...
        'The explicit no-adjustment treatment changed a raw panel');
    rAudit.sRegistrySHA256 = 'not_consumed';
    rAudit.sRegistryPath = 'not_consumed';
    rAudit.iRegistryRows = 0;
    rAudit.tRegistry = table();
    rAudit.tPriceScaleRules = table();
    rAudit.tAuxiliaryMaskRules = table();
    rAudit.tMarketCapRules = table();
    rAudit.tApplication = table();
    rAudit.iNumPriceScaleRules = 0;
    rAudit.iNumMarketCapCells = 0;
    rAudit.iNumVolumeCellsChanged = 0;
    rAudit.iNumAuxiliaryCellsMasked = 0;
    rAudit.iNumEconomicCloseCellsMasked = 0;
    return
end

assert(isscalar(sRegistry) && strlength(sRegistry) > 0, ...
    ['CTREND_EVENT_REGISTRY_FILE must explicitly identify the frozen ' ...
     'registry for an adjusted experiment']);
sRegistry = string(char(java.io.File(char(sRegistry)).getCanonicalPath()));
assert(exist(sRegistry,'file') == 2, ...
    'Frozen raw-panel event registry is missing: %s',sRegistry);
sRegistrySHA256 = string(fFileSHA256(sRegistry));
tRegistry = readtable(sRegistry,'TextType','string', ...
    'VariableNamingRule','preserve');
cRequired = {'Sequence','EventID','RuleID','AssetID','ExpectedSymbol', ...
    'Operation','Panel','StartDate','EndDate','Factor','AnchorDate', ...
    'ExpectedRawValue','HolderConversion','Evidence','DecisionNote'};
assert(all(ismember(cRequired,tRegistry.Properties.VariableNames)), ...
    'Frozen event registry has missing required columns');
assert(~isempty(tRegistry) && ...
    isequal(tRegistry.Sequence(:),(1:height(tRegistry))'), ...
    'Frozen event-registry Sequence must be exactly 1:N');
assert(all(isfinite(tRegistry.AssetID)) && ...
    all(isfinite(tRegistry.Factor) & tRegistry.Factor > 0), ...
    'Registry asset IDs and factors must be finite and positive');
assert(numel(unique(tRegistry.RuleID)) == height(tRegistry), ...
    'Every registry row must have a unique RuleID');
assert(all(ismember(tRegistry.Panel,cPanelName)), ...
    'Registry contains an unknown panel name');
assert(all(ismember(tRegistry.Operation, ...
    ["multiply","mask_auxiliary_to_nan"])), ...
    'Registry contains an unknown operation');
lMaskOperation = tRegistry.Operation == "mask_auxiliary_to_nan";
assert(all(ismember(tRegistry.Panel(lMaskOperation), ...
    ["Open","High","Low"])) && ...
    all(tRegistry.StartDate(lMaskOperation) == ...
        tRegistry.EndDate(lMaskOperation)) && ...
    ~any(tRegistry.Panel(lMaskOperation) == "Close"), ...
    ['mask_auxiliary_to_nan must be a single-day O/H/L rule and may never ' ...
     'mask the economic close']);

tRegistry.StartDateParsed = datetime(tRegistry.StartDate, ...
    'InputFormat','yyyy-MM-dd');
tRegistry.EndDateParsed = datetime(tRegistry.EndDate, ...
    'InputFormat','yyyy-MM-dd');
tRegistry.AnchorDateParsed = datetime(tRegistry.AnchorDate, ...
    'InputFormat','yyyy-MM-dd');
assert(all(~isnat(tRegistry.StartDateParsed)) && ...
    all(~isnat(tRegistry.EndDateParsed)) && ...
    all(~isnat(tRegistry.AnchorDateParsed)) && ...
    all(tRegistry.StartDateParsed <= tRegistry.EndDateParsed), ...
    'Registry contains an invalid interval or anchor date');

% Validate every identity/date/raw anchor against the immutable input before
% applying any row.  This is essential when repeated events later compound.
for iRule = 1:height(tRegistry)
    iColumn = iAssetColumn(tRegistry.AssetID(iRule), ...
        tRegistry.ExpectedSymbol(iRule),vAssetID,rMetaData);
    iPanel = iPanelIndex(tRegistry.Panel(iRule),cPanelName);
    iAnchor = find(dtDate == tRegistry.AnchorDateParsed(iRule));
    assert(isscalar(iAnchor), ...
        'Registry anchor date is absent or duplicated for %s', ...
        tRegistry.RuleID(iRule));
    dObserved = cBefore{iPanel}(iAnchor,iColumn);
    dExpected = tRegistry.ExpectedRawValue(iRule);
    assert(iRelativeEqual(dObserved,dExpected), ...
        'Raw anchor changed for event rule %s',tRegistry.RuleID(iRule));
end

cPanels = cBefore;
cTouched = cellfun(@(x)false(size(x)),cBefore,'UniformOutput',false);
tApplication = table(zeros(0,1),strings(0,1),strings(0,1), ...
    zeros(0,1),strings(0,1),strings(0,1),NaT(0,1),NaT(0,1),zeros(0,1), ...
    zeros(0,1), ...
    'VariableNames',{'Sequence','EventID','RuleID','AssetID','Operation','Panel', ...
    'StartDate','EndDate','Factor','ChangedFiniteCells'});

for iRule = 1:height(tRegistry)
    iColumn = iAssetColumn(tRegistry.AssetID(iRule), ...
        tRegistry.ExpectedSymbol(iRule),vAssetID,rMetaData);
    iPanel = iPanelIndex(tRegistry.Panel(iRule),cPanelName);
    lDate = dtDate >= tRegistry.StartDateParsed(iRule) & ...
        dtDate <= tRegistry.EndDateParsed(iRule);
    assert(any(lDate), 'Registry interval is outside the CMC calendar: %s', ...
        tRegistry.RuleID(iRule));
    vBefore = cPanels{iPanel}(lDate,iColumn);
    if tRegistry.Operation(iRule) == "multiply"
        cPanels{iPanel}(lDate,iColumn) = ...
            vBefore .* tRegistry.Factor(iRule);
    elseif tRegistry.Operation(iRule) == "mask_auxiliary_to_nan"
        assert(all(isfinite(vBefore)), ...
            'A registered mixed-unit auxiliary cell is already missing: %s', ...
            tRegistry.RuleID(iRule));
        cPanels{iPanel}(lDate,iColumn) = NaN;
    else
        error('Unsupported registry operation: %s', ...
            tRegistry.Operation(iRule));
    end
    cTouched{iPanel}(lDate,iColumn) = true;
    tApplication(end+1,:) = {tRegistry.Sequence(iRule), ...
        tRegistry.EventID(iRule),tRegistry.RuleID(iRule), ...
        tRegistry.AssetID(iRule),tRegistry.Operation(iRule), ...
        tRegistry.Panel(iRule), ...
        tRegistry.StartDateParsed(iRule),tRegistry.EndDateParsed(iRule), ...
        tRegistry.Factor(iRule),nnz(isfinite(vBefore))}; %#ok<AGROW>
end

for iPanel = 1:numel(cPanels)
    assert(isequaln(cBefore{iPanel}(~cTouched{iPanel}), ...
        cPanels{iPanel}(~cTouched{iPanel})), ...
        'Event adjustment changed an unregistered %s cell', ...
        cPanelName(iPanel));
    lCreatedMissing = ~isnan(cBefore{iPanel}) & isnan(cPanels{iPanel});
    lFilledMissing = isnan(cBefore{iPanel}) & ~isnan(cPanels{iPanel});
    lRegisteredMask = false(size(cBefore{iPanel}));
    lPanelMaskRules = lMaskOperation & ...
        tRegistry.Panel == cPanelName(iPanel);
    for iMaskRule = find(lPanelMaskRules)'
        iMaskColumn = iAssetColumn(tRegistry.AssetID(iMaskRule), ...
            tRegistry.ExpectedSymbol(iMaskRule),vAssetID,rMetaData);
        lMaskDate = dtDate >= tRegistry.StartDateParsed(iMaskRule) & ...
            dtDate <= tRegistry.EndDateParsed(iMaskRule);
        lRegisteredMask(lMaskDate,iMaskColumn) = true;
    end
    assert(~any(lFilledMissing,'all') && ...
        isequal(lCreatedMissing,lRegisteredMask), ...
        ['Only the exact registered mixed-unit auxiliary cells may become ' ...
         'missing; no missing value may be filled for %s'], ...
        cPanelName(iPanel));
end
assert(all(isnan(cPanels{4}) | ...
    (isfinite(cPanels{4}) & cPanels{4} > 0),'all'), ...
    'Event adjustment produced a nonpositive or infinite close');

[mOpen,mHigh,mLow,mClose,mME,mVolume] = cPanels{:};
lVolumeRegistry = tRegistry.Panel == "Volume";
if ~any(lVolumeRegistry)
    assert(isequaln(mVolume,cBefore{6}), ...
        'USD volume changed without a frozen field-level volume rule');
end

rAudit.sRegistryPath = sRegistry;
rAudit.sRegistrySHA256 = char(sRegistrySHA256);
rAudit.iRegistryRows = height(tRegistry);
rAudit.tRegistry = tRegistry;
rAudit.tPriceScaleRules = tRegistry(tRegistry.Operation == "multiply" & ...
    ismember(tRegistry.Panel,["Open","High","Low","Close"]),:);
rAudit.tAuxiliaryMaskRules = tRegistry(lMaskOperation,:);
rAudit.tMarketCapRules = tRegistry(tRegistry.Panel == "MarketCap",:);
rAudit.tApplication = tApplication;
rAudit.iNumPriceScaleRules = height(rAudit.tPriceScaleRules);
rAudit.iNumMarketCapCells = nnz(cTouched{5} & isfinite(cBefore{5}));
rAudit.iNumVolumeCellsChanged = nnz(cTouched{6} & isfinite(cBefore{6}));
rAudit.iNumAuxiliaryCellsMasked = nnz(lMaskOperation);
rAudit.iNumEconomicCloseCellsMasked = 0;
rAudit.vChangedFiniteCellsByPanel = cellfun(@(mask,before) ...
    nnz(mask & isfinite(before)),cTouched,cBefore);
end

function iColumn = iAssetColumn(iAssetID,sExpectedSymbol, ...
    vAssetID,rMetaData)
iColumn = find(vAssetID == iAssetID);
assert(isscalar(iColumn), ...
    'Event-registry asset ID %d is absent or duplicated',iAssetID);
sObserved = string(rMetaData.cSymbol(iColumn));
assert(isscalar(sObserved) && strcmpi(sObserved,sExpectedSymbol), ...
    'Event-registry UCID %d symbol changed from %s to %s', ...
    iAssetID,sExpectedSymbol,sObserved);
end

function iPanel = iPanelIndex(sPanel,cPanelName)
iPanel = find(cPanelName == sPanel);
assert(isscalar(iPanel),'Event-registry panel is absent or duplicated');
end

function lEqual = iRelativeEqual(dObserved,dExpected)
if isnan(dExpected)
    lEqual = isnan(dObserved);
    return
end
lEqual = isfinite(dObserved) && ...
    abs(dObserved-dExpected) <= ...
    max(1e-12,1e-10*max(abs(dObserved),abs(dExpected)));
end
