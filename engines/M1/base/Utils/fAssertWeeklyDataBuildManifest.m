function rManifest = fAssertWeeklyDataBuildManifest(sDataPath, ...
        sExpectedBuildID)
% Validate that the complete weekly-data bundle was committed together.

arguments
    sDataPath {mustBeTextScalar} = './DATA/'
    sExpectedBuildID {mustBeTextScalar} = ""
end

sDataPath = char(sDataPath);
sManifestFile = fullfile(sDataPath,'WeeklyDataBuildManifest.mat');
assert(isfile(sManifestFile), ...
    'Weekly-data bundle manifest is missing; rerun b01 and b02.');
rLoaded = load(sManifestFile,'rManifest');
assert(isfield(rLoaded,'rManifest') && isstruct(rLoaded.rManifest) && ...
    isscalar(rLoaded.rManifest),'Weekly-data bundle manifest is invalid.');
rManifest = rLoaded.rManifest;
cRequired = {'lComplete','sDataBuildID','sWeeklyCodeFingerprint', ...
    'sInputManifestSHA256','vDataSettings','cFiles','cSHA256','vBytes', ...
    'iNumWeeks','iNumAssets'};
assert(all(isfield(rManifest,cRequired)) && ...
       isequal(rManifest.lComplete,true), ...
    'Weekly-data bundle is not certified complete.');
assert(isempty(char(sExpectedBuildID)) || ...
       strcmp(char(rManifest.sDataBuildID),char(sExpectedBuildID)), ...
    'Weekly-data manifest build ID does not match the requested build.');
assert(numel(rManifest.cFiles) == numel(rManifest.cSHA256) && ...
       numel(rManifest.cFiles) == numel(rManifest.vBytes) && ...
       numel(rManifest.cFiles) == numel(rManifest.vDataSettings), ...
    'Weekly-data manifest arrays have inconsistent sizes.');

for iIdxF = 1:numel(rManifest.cFiles)
    sFile = fullfile(sDataPath,rManifest.cFiles{iIdxF});
    rInfo = dir(sFile);
    assert(isscalar(rInfo) && ...
           rInfo.bytes == rManifest.vBytes(iIdxF), ...
        'Weekly-data bundle member size changed: %s',sFile);
    assert(strcmp(fFileSHA256(sFile),rManifest.cSHA256{iIdxF}), ...
        'Weekly-data bundle member hash changed: %s',sFile);
end
end
