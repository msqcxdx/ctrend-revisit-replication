function fAssertWeeklyDataProvenance(sDataBuildID, rInputProvenance, ...
        sWeeklyCodeFingerprint, sCurrentCodeFingerprint)
% Reject weekly intermediates created before the corrected raw-input gate.

arguments
    sDataBuildID
    rInputProvenance
    sWeeklyCodeFingerprint
    sCurrentCodeFingerprint {mustBeTextScalar} = ""
end

assert((ischar(sDataBuildID) || ...
        (isstring(sDataBuildID) && isscalar(sDataBuildID))) && ...
       ~isempty(char(sDataBuildID)), ...
    'Weekly data lack a valid build ID; rerun b01 and b02.');
assert(isstruct(rInputProvenance) && isscalar(rInputProvenance) && ...
       isfield(rInputProvenance, 'lValidated') && ...
       isequal(rInputProvenance.lValidated, true) && ...
       isfield(rInputProvenance, 'sManifestSHA256'), ...
    ['Weekly data predate the corrected input-provenance gate. ' ...
     'Provide an unscreened input export and rerun b01 and b02.']);

sDigest = char(rInputProvenance.sManifestSHA256);
lArtificial = isfield(rInputProvenance, 'lArtificial') && ...
    isequal(rInputProvenance.lArtificial, true);
assert((lArtificial && strcmp(sDigest, 'ARTIFICIAL_DATA')) || ...
       (~lArtificial && numel(sDigest) == 64 && ...
        all(ismember(lower(sDigest), ['0':'9','a':'f']))), ...
    'Weekly input-provenance certificate is malformed; rerun b01 and b02.');

assert((ischar(sWeeklyCodeFingerprint) || ...
        (isstring(sWeeklyCodeFingerprint) && ...
         isscalar(sWeeklyCodeFingerprint))) && ...
       numel(char(sWeeklyCodeFingerprint)) == 64, ...
    'Weekly data lack a source fingerprint; rerun b01 and b02.');
if isempty(char(sCurrentCodeFingerprint))
    sCurrentCodeFingerprint = fPipelineCodeFingerprint(pwd);
end
assert(strcmp(char(sWeeklyCodeFingerprint), ...
              char(sCurrentCodeFingerprint)), ...
    ['Corrected source changed after weekly preprocessing. ' ...
     'Rerun b01 and b02 before using downstream steps.']);
end
