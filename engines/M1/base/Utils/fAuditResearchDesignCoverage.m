function rCoverage = fAuditResearchDesignCoverage( ...
        mYhat,mExpectedPrediction,vFactor5,vFactor3,lScheduled, ...
        lPotentialFactor5,lPotentialFactor3,lAccountingEligible5, ...
        lAccountingEligible3,rEstimatorSummary,dMinCoverageRatio)
% Audit b09 output against an output-independent expected support.
%
% A prediction week is complete only when every expected asset forecast is
% finite. A factor week passes either with a finite accounting-eligible
% return after the declared target-tradability screen, or with NaN when the
% remaining cross-section/leg-size/numerical prerequisites are not met.

arguments
    mYhat (:,:) {mustBeNumeric}
    mExpectedPrediction (:,:) {mustBeNumericOrLogical}
    vFactor5 (:,1) {mustBeNumeric}
    vFactor3 (:,1) {mustBeNumeric}
    lScheduled (:,1) {mustBeNumericOrLogical}
    lPotentialFactor5 (:,1) {mustBeNumericOrLogical}
    lPotentialFactor3 (:,1) {mustBeNumericOrLogical}
    lAccountingEligible5 (:,1) {mustBeNumericOrLogical}
    lAccountingEligible3 (:,1) {mustBeNumericOrLogical}
    rEstimatorSummary (1,1) struct
    dMinCoverageRatio (1,1) {mustBeNumeric,mustBeNonnegative}
end

lScheduled = logical(lScheduled(:));
mExpectedPrediction = logical(mExpectedPrediction);
assert(isequal(size(mExpectedPrediction),size(mYhat)), ...
    'Expected prediction support must match the asset-by-week output panel');
iNumObs = numel(lScheduled);
assert(size(mYhat,2) == iNumObs, ...
    'Coverage panels must share the complete weekly axis');

mFinitePrediction = isfinite(mYhat);
assert(~any(mFinitePrediction & ~mExpectedPrediction,'all'), ...
    'Finite prediction occurred outside ex-ante expected support');
vExpectedAssetCount = sum(mExpectedPrediction,1)';
vFiniteExpectedAssetCount = sum( ...
    mFinitePrediction & mExpectedPrediction,1)';
lPredictionEligible = lScheduled & vExpectedAssetCount > 0;
lPredictionComplete = lPredictionEligible & ...
    vFiniteExpectedAssetCount == vExpectedAssetCount;

lPotentialFactor5 = logical(lPotentialFactor5(:)) & lScheduled;
lPotentialFactor3 = logical(lPotentialFactor3(:)) & lScheduled;
lAccountingEligible5 = logical(lAccountingEligible5(:)) & lScheduled;
lAccountingEligible3 = logical(lAccountingEligible3(:)) & lScheduled;
lFiniteFactor5 = isfinite(vFactor5(:));
lFiniteFactor3 = isfinite(vFactor3(:));
assert(all([numel(lPotentialFactor5),numel(lPotentialFactor3), ...
    numel(lAccountingEligible5),numel(lAccountingEligible3), ...
    numel(lFiniteFactor5),numel(lFiniteFactor3)] == iNumObs), ...
    'Factor coverage vectors must share the complete weekly axis');
assert(~any(lAccountingEligible5 & ~lPotentialFactor5) && ...
       ~any(lAccountingEligible3 & ~lPotentialFactor3), ...
    ['Actual portfolio accounting eligibility cannot occur outside the ' ...
     'output-independent potential factor support']);
assert(~any(lFiniteFactor5 & ~lAccountingEligible5) && ...
       ~any(lFiniteFactor3 & ~lAccountingEligible3), ...
    ['A factor cannot be finite outside the declared post-tradability ' ...
     'accounting support']);

lFactorAuditPassed5 = lPotentialFactor5 & lPredictionComplete & ...
    ((lAccountingEligible5 & lFiniteFactor5) | ...
     (~lAccountingEligible5 & ~lFiniteFactor5));
lFactorAuditPassed3 = lPotentialFactor3 & lPredictionComplete & ...
    ((lAccountingEligible3 & lFiniteFactor3) | ...
     (~lAccountingEligible3 & ~lFiniteFactor3));

rCoverage = struct();
rCoverage.cStatusCodebook = { ...
    'not_scheduled','scheduled_not_eligible', ...
    'eligible_incomplete','eligible_complete'};
rCoverage.vPredictionWeekStatus = iStatusCodes( ...
    lScheduled,lPredictionEligible,lPredictionComplete);
rCoverage.vFactor5WeekStatus = iStatusCodes( ...
    lScheduled,lPotentialFactor5,lFactorAuditPassed5);
rCoverage.vFactor3WeekStatus = iStatusCodes( ...
    lScheduled,lPotentialFactor3,lFactorAuditPassed3);
rCoverage.vExpectedPredictionAssetCount = vExpectedAssetCount;
rCoverage.vFiniteExpectedPredictionAssetCount = ...
    vFiniteExpectedAssetCount;
rCoverage.rEstimatorSummary = rEstimatorSummary;
rCoverage.iScheduledWeeks = nnz(lScheduled);
rCoverage.iEligiblePredictionWeeks = nnz(lPredictionEligible);
rCoverage.iEstimatedWeeks = nnz(lPredictionComplete);
rCoverage.iFinitePredictionWeeks = nnz(lPredictionComplete);
rCoverage.iExpectedPredictionAssetWeeks = sum(vExpectedAssetCount);
rCoverage.iFinitePredictionAssetWeeks = sum(vFiniteExpectedAssetCount);
rCoverage.iEligibleFactorWeeks5 = nnz(lPotentialFactor5);
rCoverage.iEligibleFactorWeeks3 = nnz(lPotentialFactor3);
rCoverage.iFiniteFactorWeeks5 = nnz(lFiniteFactor5);
rCoverage.iFiniteFactorWeeks3 = nnz(lFiniteFactor3);
rCoverage.iFailedPredictionWeeks = ...
    nnz(lPredictionEligible & ~lPredictionComplete);
rCoverage.iFailedFactorWeeks5 = ...
    nnz(lPotentialFactor5 & ~lFactorAuditPassed5);
rCoverage.iFailedFactorWeeks3 = ...
    nnz(lPotentialFactor3 & ~lFactorAuditPassed3);
rCoverage.iUnexpectedFailureWeeks = ...
    rEstimatorSummary.iUnexpectedFailureWindows;
rCoverage.iEstimatorFailureWeeks = ...
    rEstimatorSummary.iExpectedFailureWindows;
rCoverage.dPredictionCoverageRatio = iCoverageRatio( ...
    rCoverage.iFinitePredictionWeeks, ...
    rCoverage.iEligiblePredictionWeeks);
rCoverage.dPredictionAssetCoverageRatio = iCoverageRatio( ...
    rCoverage.iFinitePredictionAssetWeeks, ...
    rCoverage.iExpectedPredictionAssetWeeks);
rCoverage.dFactorCoverageRatio5 = iCoverageRatio( ...
    nnz(lFactorAuditPassed5),rCoverage.iEligibleFactorWeeks5);
rCoverage.dFactorCoverageRatio3 = iCoverageRatio( ...
    nnz(lFactorAuditPassed3),rCoverage.iEligibleFactorWeeks3);
rCoverage.dMinCoverageRatio = dMinCoverageRatio;
rCoverage.lAccepted = rCoverage.iUnexpectedFailureWeeks == 0 && ...
    rCoverage.dPredictionCoverageRatio >= dMinCoverageRatio && ...
    rCoverage.dPredictionAssetCoverageRatio >= dMinCoverageRatio && ...
    rCoverage.dFactorCoverageRatio5 >= dMinCoverageRatio && ...
    rCoverage.dFactorCoverageRatio3 >= dMinCoverageRatio;
end

function vStatus = iStatusCodes(lScheduled,lEligible,lComplete)
vStatus = zeros(numel(lScheduled),1,'uint8');
vStatus(lScheduled) = 1;
vStatus(lEligible) = 2;
vStatus(lEligible & lComplete) = 3;
end

function dRatio = iCoverageRatio(iComplete,iEligible)
assert(iEligible > 0, ...
    'A completed applicable method must have at least one eligible unit');
dRatio = iComplete / iEligible;
end
