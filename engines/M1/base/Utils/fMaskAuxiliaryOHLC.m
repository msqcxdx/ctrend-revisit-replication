function [mOpen,mHigh,mLow,rDiagnostics] = ...
    fMaskAuxiliaryOHLC(lCoreAvailable,mClose,mOpen,mHigh,mLow, ...
    lPreserveDeclaredFill)
% One-way mask and internally validate auxiliary OHLC fields.
%
% Core availability is defined upstream from close, market cap, and volume.
% Missing open/high/low never deletes an otherwise valid core cell, but a
% core gap must not leave auxiliary quotes that bridge technical windows.

assert((islogical(lCoreAvailable) || isnumeric(lCoreAvailable)) && ...
    ismatrix(lCoreAvailable), 'Core availability must be a matrix');
assert(isequal(size(lCoreAvailable),size(mClose),size(mOpen), ...
    size(mHigh),size(mLow)), ...
    'Core availability, close, and all auxiliary OHLC fields must have equal size');
assert(islogical(lCoreAvailable) || ...
    (all(isfinite(lCoreAvailable),'all') && ...
     all(lCoreAvailable(:) == 0 | lCoreAvailable(:) == 1)), ...
    'Numeric core availability must contain only finite zero/one values');
lCoreAvailable = logical(lCoreAvailable);
if nargin < 6 || isempty(lPreserveDeclaredFill)
    lPreserveDeclaredFill = false(size(lCoreAvailable));
else
    assert((islogical(lPreserveDeclaredFill) || ...
            isnumeric(lPreserveDeclaredFill)) && ...
           isequal(size(lPreserveDeclaredFill),size(lCoreAvailable)), ...
        'Declared-fill mask must agree with the OHLC panel');
    lPreserveDeclaredFill = logical(lPreserveDeclaredFill);
end

mOpen(~isfinite(mOpen) | ~lCoreAvailable) = NaN;
mHigh(~isfinite(mHigh) | ~lCoreAvailable) = NaN;
mLow(~isfinite(mLow) | ~lCoreAvailable) = NaN;

% Close, market cap, and volume define the paper's core observation.  An
% impossible auxiliary quote must therefore invalidate only the auxiliary
% OHLC tuple, never close itself.  Check every observable pair so a missing
% third auxiliary field cannot hide a contradiction.
lInvalidRange = ...
    (isfinite(mHigh) & isfinite(mLow) & mHigh < mLow) | ...
    (isfinite(mHigh) & isfinite(mClose) & mHigh < mClose) | ...
    (isfinite(mHigh) & isfinite(mOpen) & mHigh < mOpen) | ...
    (isfinite(mLow) & isfinite(mClose) & mLow > mClose) | ...
    (isfinite(mLow) & isfinite(mOpen) & mLow > mOpen);
% The new 3x3 preprocessing contract explicitly fills a missing auxiliary
% quote with the prior close.  On a jump date that exact declared value can
% fall outside another observed field.  Preserve the declared fill rather
% than silently undoing it here; untouched contradictory candles retain the
% original corrected-pipeline fail-closed auxiliary mask.
lInvalidRange = lInvalidRange & ~lPreserveDeclaredFill;
mOpen(lInvalidRange) = NaN;
mHigh(lInvalidRange) = NaN;
mLow(lInvalidRange) = NaN;

rDiagnostics = struct();
rDiagnostics.iNumCoreAvailable = nnz(lCoreAvailable);
rDiagnostics.iNumInvalidAuxiliaryRanges = nnz(lInvalidRange);
rDiagnostics.iNumDeclaredFillRangeConflictsPreserved = nnz( ...
    lPreserveDeclaredFill & ...
    ((isfinite(mHigh) & isfinite(mLow) & mHigh < mLow) | ...
     (isfinite(mHigh) & isfinite(mClose) & mHigh < mClose) | ...
     (isfinite(mHigh) & isfinite(mOpen) & mHigh < mOpen) | ...
     (isfinite(mLow) & isfinite(mClose) & mLow > mClose) | ...
     (isfinite(mLow) & isfinite(mOpen) & mLow > mOpen)));
end
