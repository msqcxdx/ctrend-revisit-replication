function [lBalanced, vScheduledCoverage, vOverlap] = ...
        fTable6BalancedCellGate(vCommonN, vUnionN, vScheduledN, ...
        mCommonSharpe, dMinCoverage)
% Gate Table 6 comparisons on one identical design-cell support.
%
% A cell passes only when its exact common weeks cover enough of the complete
% scheduled OOS calendar, its intersection/union overlap is also adequate,
% and every compared Sharpe is defined. No missing statistic is imputed.

arguments
    vCommonN (:,1) {mustBeNumeric, mustBeNonnegative}
    vUnionN (:,1) {mustBeNumeric, mustBeNonnegative}
    vScheduledN (:,1) {mustBeNumeric, mustBePositive}
    mCommonSharpe (:,:) {mustBeNumeric}
    dMinCoverage (1,1) {mustBeNumeric, mustBeNonnegative}
end

iNumCells = numel(vCommonN);
assert(numel(vUnionN) == iNumCells && ...
       numel(vScheduledN) == iNumCells && ...
       size(mCommonSharpe,1) == iNumCells, ...
    'Table 6 support counts and Sharpe rows must identify the same cells');
assert(dMinCoverage <= 1, ...
    'Table 6 coverage threshold must lie in [0,1]');
assert(all(vCommonN == fix(vCommonN)) && ...
       all(vUnionN == fix(vUnionN)) && ...
       all(vScheduledN == fix(vScheduledN)) && ...
       all(vCommonN <= vUnionN) && ...
       all(vUnionN <= vScheduledN), ...
    ['Table 6 support must satisfy integer common N <= union N <= ' ...
     'scheduled N']);

vScheduledCoverage = vCommonN./vScheduledN;
vOverlap = NaN(iNumCells,1);
lPositiveUnion = vUnionN > 0;
vOverlap(lPositiveUnion) = ...
    vCommonN(lPositiveUnion)./vUnionN(lPositiveUnion);

lBalanced = ...
    vScheduledCoverage >= dMinCoverage & ...
    vOverlap >= dMinCoverage & ...
    all(isfinite(mCommonSharpe),2);
end
