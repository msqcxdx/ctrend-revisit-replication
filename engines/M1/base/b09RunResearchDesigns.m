function sPayloadSHA256 = fSaveTREND(sFilename,mYhat, vDates, vAssetID, cTrendNames, ...
        mTrend_5, mTrend_3, mLTW, sResearchDesignRunID, ...
        sCodeFingerprint, sDataBuildID, rKnownAlias, rMethodStatus, ...
        iSetting, rOutlierAuditStandard, rOutlierAuditValidation, ...
        rPredictorSupportAudit)
sPredictionSourceFingerprint = sCodeFingerprint;
% Publish a combo only after MATLAB has completed the whole serialization.
% A killed worker may leave the temporary file, but never a partially
% written canonical filename that a later resume could mistake for output.
sOutputDir = fileparts(sFilename);
if isempty(sOutputDir)
    sOutputDir = '.';
end
sTemporary = [tempname(sOutputDir),'.mat'];
save(sTemporary, 'mYhat','vDates','vAssetID','cTrendNames','mTrend_5', ...
    'mTrend_3', 'mLTW', 'sResearchDesignRunID', 'sCodeFingerprint', ...
    'sDataBuildID','sPredictionSourceFingerprint','rKnownAlias', ...
    'rMethodStatus','iSetting','rOutlierAuditStandard', ...
    'rOutlierAuditValidation','rPredictorSupportAudit');
[lMoved,sMoveMessage] = movefile(sTemporary,sFilename,'f');
assert(lMoved,'Could not publish combo %d atomically: %s', ...
    iSetting,sMoveMessage);
sPayloadSHA256 = fFileSHA256(sFilename);
sDigestFilename = [sFilename,'.sha256'];
sDigestTemporary = [tempname(sOutputDir),'.sha256'];
iDigestFile = fopen(sDigestTemporary,'w');
assert(iDigestFile >= 0, ...
    'Could not create payload digest for combo %d',iSetting);
rDigestCleanup = onCleanup(@() fclose(iDigestFile));
fprintf(iDigestFile,'%s  %s\n',sPayloadSHA256, ...
    [sprintf('CTREND_Combo%d.mat',iSetting)]);
clear rDigestCleanup
[lMoved,sMoveMessage] = movefile( ...
    sDigestTemporary,sDigestFilename,'f');
assert(lMoved,'Could not publish combo %d payload digest atomically: %s', ...
    iSetting,sMoveMessage);
end

function rManifest = iInitializeManifest(sFilename, sRunID, ...
        sCodeFingerprint, sDataBuildID, tCombos, cMethodNames, ...
        dMinCoverageRatio)
iNumCombos = height(tCombos);
if exist(sFilename, 'file') == 2
    rOld = load(sFilename, 'rRunManifest');
    if isfield(rOld, 'rRunManifest') && ...
            isfield(rOld.rRunManifest, 'sResearchDesignRunID') && ...
            strcmp(rOld.rRunManifest.sResearchDesignRunID, sRunID)
        rManifest = rOld.rRunManifest;
        assert(strcmp(rManifest.sCodeFingerprint, sCodeFingerprint), ...
            'Cannot resume run %s after corrected source code changed', sRunID);
        assert(strcmp(rManifest.sDataBuildID, sDataBuildID), ...
            'Cannot resume run %s with a different weekly data build', sRunID);
        assert(rManifest.iNumCombos == iNumCombos && ...
            numel(rManifest.lCompleted) == iNumCombos && ...
            isfield(rManifest, 'tCombos') && isequaln(rManifest.tCombos, tCombos), ...
            'Cannot resume run %s after DesignChoices changed', sRunID);
        assert(isfield(rManifest,'cMethodNames') && ...
            isequal(rManifest.cMethodNames(:)',cMethodNames(:)') && ...
            isequal(size(rManifest.mMethodCompleted), ...
                [iNumCombos,numel(cMethodNames)]), ...
            'Cannot resume run %s after the method manifest changed', sRunID);
        assert(isfield(rManifest,'dMinCoverageRatio') && ...
            rManifest.dMinCoverageRatio == dMinCoverageRatio, ...
            'Cannot resume run %s after the coverage gate changed',sRunID);
        assert(isfield(rManifest,'cPayloadSHA256') && ...
            isequal(size(rManifest.cPayloadSHA256),[iNumCombos,1]), ...
            'Cannot resume run %s from a manifest without payload digests', ...
            sRunID);
        return
    end
end

