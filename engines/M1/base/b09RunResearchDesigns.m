% Script for creating the trend characteristic (CTREND) and benchmark
% factors for various combinations of reseach designs
%
% Requires that b02CalculateIndicators.m was executed

% Clear console
clear; clc; close all;

% Set paths
sOldPath    = path;
sDataPath   = './DATA/';
addpath('./Utils/');

% Load design choices
load('DesignChoices.mat','tCombos');
iNumCombos      = size(tCombos,1);
cResearchMethods = {'FM','CFM','C_ENET_SCS','C_ENET_SCS_T', ...
    'POLS','CPOLS','C_ENET','C_ENET_SCS_VAL','C_ENET_SCS_VAL_T'};
% Operational completeness gate, not an estimation choice: a method must
% produce finite output on at least half of independently eligible weeks.
% Any thrown/unexpected estimator exception still aborts the run.
dMinCoverageRatio = 0.50;

% Optional range controls for explicit chunked runs. Every combo inside the
% requested range is recomputed and overwritten below. Existing
% result files are never treated as a cache because variable-name checks do
% not establish code, input-data, or DesignChoices provenance.
iComboStart = str2double(getenv('PIPELINE_COMBO_START'));
if isnan(iComboStart) || iComboStart < 1
    iComboStart = 1;
end
iComboEnd = str2double(getenv('PIPELINE_COMBO_END'));
if isnan(iComboEnd) || iComboEnd < 1
    iComboEnd = iNumCombos;
end
iComboStart = max(1, floor(iComboStart));
iComboEnd   = min(iNumCombos, floor(iComboEnd));
assert(iComboStart <= iComboEnd, 'Requested combo range is empty');
fprintf('combo_start=%i\n', iComboStart);
fprintf('combo_end=%i\n', iComboEnd);
fprintf('combo_recompute_all_in_range=1\n');

% Provenance for chunked or full research-design runs. A manifest is marked
% complete only after every combo carrying the same run, code, and data IDs
% has been written. Downstream Table 6 refuses stale or mixed files.
sCodeFingerprint = fPipelineCodeFingerprint(pwd);
rDataBuild = load([sDataPath, sprintf('bCharacteristicsOLHC_Combo%i.mat', ...
    tCombos.data_setting(1))], 'sDataBuildID', 'rInputProvenance', ...
    'sWeeklyCodeFingerprint');
assert(isfield(rDataBuild, 'sDataBuildID') && ...
       isfield(rDataBuild, 'rInputProvenance') && ...
       isfield(rDataBuild, 'sWeeklyCodeFingerprint'), ...
    'Weekly data lack corrected provenance; rerun b01 and b02');
fAssertWeeklyDataProvenance(rDataBuild.sDataBuildID, ...
    rDataBuild.rInputProvenance, rDataBuild.sWeeklyCodeFingerprint, ...
    sCodeFingerprint);
sDataBuildID = rDataBuild.sDataBuildID;
assert(strcmp(char(sDataBuildID), ...
    fGetCurrentWeeklyDataBuildID(sDataPath)), ...
    'Research-design inputs are not a certified complete weekly bundle');
sResearchDesignRunID = getenv('PIPELINE_RESEARCH_RUN_ID');
if isempty(sResearchDesignRunID)
    sResearchDesignRunID = char(java.util.UUID.randomUUID());
end
fprintf('research_design_run_id=%s\n', sResearchDesignRunID);
fprintf('data_build_id=%s\n', sDataBuildID);
fprintf('code_fingerprint=%s\n', sCodeFingerprint);

sManifestFile = './Results/CTREND/ResearchDesignRunManifest.mat';
rRunManifest = iInitializeManifest(sManifestFile, sResearchDesignRunID, ...
    sCodeFingerprint, sDataBuildID, tCombos, cResearchMethods, ...
    dMinCoverageRatio);
iSaveManifest(sManifestFile, rRunManifest);

% Load the large daily-event ledger once per MATLAB client, not once per
% research-design row.  Every weekly file below must carry the same sealed
% reference and asset/week axes.
sLedgerBootstrapFile = [sDataPath, sprintf( ...
    'bCharacteristicsOLHC_Combo%i.mat',tCombos.data_setting(1))];
rLedgerBootstrap = load(sLedgerBootstrapFile,'rData','rMetaData');
[rEconomicReinvestmentLedger,vLedgerWeekRowFull] = ...
    fLoadEconomicReinvestmentLedger(sDataPath, ...
    rLedgerBootstrap.rData.rEconomicReinvestmentLedgerReference, ...
    rLedgerBootstrap.rMetaData.vID(:), ...
    rLedgerBootstrap.rData.yrmoda(:));
sEconomicLedgerReferenceSHA256 = ...
    char(rLedgerBootstrap.rData.rEconomicReinvestmentLedgerReference.sSHA256);
clear rLedgerBootstrap

% Other settings that are no design choices
iMinNumAssets   = 5;  % Minimum assets in portfolios 
iMinNumObsCS    = 25; % Minimum cross-section
iStartDate      = 201416;       
iEndDate        = 202222; 
vQuantiles      = 0:0.2:1;

% Loop over data combinations
WaitBar = parfor_wait(iNumCombos,'WaitBar',false); % https://de.mathworks.com/matlabcentral/fileexchange/71083-waitbar-for-parfor
for iIdxC = 1:iNumCombos
    sFilename = sprintf('./Results/CTREND/CTREND_Combo%i.mat', tCombos.setting(iIdxC));
    if iIdxC < iComboStart || iIdxC > iComboEnd
        WaitBar.Send()
        continue
    end
    % Print progress
    fprintf(2, 'Estimate combo %i of %i\n', iIdxC, iNumCombos);

    % Extract setting
    lRoll               = tCombos.vRoll(iIdxC);
    lUseValueWeightedPortfolio = tCombos.vUseValueWts(iIdxC);
    iNumIn              = tCombos.vNumIn(iIdxC);
    dMinMCAP            = tCombos.vMinMCAP(iIdxC);
    dMinPrc             = tCombos.vMinPRC(iIdxC);
    lExclStable         = tCombos.vExclStable(iIdxC);
    iRetLead            = tCombos.vRetLead(iIdxC);
    lUseVolume          = tCombos.vUseVolume(iIdxC);
    sOutlierTreatment   = tCombos.cOutlierTreatment{iIdxC};
    dThreshold          = tCombos.vThreshold(iIdxC);
    iNumPorts           = length(vQuantiles);

    % All setting files contain the same raw-return panel. The outlier method
    % and threshold are fitted later, independently inside each OOS window.
    iIdxDataComb = tCombos.data_setting(iIdxC);
    [rData, rMetaData, rChars, sLoadedDataBuildID] = fLoadData( ...
        [sDataPath,sprintf('bCharacteristicsOLHC_Combo%i.mat', iIdxDataComb)], ...
        sCodeFingerprint);
    assert(strcmp(sLoadedDataBuildID, sDataBuildID), ...
        'Data-build IDs differ across weekly input files');

    % Extract data from struct
    mReturns        = rData.mReturns;
    mReturnsLead    = rData.mRetLead;
    assert(isfield(rData,'mPnlReturns') && isfield(rData,'mPnlRetLead'), ...
        ['Weekly input predates separated economic P&L; rerun b01ReadData ' ...
         'and b02CalculateIndicators.']);
    mPnlReturns     = rData.mPnlReturns;
    mPnlRetLead     = rData.mPnlRetLead;
    mME             = rData.mME;
    mPrices         = rData.mClose;
    mVolume         = rData.mVolume;
    vDates          = rData.yrmoda;
    vMktRet         = rData.vMktRet;
    vRiskFree       = rData.vRiskFree;
    vAssetID        = rMetaData.vID;
    assert(strcmp(char(rData.rEconomicReinvestmentLedgerReference.sSHA256), ...
        sEconomicLedgerReferenceSHA256) && ...
        isequal(double(rEconomicReinvestmentLedger.vAssetID(:)), ...
        double(vAssetID(:))), ...
        'Research-design rows do not share one economic ledger');
    mMOM3           = [NaN(1, size(rChars.ret_3_0,2)); rChars.ret_3_0(1:end-1,:)]; % Used for CMOM

    % Define technical indicators
    if lUseVolume
        cTechnicalIndicators = [cellfun(@(x)['sma_',x,'d'],sprintfc('%i',[3,5,10,20,50,100,200]),'un',false),...
            {'macd', 'macd_diff_signal'},...
            cellfun(@(x)['volsma_',x,'d'],sprintfc('%i',[3,5,10,20,50,100,200]),'un',false),...
            {'volmacd', 'volmacd_diff_signal'},{'rsi', 'stochRSI', 'stochK', 'stochD'}...
            {'boll_low','boll_mid','boll_high','boll_width', 'cci','chaikin'}]';
    else
        cTechnicalIndicators = [cellfun(@(x)['sma_',x,'d'],sprintfc('%i',[3,5,10,20,50,100,200]),'un',false),...
            {'macd', 'macd_diff_signal','rsi', 'stochRSI', 'stochK', 'stochD'}...
            {'boll_low','boll_mid','boll_high','boll_width', 'cci'}]';
    end

    % Determine dimensions
    [iNumObs, iNumAssets]   = size(mReturns);
    iNumChars               = length(cTechnicalIndicators);

    % Lag characteristics and convert to matrix
    mChars_L1 = NaN(iNumAssets, iNumObs, iNumChars);
    parfor iIdxChar = 1:iNumChars
        mChars_L1(:,:,iIdxChar) = [NaN(1, iNumAssets); rChars.(cTechnicalIndicators{iIdxChar})(1:end-1,:)]';
    end

    % Signals are always observed at the preceding weekly boundary. For the
    % lag-1 robustness design, however, portfolio filters and VW weights must
    % use the actual construction day t rather than the signal day t-1.
    mME_Signal_L1 = [NaN(1, iNumAssets); mME(1:end-1,:)];
    if iRetLead == 1
        assert(isfield(rData,'mMEFormationDay') && ...
            isfield(rData,'mCloseFormationDay'), ...
            ['Weekly input predates construction-day snapshots; rerun ' ...
             'b02CalculateIndicators.']);
        mME_L1 = rData.mMEFormationDay;
        mPrices_L1 = rData.mCloseFormationDay;
    else
        mME_L1 = mME_Signal_L1;
        mPrices_L1 = [NaN(1, iNumAssets); mPrices(1:end-1,:)];
    end

    % Restrict to sample period
    lIsSample                   = vDates >= iStartDate & vDates <= iEndDate;
    mReturns(~lIsSample,:)      = [];
    mReturnsLead(~lIsSample,:)  = [];
    mPnlReturns(~lIsSample,:)   = [];
    mPnlRetLead(~lIsSample,:)   = [];
    mVolume(~lIsSample,:)       = [];
    mME_L1(~lIsSample,:)        = [];
    mME_Signal_L1(~lIsSample,:) = [];
    mPrices_L1(~lIsSample,:)    = [];
    mME(~lIsSample,:)           = [];
    mChars_L1(:,~lIsSample,:)   = [];
    vDates(~lIsSample)          = [];
    vMktRet(~lIsSample)         = [];
    vRiskFree(~lIsSample)       = [];
    mMOM3(~lIsSample,:)         = [];
    iNumObs                     = length(vDates);
    vLedgerWeekRow = vLedgerWeekRowFull(lIsSample);

    % Apply formation-time filters using lagged market cap and price
    lRemoveObs                  = ~isfinite(mME_L1) | ~isfinite(mPrices_L1) | ...
                                  (mME_L1 == 0) | (mME_L1 < dMinMCAP) | (mPrices_L1 < dMinPrc);
    if lExclStable
        lRemoveObs              = lRemoveObs | rMetaData.lIsStable;
    end
    mReturns(lRemoveObs)        = NaN;
    mReturnsLead(lRemoveObs)    = NaN;
    mME_L1(lRemoveObs)          = NaN;
    mME_Signal_L1(lRemoveObs)   = NaN;

    % Return outlier cutoffs are a sample-definition choice, not a model
    % availability choice.  Preserve all formation-eligible returns here,
    % before the joint technical-indicator mask below.
    lOutlierFit = isfinite(mReturns);
    [vOutlierFitTime,vOutlierFitAsset] = find(lOutlierFit);
    vOutlierFitY = mReturns(lOutlierFit);
    mOutlierFitID = [vOutlierFitTime,vOutlierFitAsset];
    cOutlierReferenceArgs = {'vOutlierFitY',vOutlierFitY, ...
        'mOutlierFitID',mOutlierFitID};
    rOutlierAuditStandard = fBuildHistoricalWeeklyOutlierAudit( ...
        vOutlierFitY,mOutlierFitID,(1:iNumObs)',iNumIn,lRoll,0, ...
        sOutlierTreatment,dThreshold);
    rOutlierAuditValidation = fBuildHistoricalWeeklyOutlierAudit( ...
        vOutlierFitY,mOutlierFitID,(1:iNumObs)',iNumIn,lRoll,12, ...
        sOutlierTreatment,dThreshold);

    % Select the raw, untransformed economic payoff matching the
    % implementation timing. Statistical labels above remain the strict
    % core-return panel and are the only returns used to fit outlier rules.
    if iRetLead == 1
        % 1-day implementation lag
        mPnlSort = mPnlRetLead;
        sPayoffTiming = 'lead1';
    else
        % No implementation lag
        mPnlSort = mPnlReturns;
        sPayoffTiming = 'ordinary';
    end

    % Create LTW factors
    % CSMB uses 30% and 70% breakpoints: univariate sorts. L-H portfolios
    [vCSMB_EW, vCSMB] = fSingleSortFast(-mME_Signal_L1', ...
            mPnlSort', mME_L1',...
            'vPercentile',[0, 0.3, 0.7, 1],...
            'iMinNumCS', iMinNumObsCS,...
            'iMinNumAssets',iMinNumAssets, ...
            'rReinvestmentLedger',rEconomicReinvestmentLedger, ...
            'vLedgerWeekRow',vLedgerWeekRow, ...
            'sPayoffTiming',sPayoffTiming);

    % CMOM uses dependent sorts: First split into small and big
    % cryptocurrencies and then use 30% and 70% breakpoints
    rResultsCMOM = fDepDoubleSort(mME_Signal_L1', mMOM3', ...
        mPnlSort', [], mME_L1', 'vPercentileA',0:0.5:1, ...
        'vPercentileB', [0, 0.3, 0.7, 1], ...
        'rReinvestmentLedger',rEconomicReinvestmentLedger, ...
        'vLedgerWeekRow',vLedgerWeekRow, ...
        'sPayoffTiming',sPayoffTiming);
    vCMOM = 0.5 * (rResultsCMOM.VW.cPortRets{1,end-1} + ...  % Small high
        rResultsCMOM.VW.cPortRets{2,end-1}) - ...             % Bigh high
        0.5 * (rResultsCMOM.VW.cPortRets{1,1} + ...           % Small low
        rResultsCMOM.VW.cPortRets{2,1});                      % Big low
    vCMOM_EW = 0.5 * (rResultsCMOM.EW.cPortRets{1,end-1} + ...  % Small high
        rResultsCMOM.EW.cPortRets{2,end-1}) - ...             % Bigh high
        0.5 * (rResultsCMOM.EW.cPortRets{1,1} + ...           % Small low
        rResultsCMOM.EW.cPortRets{2,1});                      % Big low

    % Merge
    mLTW    = [vCSMB, vCMOM'];
    mLTW_EW = [vCSMB_EW, vCMOM_EW'];

    % Rank every predictor on its own ex-ante support.  Equations (7)-(8)
    % are univariate by j, so another predictor's missingness cannot change
    % j's percentile or its regression sample.  Joint complete cases are
    % imposed later only by estimators that are genuinely multivariate or
    % by the equation-(10) forecast-selection regression.
    lFormationEligible = isfinite(mME_L1');
    [mCharsUse,mRawPredictorObserved] = ...
        fRankPredictorsOwnSupport(mChars_L1,lFormationEligible);
    rPredictorSupportAudit = struct();
    rPredictorSupportAudit.vObservedByPredictor = ...
        reshape(sum(mRawPredictorObserved,[1,2]),1,[]);
    rPredictorSupportAudit.iUnionRows = ...
        nnz(any(mRawPredictorObserved,3));
    rPredictorSupportAudit.iJointRows = ...
        nnz(all(mRawPredictorObserved,3));
    rPredictorSupportAudit.sRankRule = ...
        ['Predictor-specific formation support before estimator-specific ' ...
         'complete-case restrictions'];

    % Define methods
    cTrendNames = cResearchMethods;
    iNumTrend   = length(cTrendNames);

    % Initialize memory
    mTrend      = NaN(iNumObs, iNumTrend);
    mAvgRet     = NaN(iNumPorts, iNumTrend);

    % Equation (4) uses market-cap WLS for every design.  The
    % vUseValueWts design choice is exclusively an EW/VW factor-portfolio
    % choice below; it must not silently change the fitted predictor.
    mWts_L1 = (mME_L1 ./ sum(mME_L1,2,'omitmissing'))';

    % Every estimator cleans each already-realized training/validation week
    % on that week's formation-eligible return cross-section. Raw rather
    % than excess returns are passed because subsequent within-week
    % demeaning exactly cancels the common risk-free rate.
    mRet = mReturns;
    
    % To panel matrix
    [mC, vY, mID, vW] = fCreatePanelExAnte( ...
        mCharsUse,mRet',mWts_L1,'lKeepPredictorUnion',true);
    [mCUnpenalized,~,rKnownAlias] = ...
        fReduceKnownUnpenalizedAliases(mC,cTechnicalIndicators);
    iNumPanelObs    = length(vY);
    vAssetNum       = 1:iNumAssets;
    vTimeID         = 1:iNumObs;
    vEvaluationY    = mPnlSort(sub2ind(size(mPnlSort), mID(:,1), mID(:,2)));
    vPnlRawOOS      = fBuildRawOOSPanelOutcome( ...
        vEvaluationY,mID,vTimeID(:),iNumIn);
    mPnlOOS         = fPanel2Matrix(vPnlRawOOS,mID(:,2),mID(:,1), ...
        vAssetNum,vTimeID);
    lScheduledWeek = false(iNumObs,1);
    lScheduledWeek(iNumIn+1:end) = true;

    % Initialize memory
    mYhat       = NaN(iNumAssets, iNumObs, iNumTrend);
    mTrendEW_5  = NaN(iNumObs, iNumTrend); % Quintile, equal-weighted
    mTrendVW_5  = NaN(iNumObs, iNumTrend); % Quintile, value-weighted
    mTrendEW_3  = NaN(iNumObs, iNumTrend); % Tertile, equal-weighted
    mTrendVW_3  = NaN(iNumObs, iNumTrend); % Tertile, value-weighted
    rMethodStatus = iEmptyMethodStatus(cTrendNames);
    iSetting = tCombos.setting(iIdxC);
    rRunManifest.lCompleted(iSetting) = false;
    rRunManifest.mMethodCompleted(iSetting,:) = false;
    rRunManifest.mFinitePredictionWeeks(iSetting,:) = NaN;
    rRunManifest.mFiniteFactorWeeks5(iSetting,:) = NaN;
    rRunManifest.mFiniteFactorWeeks3(iSetting,:) = NaN;
    rRunManifest.mScheduledWeeks(iSetting,:) = NaN;
    rRunManifest.mEligiblePredictionWeeks(iSetting,:) = NaN;
    rRunManifest.mEstimatedWeeks(iSetting,:) = NaN;
    rRunManifest.mEligibleFactorWeeks5(iSetting,:) = NaN;
    rRunManifest.mEligibleFactorWeeks3(iSetting,:) = NaN;
    rRunManifest.mFailedPredictionWeeks(iSetting,:) = NaN;
    rRunManifest.mFailedFactorWeeks5(iSetting,:) = NaN;
    rRunManifest.mFailedFactorWeeks3(iSetting,:) = NaN;
    rRunManifest.mUnexpectedFailureWeeks(iSetting,:) = NaN;
    rRunManifest.mEstimatorFailureWeeks(iSetting,:) = NaN;
    rRunManifest.mExpectedPredictionAssetWeeks(iSetting,:) = NaN;
    rRunManifest.mFinitePredictionAssetWeeks(iSetting,:) = NaN;
    rRunManifest.mPredictionCoverageRatio(iSetting,:) = NaN;
    rRunManifest.mPredictionAssetCoverageRatio(iSetting,:) = NaN;
    rRunManifest.mFactorCoverageRatio5(iSetting,:) = NaN;
    rRunManifest.mFactorCoverageRatio3(iSetting,:) = NaN;
    rRunManifest.cPayloadSHA256{iSetting} = '';
    rRunManifest.cMethodFailureIdentifier(iSetting,:) = {''};
    rRunManifest.cMethodFailureMessage(iSetting,:) = {''};

    % Loop over methods
    for iIdxM = 1:iNumTrend
        % Copy characteristics
        mCtemp = mC;
        rEstimatorAudit = struct();
        try

        switch upper(cTrendNames{iIdxM})
            case 'FM'
                % Multivariate FM uses joint complete cases.  The walk-
                % forward estimator applies that restriction inside each
                % training/OOS window; never impute a missing rank as zero.
                mCtemp = mCUnpenalized;

                % Estimate Fama-MacBeth
                [vYhatTemp, ~] = ...
                    fWalkforwardFamaMacBethPanel(vY, mCtemp, mID, vW,...
                    'lEstAlpha',true,...
                    'iNumIn',iNumIn,...
                    'lRoll',lRoll,...
                    'vAllTimeID',vTimeID(:),...
                    'sOutlierTreatment',sOutlierTreatment,...
                    'dOutlierThreshold',dThreshold,...
                    'lDemeanY',true,...
                    'vEvaluationY',vEvaluationY,...
                    cOutlierReferenceArgs{:});

            case 'CFM'
                % Estimate Combined Fama-MacBeth

                % Initialize memory
                mYhatTemp = NaN(length(vY), iNumChars);
                for iIdxV = 1:iNumChars
                    [mYhatTemp(:,iIdxV), ~] = ...
                        fWalkforwardFamaMacBethPanel(vY, mCtemp(:,iIdxV), mID, vW,...
                    'lEstAlpha',true,...
                    'iNumIn',iNumIn,...
                    'lRoll',lRoll,...
                    'vAllTimeID',vTimeID(:),...
                    'sOutlierTreatment',sOutlierTreatment,...
                    'dOutlierThreshold',dThreshold,...
                    'lDemeanY',true,...
                    'vEvaluationY',vEvaluationY,...
                    cOutlierReferenceArgs{:});
                end
                % Equation (9): fixed 1/J over all univariate forecasts.
                % An unavailable component makes that observation's
                % combined forecast undefined; do not use dynamic 1/J_t.
                vYhatTemp = fMeanForecastsFixedSet(mYhatTemp);

            case 'C_ENET_SCS'
                % Estimate CS-E-Net
                [vYhatTemp, ~, ~, ~, ~, ~, rEstimatorAudit] = ...
                    fWalkforwardCSENET(vY, mCtemp, mID, vW,...
                    "dAlpha",0.5,...
                    "iNumIn",iNumIn,...
                    "lRoll",lRoll,...
                    "vAllTimeID",vTimeID(:),...
                    "lEstAlpha",true,...
                    "sOutlierTreatment",sOutlierTreatment,...
                    "dOutlierThreshold",dThreshold,...
                    "lDemeanY",true,...
                    "vEvaluationY",vEvaluationY,...
                    cOutlierReferenceArgs{:});
            case 'C_ENET_SCS_T'
                % Estimate theta-weighted CS-E-Net independently, so method
                % order does not affect the research-design grid.
                [~, ~, ~, vYhatTemp, ~, ~, rEstimatorAudit] = ...
                    fWalkforwardCSENET(vY, mCtemp, mID, vW,...
                    "dAlpha",0.5,...
                    "iNumIn",iNumIn,...
                    "lRoll",lRoll,...
                    "vAllTimeID",vTimeID(:),...
                    "lEstAlpha",true,...
                    "sOutlierTreatment",sOutlierTreatment,...
                    "dOutlierThreshold",dThreshold,...
                    "lDemeanY",true,...
                    "vEvaluationY",vEvaluationY,...
                    cOutlierReferenceArgs{:});

            case 'POLS' 
                % Pooled OLS
                % As with multivariate FM, preserve NaNs so the estimator
                % uses genuine joint complete cases rather than neutral-rank
                % imputation.
                mCtemp = mCUnpenalized;

                % Estimation
                [vYhatTemp, ~] = ...
                    fWalkforwardPanelRegression(vY, mCtemp, mID, vW,...
                    'lEstAlpha',true,...
                    'iNumIn',iNumIn,...
                    'lRoll',lRoll,...
                    'vAllTimeID',vTimeID(:),...
                    'sOutlierTreatment',sOutlierTreatment,...
                    'dOutlierThreshold',dThreshold,...
                    'lDemeanY',true,...
                    'vEvaluationY',vEvaluationY,...
                    cOutlierReferenceArgs{:});

            case 'CPOLS' 
                % Combined Pooled OLS

                % Initialize memory
                mYhatTemp = NaN(length(vY), iNumChars);
                for iIdxV = 1:iNumChars
                    [mYhatTemp(:,iIdxV), ~] = ...
                        fWalkforwardPanelRegression(vY, mCtemp(:,iIdxV), mID, vW,...
                    'lEstAlpha',true,...
                    'iNumIn',iNumIn,...
                    'lRoll',lRoll,...
                    'vAllTimeID',vTimeID(:),...
                    'sOutlierTreatment',sOutlierTreatment,...
                    'dOutlierThreshold',dThreshold,...
                    'lDemeanY',true,...
                    'vEvaluationY',vEvaluationY,...
                    cOutlierReferenceArgs{:});
                end

                % Equation (9): fixed 1/J over all univariate forecasts.
                vYhatTemp = fMeanForecastsFixedSet(mYhatTemp);

            case 'C_ENET'
                % Estimate C-E-Net (3rd output is theta-weighted forecast
                [vYhatTemp, ~, ~, ~, ~, rEstimatorAudit] = ...
                    fWalkforwardCENET(vY, mCtemp, mID, vW,...
                    "dAlpha",0.5,...
                    "iNumIn",iNumIn,...
                    "lRoll",lRoll,...
                    "vAllTimeID",vTimeID(:),...
                    "lEstAlpha",true,...
                    "sOutlierTreatment",sOutlierTreatment,...
                    "dOutlierThreshold",dThreshold,...
                    "lDemeanY",true,...
                    "vEvaluationY",vEvaluationY,...
                    cOutlierReferenceArgs{:});

            case 'C_ENET_SCS_VAL'
                % Estimate CS-E-Net with validation sample
                [vYhatTemp, ~, ~, ~, ~, ~, rEstimatorAudit] = ...
                    fWalkforwardCSENET(vY, mCtemp, mID, vW,...
                    "dAlpha",0.5,...
                    "iNumIn",iNumIn,...
                    "lRoll",lRoll,...
                    "vAllTimeID",vTimeID(:),...
                    "lEstAlpha",true,...
                    "iNumVal",12,...
                    "lReest",false,...
                    "sOutlierTreatment",sOutlierTreatment,...
                    "dOutlierThreshold",dThreshold,...
                    "lDemeanY",true,...
                    "vEvaluationY",vEvaluationY,...
                    cOutlierReferenceArgs{:});
                    
            case 'C_ENET_SCS_VAL_T'
                % Estimate theta-weighted validation CS-E-Net independently.
                [~, ~, ~, vYhatTemp, ~, ~, rEstimatorAudit] = ...
                    fWalkforwardCSENET(vY, mCtemp, mID, vW,...
                    "dAlpha",0.5,...
                    "iNumIn",iNumIn,...
                    "lRoll",lRoll,...
                    "vAllTimeID",vTimeID(:),...
                    "lEstAlpha",true,...
                    "iNumVal",12,...
                    "lReest",false,...
                    "sOutlierTreatment",sOutlierTreatment,...
                    "dOutlierThreshold",dThreshold,...
                    "lDemeanY",true,...
                    "vEvaluationY",vEvaluationY,...
                    cOutlierReferenceArgs{:});

            otherwise
                error('Unknown method');
        end

        % Define expected forecast support before inspecting the numeric
        % method output. Multivariate/all-component methods require their
        % complete current input vector. ENet methods expose the exact
        % fixed-selected-set support and use potential union rows when
        % selection is empty or statistically unidentified, so a failure
        % cannot shrink its own denominator.
        if isfield(rEstimatorAudit,'lExpectedPanel')
            vExpectedPanel = logical(rEstimatorAudit.lExpectedPanel);
            assert(numel(vExpectedPanel) == numel(vY), ...
                'Estimator expected-support audit has the wrong panel size');
        else
            vExpectedPanel = all(isfinite(mCtemp),2) & ...
                mID(:,1) > iNumIn;
        end
        mExpectedPrediction = false(iNumAssets,iNumObs);
        mExpectedPrediction(sub2ind([iNumAssets,iNumObs], ...
            mID(:,2),mID(:,1))) = vExpectedPanel;
        rEstimatorSummary = ...
            fSummarizeResearchDesignEstimatorAudit(rEstimatorAudit);

        % Make panel to matrix.
        mYhat(:,:,iIdxM) = fPanel2Matrix(vYhatTemp, mID(:,2), ...
            mID(:,1), vAssetNum, vTimeID);
        % Sorts use genuine raw realized OOS returns.  Outlier preprocessing
        % is confined to statistical labels and never caps/deletes P&L.
        [mTrendEW_5(:,iIdxM), mTrendVW_5(:,iIdxM), rSortCoverage5] = ...
            fSingleSortFast(mYhat(:,:,iIdxM), mPnlOOS, mME_L1',...
            'vPercentile',0:0.2:1,...
            'iMinNumCS', iMinNumObsCS,...
            'iMinNumAssets',iMinNumAssets, ...
            'rReinvestmentLedger',rEconomicReinvestmentLedger, ...
            'vLedgerWeekRow',vLedgerWeekRow, ...
            'sPayoffTiming',sPayoffTiming);
        [mTrendEW_3(:,iIdxM), mTrendVW_3(:,iIdxM), rSortCoverage3] = ...
            fSingleSortFast(mYhat(:,:,iIdxM), mPnlOOS, mME_L1',...
            'vPercentile',[0,0.3,0.7,1],...
            'iMinNumCS', iMinNumObsCS,...
            'iMinNumAssets',iMinNumAssets, ...
            'rReinvestmentLedger',rEconomicReinvestmentLedger, ...
            'vLedgerWeekRow',vLedgerWeekRow, ...
            'sPayoffTiming',sPayoffTiming);

        if lUseValueWeightedPortfolio
            vFactor5 = mTrendVW_5(:,iIdxM);
            vFactor3 = mTrendVW_3(:,iIdxM);
            lFactorEligible5 = rSortCoverage5.lVWAccountingEligible;
            lFactorEligible3 = rSortCoverage3.lVWAccountingEligible;
        else
            vFactor5 = mTrendEW_5(:,iIdxM);
            vFactor3 = mTrendEW_3(:,iIdxM);
            lFactorEligible5 = rSortCoverage5.lEWAccountingEligible;
            lFactorEligible3 = rSortCoverage3.lEWAccountingEligible;
        end
        lPotentialFactor5 = fPotentialResearchDesignFactorWeeks( ...
            mExpectedPrediction,0:0.2:1,iMinNumObsCS, ...
            iMinNumAssets,lScheduledWeek);
        lPotentialFactor3 = fPotentialResearchDesignFactorWeeks( ...
            mExpectedPrediction,[0,0.3,0.7,1],iMinNumObsCS, ...
            iMinNumAssets,lScheduledWeek);
        rCoverage = fAuditResearchDesignCoverage(mYhat(:,:,iIdxM), ...
            mExpectedPrediction,vFactor5,vFactor3,lScheduledWeek, ...
            lPotentialFactor5,lPotentialFactor3,lFactorEligible5, ...
            lFactorEligible3,rEstimatorSummary,dMinCoverageRatio);
        rMethodStatus.lCompleted(iIdxM) = rCoverage.lAccepted;
        rMethodStatus.vFinitePredictionWeeks(iIdxM) = ...
            rCoverage.iFinitePredictionWeeks;
        rMethodStatus.vFiniteFactorWeeks5(iIdxM) = ...
            rCoverage.iFiniteFactorWeeks5;
        rMethodStatus.vFiniteFactorWeeks3(iIdxM) = ...
            rCoverage.iFiniteFactorWeeks3;
        rMethodStatus.vScheduledWeeks(iIdxM) = rCoverage.iScheduledWeeks;
        rMethodStatus.vEligiblePredictionWeeks(iIdxM) = ...
            rCoverage.iEligiblePredictionWeeks;
        rMethodStatus.vEstimatedWeeks(iIdxM) = rCoverage.iEstimatedWeeks;
        rMethodStatus.vEligibleFactorWeeks5(iIdxM) = ...
            rCoverage.iEligibleFactorWeeks5;
        rMethodStatus.vEligibleFactorWeeks3(iIdxM) = ...
            rCoverage.iEligibleFactorWeeks3;
        rMethodStatus.vFailedPredictionWeeks(iIdxM) = ...
            rCoverage.iFailedPredictionWeeks;
        rMethodStatus.vFailedFactorWeeks5(iIdxM) = ...
            rCoverage.iFailedFactorWeeks5;
        rMethodStatus.vFailedFactorWeeks3(iIdxM) = ...
            rCoverage.iFailedFactorWeeks3;
        rMethodStatus.vUnexpectedFailureWeeks(iIdxM) = ...
            rCoverage.iUnexpectedFailureWeeks;
        rMethodStatus.vEstimatorFailureWeeks(iIdxM) = ...
            rCoverage.iEstimatorFailureWeeks;
        rMethodStatus.vExpectedPredictionAssetWeeks(iIdxM) = ...
            rCoverage.iExpectedPredictionAssetWeeks;
        rMethodStatus.vFinitePredictionAssetWeeks(iIdxM) = ...
            rCoverage.iFinitePredictionAssetWeeks;
        rMethodStatus.vPredictionCoverageRatio(iIdxM) = ...
            rCoverage.dPredictionCoverageRatio;
        rMethodStatus.vPredictionAssetCoverageRatio(iIdxM) = ...
            rCoverage.dPredictionAssetCoverageRatio;
        rMethodStatus.vFactorCoverageRatio5(iIdxM) = ...
            rCoverage.dFactorCoverageRatio5;
        rMethodStatus.vFactorCoverageRatio3(iIdxM) = ...
            rCoverage.dFactorCoverageRatio3;
        rMethodStatus.cCoverage{iIdxM} = rCoverage;
        fprintf(['coverage combo=%i method=%s scheduled=%i ' ...
            'eligible_prediction=%i finite_prediction=%i ' ...
            'prediction_ratio=%.6f prediction_asset_ratio=%.6f ' ...
            'eligible_factor5=%i ' ...
            'finite_factor5=%i factor5_ratio=%.6f ' ...
            'eligible_factor3=%i finite_factor3=%i ' ...
            'factor3_ratio=%.6f unexpected=%i accepted=%i\n'], ...
            iSetting,cTrendNames{iIdxM},rCoverage.iScheduledWeeks, ...
            rCoverage.iEligiblePredictionWeeks, ...
            rCoverage.iFinitePredictionWeeks, ...
            rCoverage.dPredictionCoverageRatio, ...
            rCoverage.dPredictionAssetCoverageRatio, ...
            rCoverage.iEligibleFactorWeeks5, ...
            rCoverage.iFiniteFactorWeeks5, ...
            rCoverage.dFactorCoverageRatio5, ...
            rCoverage.iEligibleFactorWeeks3, ...
            rCoverage.iFiniteFactorWeeks3, ...
            rCoverage.dFactorCoverageRatio3, ...
            rCoverage.iUnexpectedFailureWeeks,rCoverage.lAccepted);
        catch ME
            rMethodStatus.cFailureIdentifier{iIdxM} = ME.identifier;
            rMethodStatus.cFailureMessage{iIdxM} = ME.message;
            rRunManifest = iStoreMethodStatus( ...
                rRunManifest, iSetting, rMethodStatus);
            rRunManifest.sUpdatedAt = char(datetime('now', ...
                'Format','yyyy-MM-dd''T''HH:mm:ss'));
            iSaveManifest(sManifestFile, rRunManifest);
            rethrow(ME)
        end
    end

    % Persist method-level coverage even when the acceptance gate below
    % rejects this combo. A failed audit must remain diagnosable.
    rRunManifest = iStoreMethodStatus(rRunManifest,iSetting,rMethodStatus);
    rRunManifest.sUpdatedAt = char(datetime('now', ...
        'Format','yyyy-MM-dd''T''HH:mm:ss'));
    iSaveManifest(sManifestFile,rRunManifest);
    assert(all(rMethodStatus.lCompleted) && ...
        all(rMethodStatus.vUnexpectedFailureWeeks == 0) && ...
        all(rMethodStatus.vPredictionCoverageRatio >= dMinCoverageRatio) && ...
        all(rMethodStatus.vPredictionAssetCoverageRatio >= ...
            dMinCoverageRatio) && ...
        all(rMethodStatus.vFactorCoverageRatio5 >= dMinCoverageRatio) && ...
        all(rMethodStatus.vFactorCoverageRatio3 >= dMinCoverageRatio), ...
        ['Every applicable method must meet the declared eligible-week ' ...
         'coverage floor with no unexpected failure']);

    % Save results
    if lUseValueWeightedPortfolio
        sPayloadSHA256 = fSaveTREND(sFilename, mYhat, vDates, ...
            vAssetID, cTrendNames, ...
            mTrendVW_5, mTrendVW_3, mLTW, sResearchDesignRunID, ...
            sCodeFingerprint, sDataBuildID, rKnownAlias, rMethodStatus, ...
            iSetting,rOutlierAuditStandard,rOutlierAuditValidation, ...
            rPredictorSupportAudit);
    else
        sPayloadSHA256 = fSaveTREND(sFilename,mYhat, vDates, ...
            vAssetID, cTrendNames, ...
            mTrendEW_5, mTrendEW_3, mLTW_EW, sResearchDesignRunID, ...
            sCodeFingerprint, sDataBuildID, rKnownAlias, rMethodStatus, ...
            iSetting,rOutlierAuditStandard,rOutlierAuditValidation, ...
            rPredictorSupportAudit);
    end
    rRunManifest = iStoreMethodStatus(rRunManifest, iSetting, rMethodStatus);
    rRunManifest.cPayloadSHA256{iSetting} = sPayloadSHA256;
    rRunManifest.lCompleted(iSetting) = true;
    rRunManifest.lComplete = all(rRunManifest.lCompleted);
    rRunManifest.sUpdatedAt = char(datetime('now', ...
        'Format','yyyy-MM-dd''T''HH:mm:ss'));
    iSaveManifest(sManifestFile, rRunManifest);
    WaitBar.Send()
end
WaitBar.Destroy()
fprintf('research_design_run_complete=%i (%i/%i combos)\n', ...
    rRunManifest.lComplete, sum(rRunManifest.lCompleted), iNumCombos);

