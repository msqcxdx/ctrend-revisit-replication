% Script for evaluating the Sharpe ratio of the CTREND and benchmark factors
% across all possible combinations of research designs.
%
% Requires that b09RunResearchDesigns was executed
%
% This script produces:
%   Figure 2:   Distribution of Sharpe Ratios under Alternative Research Designs
%   Table 6:    Paper-aligned method-specific available-case performance
%   Table 6 CW: Strict all-method and pairwise common-week comparisons for
%               the same balanced design cells (parallel audit output)
%   Figure B1:  Distribution of Sharpe Ratios under Alternative Research Designs
%               (Value-Weighted Portfolios Only)
%   Table B6:   Factor Performance Depending on Research Design Choices 
%               without Equal-Weighting

% Clear console
clear; clc; close all;

% Set paths
sOldPath    = path;
sDataPath   = './DATA/';
addpath('./Utils/');
addpath('./LatexTables/');

% Load design choices
load('DesignChoices.mat','tCombos');
tCombosFull = tCombos;

% Select the explicitly requested publication variant.  The full b09
% manifest is always validated before this presentation-only filter is
% applied, so the value-weighted appendix cannot mistake its 1,536 selected
% rows for an incomplete 3,072-combination research-design run.
sOutputVariant = lower(strtrim(getenv('CTREND_OUTPUT_VARIANT')));
if isempty(sOutputVariant)
    sOutputVariant = 'main';
end
assert(ismember(sOutputVariant,{'main','value_weighted_only'}), ...
    ['CTREND_OUTPUT_VARIANT must be main or value_weighted_only for ' ...
     'b10Table6_FactorPerformanceAcrossResearchDesignChoices']);
lDropEW = strcmp(sOutputVariant,'value_weighted_only');
if lDropEW
    tCombos(~tCombos.vUseValueWts,:) = [];
end
iNumCombos      = size(tCombos,1);
fprintf('table6_output_variant=%s\n',sOutputVariant);
fprintf('table6_selected_b09_combos=%d\n',iNumCombos);
fprintf('table6_full_manifest_combos=%d\n',height(tCombosFull));

% Refuse incomplete, stale-code, stale-data, or mixed chunk outputs.
sManifestFile = './Results/CTREND/ResearchDesignRunManifest.mat';
assert(exist(sManifestFile, 'file') == 2, ...
    'Research-design manifest is missing; run b09RunResearchDesigns');
rManifestLoad = load(sManifestFile, 'rRunManifest');
assert(isfield(rManifestLoad, 'rRunManifest'), ...
    'Research-design manifest is invalid');
rRunManifest = rManifestLoad.rRunManifest;
assert(rRunManifest.lComplete && all(rRunManifest.lCompleted) && ...
    rRunManifest.iNumCombos == height(tCombosFull), ...
    'Research-design run is incomplete; finish every b09 combo first');
assert(isfield(rRunManifest,'cMethodNames') && ...
    isfield(rRunManifest,'mMethodCompleted') && ...
    isfield(rRunManifest,'mFinitePredictionWeeks') && ...
    isfield(rRunManifest,'mFiniteFactorWeeks5') && ...
    isfield(rRunManifest,'mFiniteFactorWeeks3') && ...
    isfield(rRunManifest,'mScheduledWeeks') && ...
    isfield(rRunManifest,'mEligiblePredictionWeeks') && ...
    isfield(rRunManifest,'mEstimatedWeeks') && ...
    isfield(rRunManifest,'mEligibleFactorWeeks5') && ...
    isfield(rRunManifest,'mEligibleFactorWeeks3') && ...
    isfield(rRunManifest,'mFailedPredictionWeeks') && ...
    isfield(rRunManifest,'mFailedFactorWeeks5') && ...
    isfield(rRunManifest,'mFailedFactorWeeks3') && ...
    isfield(rRunManifest,'mUnexpectedFailureWeeks') && ...
    isfield(rRunManifest,'mEstimatorFailureWeeks') && ...
    isfield(rRunManifest,'mExpectedPredictionAssetWeeks') && ...
    isfield(rRunManifest,'mFinitePredictionAssetWeeks') && ...
    isfield(rRunManifest,'mPredictionCoverageRatio') && ...
    isfield(rRunManifest,'mPredictionAssetCoverageRatio') && ...
    isfield(rRunManifest,'mFactorCoverageRatio5') && ...
    isfield(rRunManifest,'mFactorCoverageRatio3') && ...
    isfield(rRunManifest,'dMinCoverageRatio') && ...
    all(rRunManifest.mMethodCompleted(:)) && ...
    all(rRunManifest.mEligiblePredictionWeeks(:) > 0) && ...
    all(rRunManifest.mEligibleFactorWeeks5(:) > 0) && ...
    all(rRunManifest.mEligibleFactorWeeks3(:) > 0) && ...
    all(rRunManifest.mUnexpectedFailureWeeks(:) == 0) && ...
    all(rRunManifest.mPredictionCoverageRatio(:) >= ...
        rRunManifest.dMinCoverageRatio) && ...
    all(rRunManifest.mPredictionAssetCoverageRatio(:) >= ...
        rRunManifest.dMinCoverageRatio) && ...
    all(rRunManifest.mFactorCoverageRatio5(:) >= ...
        rRunManifest.dMinCoverageRatio) && ...
    all(rRunManifest.mFactorCoverageRatio3(:) >= ...
        rRunManifest.dMinCoverageRatio), ...
    ['Research-design method manifest lacks full eligible-week coverage ' ...
     'or contains an unexpected/failed window']);
assert(isfield(rRunManifest, 'tCombos') && ...
    isequaln(rRunManifest.tCombos, tCombosFull), ...
    'DesignChoices changed after b09; recompute the research-design run');
sCurrentCodeFingerprint = fPipelineCodeFingerprint(pwd);
assert(strcmp(rRunManifest.sCodeFingerprint, sCurrentCodeFingerprint), ...
    'Corrected source changed after b09; recompute the research-design run');
sRequiredRunID = rRunManifest.sResearchDesignRunID;
sRequiredDataBuildID = rRunManifest.sDataBuildID;
fprintf('table6_research_run_id=%s\n',sRequiredRunID);
fprintf('table6_data_build_id=%s\n',sRequiredDataBuildID);
fprintf('table6_code_fingerprint=%s\n',sCurrentCodeFingerprint);
assert(strcmp(sRequiredDataBuildID, ...
    fGetCurrentWeeklyDataBuildID(sDataPath)), ...
    'Weekly data were rebuilt after b09; recompute the research-design run');

% Load any combo to get some info
sFilename   = sprintf('./Results/CTREND/CTREND_Combo%i.mat', 1);
fAssertB09PayloadDigest(sFilename,1, ...
    rRunManifest.cPayloadSHA256{1});
rInfo       = load(sFilename, 'cTrendNames', 'sResearchDesignRunID', ...
    'sCodeFingerprint', 'sDataBuildID','sPredictionSourceFingerprint', ...
    'rMethodStatus','iSetting','vDates','vAssetID');
assert(strcmp(rInfo.sResearchDesignRunID, sRequiredRunID) && ...
       strcmp(rInfo.sCodeFingerprint, sCurrentCodeFingerprint) && ...
       strcmp(rInfo.sDataBuildID, sRequiredDataBuildID) && ...
       strcmp(rInfo.sPredictionSourceFingerprint, ...
           sCurrentCodeFingerprint) && rInfo.iSetting == 1, ...
    'Combo 1 provenance does not match the completed b09 manifest');
assert(isfield(rInfo,'rMethodStatus') && ...
    all(rInfo.rMethodStatus.lCompleted) && ...
    all(rInfo.rMethodStatus.vUnexpectedFailureWeeks == 0) && ...
    all(rInfo.rMethodStatus.vPredictionCoverageRatio >= ...
        rRunManifest.dMinCoverageRatio) && ...
    all(rInfo.rMethodStatus.vPredictionAssetCoverageRatio >= ...
        rRunManifest.dMinCoverageRatio) && ...
    all(rInfo.rMethodStatus.vFactorCoverageRatio5 >= ...
        rRunManifest.dMinCoverageRatio) && ...
    all(rInfo.rMethodStatus.vFactorCoverageRatio3 >= ...
        rRunManifest.dMinCoverageRatio), ...
    'Combo 1 method-level status is incomplete');
cTrendNames = rInfo.cTrendNames;
iNumMethods = length(cTrendNames);
assert(isequal(cTrendNames(:)',rRunManifest.cMethodNames(:)'), ...
    'Combo 1 method order does not match the b09 manifest');
iAssertStatusAgainstManifest(rInfo.rMethodStatus,rRunManifest,1);
vReferenceDates = rInfo.vDates(:);
vReferenceAssetID = rInfo.vAssetID(:);

% The paper's cross-method comparison uses these six estimators.  Hold the
% CS-C-ENet forecast aggregation at equal weighting/no validation so every
% estimator is evaluated on the same research-design cells.  The other
% CS-C-ENet validation/theta variants remain in the paper Table 6 panels.
cMethods = {'FM','CFM','C_ENET_SCS','POLS','CPOLS','C_ENET'};
iNumComparisonMethods = numel(cMethods);
vComparisonMethodIndex = NaN(1,iNumComparisonMethods);
for iIdxM = 1:iNumComparisonMethods
    vMatch = find(strcmpi(cTrendNames,cMethods{iIdxM}));
    assert(isscalar(vMatch), ...
        'Expected exactly one baseline implementation of method %s', ...
        cMethods{iIdxM});
    vComparisonMethodIndex(iIdxM) = vMatch;
end

% Initialize memory
mShp3        = NaN(iNumCombos, iNumMethods); % Sharpe ratios of tertile portfolios
mShp5        = NaN(iNumCombos, iNumMethods); % Sharpe ratios of quintile portfolios
mShp3_T      = NaN(iNumCombos, iNumMethods); % t-stats of Sharpe ratios of tertile portfolios
mShp5_T      = NaN(iNumCombos, iNumMethods); % t-stats of Sharpe ratios of quintile portfolios
mShpLTW      = NaN(iNumCombos, 2);           % Sharpe ratios of LTW factors
mShpLTW_T    = NaN(iNumCombos, 2);           % t-stats of Sharpe ratios of LTW factors
mN3          = NaN(iNumCombos, iNumMethods); % finite weekly returns used by tertile Sharpes
mN5          = NaN(iNumCombos, iNumMethods); % finite weekly returns used by quintile Sharpes
mNLTW        = NaN(iNumCombos, 2);           % finite scheduled-OOS LTW weekly returns

% Strict comparison artifacts for the six baseline estimators.  These are
% calculated from the same return arrays as the paper Table 6, never from a
% reconstructed or imputed series.
mAllCommonShp3 = NaN(iNumCombos,iNumComparisonMethods);
mAllCommonShp5 = NaN(iNumCombos,iNumComparisonMethods);
vAllCommonN3 = NaN(iNumCombos,1);
vAllCommonN5 = NaN(iNumCombos,1);
vAllUnionN3 = NaN(iNumCombos,1);
vAllUnionN5 = NaN(iNumCombos,1);
mOwnFirstIndex3 = NaN(iNumCombos,iNumComparisonMethods);
mOwnFirstIndex5 = NaN(iNumCombos,iNumComparisonMethods);
mOwnLastIndex3 = NaN(iNumCombos,iNumComparisonMethods);
mOwnLastIndex5 = NaN(iNumCombos,iNumComparisonMethods);
vAllCommonFirstIndex3 = NaN(iNumCombos,1);
vAllCommonFirstIndex5 = NaN(iNumCombos,1);
vAllCommonLastIndex3 = NaN(iNumCombos,1);
vAllCommonLastIndex5 = NaN(iNumCombos,1);
mPairCommonN3 = NaN(iNumCombos,iNumComparisonMethods, ...
    iNumComparisonMethods);
mPairCommonN5 = NaN(iNumCombos,iNumComparisonMethods, ...
    iNumComparisonMethods);
mPairUnionN3 = NaN(iNumCombos,iNumComparisonMethods, ...
    iNumComparisonMethods);
mPairUnionN5 = NaN(iNumCombos,iNumComparisonMethods, ...
    iNumComparisonMethods);
mPairJaccard3 = NaN(iNumCombos,iNumComparisonMethods, ...
    iNumComparisonMethods);
mPairJaccard5 = NaN(iNumCombos,iNumComparisonMethods, ...
    iNumComparisonMethods);
mPairSharpe3 = NaN(iNumCombos,iNumComparisonMethods, ...
    iNumComparisonMethods);
mPairSharpe5 = NaN(iNumCombos,iNumComparisonMethods, ...
    iNumComparisonMethods);
mEstimatorStatusCounts = zeros(iNumCombos,iNumComparisonMethods,8);
mEstimatedEmptySelection = zeros(iNumCombos,iNumComparisonMethods);
lEstimatorStatusExposed = false(iNumCombos,iNumComparisonMethods);

% Loop over combos to calculate the Sharpe ratios
parfor iIdxC = 1:iNumCombos
    % Print progress
    fprintf('Load combo %i of %i \n', iIdxC, iNumCombos);

    % Create filename for combination
    iExpectedSetting = tCombos.setting(iIdxC);
    sFilename = sprintf('./Results/CTREND/CTREND_Combo%i.mat', ...
        iExpectedSetting);

    % Load combination (tertile and quintile CTREND factors and LTW factors)
    try
        fAssertB09PayloadDigest(sFilename,iExpectedSetting, ...
            rRunManifest.cPayloadSHA256{iExpectedSetting});
        rCombo = load(sFilename,'mTrend_3','mTrend_5','mLTW', ...
            'sResearchDesignRunID','sCodeFingerprint','sDataBuildID', ...
            'sPredictionSourceFingerprint','rMethodStatus','iSetting', ...
            'cTrendNames','vDates','vAssetID');
        assert(strcmp(rCombo.sResearchDesignRunID, sRequiredRunID) && ...
               strcmp(rCombo.sCodeFingerprint, sCurrentCodeFingerprint) && ...
               strcmp(rCombo.sDataBuildID, sRequiredDataBuildID) && ...
               strcmp(rCombo.sPredictionSourceFingerprint, ...
                   sCurrentCodeFingerprint), ...
            'Mixed or stale provenance in %s', sFilename);
        assert(isscalar(rCombo.iSetting) && ...
               rCombo.iSetting == iExpectedSetting && ...
               isequal(rCombo.cTrendNames(:)',cTrendNames(:)') && ...
               isequal(rCombo.vDates(:),vReferenceDates) && ...
               isequal(rCombo.vAssetID(:),vReferenceAssetID), ...
            'Combo identity or axes disagree in %s',sFilename);
        assert(isequal(size(rCombo.mTrend_3), ...
                   [numel(vReferenceDates),iNumMethods]) && ...
               isequal(size(rCombo.mTrend_5), ...
                   [numel(vReferenceDates),iNumMethods]) && ...
               isequal(size(rCombo.mLTW),[numel(vReferenceDates),2]), ...
            'Combo factor dimensions are invalid in %s',sFilename);
        rVariables = whos('-file',sFilename);
        iAssertStoredVariableSize(rVariables,'mYhat', ...
            [numel(vReferenceAssetID),numel(vReferenceDates),iNumMethods], ...
            iExpectedSetting);
        iAssertStatusAgainstManifest( ...
            rCombo.rMethodStatus,rRunManifest,iExpectedSetting);
        assert(all(rCombo.rMethodStatus.lCompleted) && ...
               all(rCombo.rMethodStatus.vUnexpectedFailureWeeks == 0) && ...
               all(rCombo.rMethodStatus.vPredictionCoverageRatio >= ...
                   rRunManifest.dMinCoverageRatio) && ...
               all(rCombo.rMethodStatus.vPredictionAssetCoverageRatio >= ...
                   rRunManifest.dMinCoverageRatio) && ...
               all(rCombo.rMethodStatus.vFactorCoverageRatio5 >= ...
                   rRunManifest.dMinCoverageRatio) && ...
               all(rCombo.rMethodStatus.vFactorCoverageRatio3 >= ...
                   rRunManifest.dMinCoverageRatio), ...
            'Incomplete method-level coverage in %s', sFilename);
        mTrend_3 = rCombo.mTrend_3;
        mTrend_5 = rCombo.mTrend_5;
        mLTW     = rCombo.mLTW;
    catch ME
        error('%s could not be loaded (%s). Run b09RunResearchDesigns completely before Table 6.', sFilename, ME.message);
    end

    % LTW is observable during CTREND's training history, but the reported
    % comparison starts at the design's first scheduled OOS week. Derive that
    % boundary ex ante from iNumIn; never move it after observing whether an
    % early CTREND portfolio return happened to be missing.
    iIdxFirst = tCombos.vNumIn(iIdxC) + 1;
    assert(iIdxFirst <= size(mLTW,1), ...
        'In-sample window leaves no scheduled OOS week in %s', sFilename);
    mLTW(1:iIdxFirst-1,:) = NaN;

    % Calculate Sharpe ratio
    [mShp3(iIdxC,:), mShp3_T(iIdxC,:)]      = fSharpeRatio(mTrend_3,0,1,2);
    [mShp5(iIdxC,:), mShp5_T(iIdxC,:)]      = fSharpeRatio(mTrend_5,0,1,2);
    [mShpLTW(iIdxC,:), mShpLTW_T(iIdxC,:)]  = fSharpeRatio(mLTW,0,1,2);
    mN3(iIdxC,:) = sum(isfinite(mTrend_3),1);
    mN5(iIdxC,:) = sum(isfinite(mTrend_5),1);
    mNLTW(iIdxC,:) = sum(isfinite(mLTW),1);

    rCommon3 = fTable6CommonWeekStats( ...
        mTrend_3(:,vComparisonMethodIndex));
    rCommon5 = fTable6CommonWeekStats( ...
        mTrend_5(:,vComparisonMethodIndex));
    mAllCommonShp3(iIdxC,:) = rCommon3.vAllCommonSharpe;
    mAllCommonShp5(iIdxC,:) = rCommon5.vAllCommonSharpe;
    vAllCommonN3(iIdxC) = rCommon3.iAllCommonN;
    vAllCommonN5(iIdxC) = rCommon5.iAllCommonN;
    vAllUnionN3(iIdxC) = rCommon3.iAllUnionN;
    vAllUnionN5(iIdxC) = rCommon5.iAllUnionN;
    mOwnFirstIndex3(iIdxC,:) = rCommon3.vOwnFirstIndex;
    mOwnFirstIndex5(iIdxC,:) = rCommon5.vOwnFirstIndex;
    mOwnLastIndex3(iIdxC,:) = rCommon3.vOwnLastIndex;
    mOwnLastIndex5(iIdxC,:) = rCommon5.vOwnLastIndex;
    vAllCommonFirstIndex3(iIdxC) = rCommon3.iAllCommonFirstIndex;
    vAllCommonFirstIndex5(iIdxC) = rCommon5.iAllCommonFirstIndex;
    vAllCommonLastIndex3(iIdxC) = rCommon3.iAllCommonLastIndex;
    vAllCommonLastIndex5(iIdxC) = rCommon5.iAllCommonLastIndex;
    mPairCommonN3(iIdxC,:,:) = reshape( ...
        rCommon3.mPairCommonN,1,iNumComparisonMethods,[]);
    mPairCommonN5(iIdxC,:,:) = reshape( ...
        rCommon5.mPairCommonN,1,iNumComparisonMethods,[]);
    mPairUnionN3(iIdxC,:,:) = reshape( ...
        rCommon3.mPairUnionN,1,iNumComparisonMethods,[]);
    mPairUnionN5(iIdxC,:,:) = reshape( ...
        rCommon5.mPairUnionN,1,iNumComparisonMethods,[]);
    mPairJaccard3(iIdxC,:,:) = reshape( ...
        rCommon3.mPairJaccard,1,iNumComparisonMethods,[]);
    mPairJaccard5(iIdxC,:,:) = reshape( ...
        rCommon5.mPairJaccard,1,iNumComparisonMethods,[]);
    mPairSharpe3(iIdxC,:,:) = reshape( ...
        rCommon3.mPairSharpe,1,iNumComparisonMethods,[]);
    mPairSharpe5(iIdxC,:,:) = reshape( ...
        rCommon5.mPairSharpe,1,iNumComparisonMethods,[]);

    mStatusCountsTemp = zeros(iNumComparisonMethods,8);
    vEmptySelectionTemp = zeros(1,iNumComparisonMethods);
    lStatusExposedTemp = false(1,iNumComparisonMethods);
    assert(isfield(rCombo.rMethodStatus,'cCoverage') && ...
        numel(rCombo.rMethodStatus.cCoverage) == numel(cTrendNames), ...
        'Combo %d lacks per-method coverage/status audit', ...
        iExpectedSetting);
    for iIdxM = 1:iNumComparisonMethods
        rCoverageTemp = rCombo.rMethodStatus.cCoverage{ ...
            vComparisonMethodIndex(iIdxM)};
        assert(isstruct(rCoverageTemp) && ...
            isfield(rCoverageTemp,'rEstimatorSummary') && ...
            isfield(rCoverageTemp.rEstimatorSummary,'vWindowStatus') && ...
            isfield(rCoverageTemp.rEstimatorSummary,'lEmptySelection'), ...
            'Combo %d method %s has malformed estimator status audit', ...
            iExpectedSetting,cMethods{iIdxM});
        vWindowStatus = ...
            double(rCoverageTemp.rEstimatorSummary.vWindowStatus(:));
        assert(all(ismember(vWindowStatus,0:8)), ...
            'Combo %d method %s has an unknown estimator status code', ...
            iExpectedSetting,cMethods{iIdxM});
        lStatusExposedTemp(iIdxM) = ~isempty(vWindowStatus);
        for iStatus = 1:8
            mStatusCountsTemp(iIdxM,iStatus) = ...
                nnz(vWindowStatus == iStatus);
        end
        vEmptySelectionTemp(iIdxM) = nnz( ...
            rCoverageTemp.rEstimatorSummary.lEmptySelection);
    end
    mEstimatorStatusCounts(iIdxC,:,:) = reshape( ...
        mStatusCountsTemp,1,iNumComparisonMethods,[]);
    mEstimatedEmptySelection(iIdxC,:) = vEmptySelectionTemp;
    lEstimatorStatusExposed(iIdxC,:) = lStatusExposedTemp;
end

% So far, the breakpoints for portfolio sorts have not been part of the
% tCombos table because both tertiles and quintiles were calculated (to
% save computation time). To evaluate the combinations, we now need to add
% them to tCombos

% Define breakpoints to consider
cBreakpoints    = {'tertile';'quintile'};
iNumBreakpoints = length(cBreakpoints);

% Repeat tCombos and add breakpoints 
tCombosAll              = repmat(tCombos,iNumBreakpoints,1); 
tCombosAll.cBreakpoints = repelem(cBreakpoints,iNumCombos,1);
tCombosAll.b09Setting   = tCombosAll.setting;

% Adjust number of combinations, including choice of breakpoints
iNumCombosAll       = size(tCombosAll,1);
tCombosAll.setting  = (1:iNumCombosAll)'; % Update index of combination

% Merge the Sharpe ratios for different breakpoints
mShp        = [mShp3; mShp5]; 
mShpT       = [mShp3_T; mShp5_T];
mN          = [mN3; mN5];

% Exact balanced-cell arrays used by the strict Table 6 comparison.
tMethodComparisonDesigns = tCombosAll;
mOwnComparisonShp = mShp(:,vComparisonMethodIndex);
mOwnComparisonN = mN(:,vComparisonMethodIndex);
mAllCommonShp = [mAllCommonShp3;mAllCommonShp5];
vAllCommonN = [vAllCommonN3;vAllCommonN5];
vAllUnionN = [vAllUnionN3;vAllUnionN5];
mOwnFirstIndex = [mOwnFirstIndex3;mOwnFirstIndex5];
mOwnLastIndex = [mOwnLastIndex3;mOwnLastIndex5];
vAllCommonFirstIndex = [vAllCommonFirstIndex3; ...
    vAllCommonFirstIndex5];
vAllCommonLastIndex = [vAllCommonLastIndex3; ...
    vAllCommonLastIndex5];
mPairCommonN = cat(1,mPairCommonN3,mPairCommonN5);
mPairUnionN = cat(1,mPairUnionN3,mPairUnionN5);
mPairJaccard = cat(1,mPairJaccard3,mPairJaccard5);
mPairSharpe = cat(1,mPairSharpe3,mPairSharpe5);
mEstimatorStatusCounts = cat(1,mEstimatorStatusCounts, ...
    mEstimatorStatusCounts);
mEstimatedEmptySelection = [mEstimatedEmptySelection; ...
    mEstimatedEmptySelection];
lEstimatorStatusExposed = [lEstimatorStatusExposed; ...
    lEstimatorStatusExposed];
assert(all(vAllCommonN <= min(mOwnComparisonN,[],2)) && ...
       all(max(mOwnComparisonN,[],2) <= vAllUnionN) && ...
       all(mOwnComparisonN >= 0,'all'), ...
    'All-method common weeks must be a subset of every own-week sample');
for iIdxM = 1:iNumComparisonMethods
    assert(isequal(squeeze(mPairCommonN(:,iIdxM,iIdxM)), ...
                   mOwnComparisonN(:,iIdxM)) && ...
           all(abs(squeeze(mPairJaccard(:,iIdxM,iIdxM))-1) < eps(2)), ...
        'Pairwise diagonal must reproduce method %s own-week support', ...
        cMethods{iIdxM});
end
assert(isequal(mPairCommonN,permute(mPairCommonN,[1,3,2])) && ...
       isequal(mPairUnionN,permute(mPairUnionN,[1,3,2])) && ...
       isequaln(mPairJaccard,permute(mPairJaccard,[1,3,2])), ...
    'Pairwise support and Jaccard matrices must be symmetric');

% Note that we did not change the breakpoints of LTW factors. Since
% 'tertile' is the alternative setting compared to the baseline, we add
% missing values at the position where tertiles were used.
mShpLTW     = [NaN(iNumCombos,2); mShpLTW];      
mShpLTW_T   = [NaN(iNumCombos,2); mShpLTW_T]; 
mNLTW       = [NaN(iNumCombos,2); mNLTW];

% So far, we treated the design choice to use a validation sample during 
% the estimation and the choice to theta-weight the predictions as separate 
% models. Now we merge the combos with this design choice. This implies 
% that we need to insert missing values for all methods for which these 
% two choices are irrelevant. 

% Define the six paper methods.
iNumMethods = length(cMethods);

% Initialize memory
mShpAll     = NaN(iNumCombosAll * 4, iNumMethods);
mShpAll_T   = NaN(iNumCombosAll * 4, iNumMethods);
mNAll       = NaN(iNumCombosAll * 4, iNumMethods);
mApplicable = false(iNumCombosAll * 4, iNumMethods);

% Create combos for that
cWts        = {'equally weighted','$\theta$-weighted'};
cValSample  = {'no','yes'};
tCombosAdd  = combinations(cWts, cValSample);

% Merge combos
[ii,jj]     = meshgrid(1:height(tCombosAdd),1:height(tCombosAll));
tCombosAll  = [tCombosAdd(ii,:) tCombosAll(jj,:)];

% Adjust number of combinations, including validation sample and
% theta-weighting
tCombosAll.setting  = (1:height(tCombosAll))';
iNumCombos          = size(tCombosAll,1);

% Loop over methods
parfor iIdxM = 1:iNumMethods
    % Get method
    sMethodTemp = cMethods{iIdxM};

    switch sMethodTemp
        case {'FM','CFM','POLS','CPOLS','C_ENET'}
            % These models do not have the option of having a validation
            % sample or theta weights

            % Get Sharpe ratios
            iIdxTemp = find(strcmpi(cTrendNames,sMethodTemp));

            % Add missing values
            vShpTemp    = [mShp(:,iIdxTemp); NaN(iNumCombosAll*3,1)];
            vShpTempT   = [mShpT(:,iIdxTemp); NaN(iNumCombosAll*3,1)];
            vNTemp      = [mN(:,iIdxTemp); NaN(iNumCombosAll*3,1)];
            vApplicableTemp = [true(iNumCombosAll,1); ...
                false(iNumCombosAll*3,1)];

        case {'C_ENET_SCS'}
            % Find indices of models
            iIdxTemp        = find(strcmpi(cTrendNames,sMethodTemp));               % Method, equal, no validation
            iIdxTemp_T      = find(strcmpi(cTrendNames,[sMethodTemp,'_T']));        % Method, theta, no validation
            iIdxTemp_VAL    = find(strcmpi(cTrendNames,[sMethodTemp,'_VAL']));      % Method, equal, validation
