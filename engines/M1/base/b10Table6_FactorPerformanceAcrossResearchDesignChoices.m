function tSummary = iPairwiseSummary(tPairwise)
cPair = unique(tPairwise(:,{'MethodA','MethodB'}),'rows','stable');
iNumPairs = height(cPair);
vDesignCells = zeros(iNumPairs,1);
vMedianCommonN = NaN(iNumPairs,1);
vMedianJaccard = NaN(iNumPairs,1);
vMedianDelta = NaN(iNumPairs,1);
vShareAPositive = NaN(iNumPairs,1);
for iIdxP = 1:iNumPairs
    lPair = tPairwise.MethodA == cPair.MethodA(iIdxP) & ...
        tPairwise.MethodB == cPair.MethodB(iIdxP);
    lBalanced = lPair & tPairwise.BalancedCell;
    assert(all(isfinite(tPairwise.DeltaSharpeAminusB(lBalanced))), ...
        'A balanced pairwise Table 6 cell must have both Sharpes defined');
    vDesignCells(iIdxP) = nnz(lBalanced);
    vMedianCommonN(iIdxP) = median( ...
        tPairwise.PairCommonN(lBalanced),'omitmissing');
    vMedianJaccard(iIdxP) = median( ...
        tPairwise.Jaccard(lBalanced),'omitmissing');
    vMedianDelta(iIdxP) = median( ...
        tPairwise.DeltaSharpeAminusB(lBalanced),'omitmissing');
    if any(lBalanced)
        vShareAPositive(iIdxP) = mean( ...
            tPairwise.DeltaSharpeAminusB(lBalanced) > 0);
    end
end
tSummary = cPair;
tSummary.FiniteBalancedDesignCells = vDesignCells;
tSummary.MedianCommonWeeks = vMedianCommonN;
tSummary.MedianJaccard = vMedianJaccard;
tSummary.MedianDeltaSharpeAminusB = vMedianDelta;
tSummary.ShareDesignCellsAOutperformsB = vShareAPositive;
end

