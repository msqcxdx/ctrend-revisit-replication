% Script for measuring the variable importance within the cross-sectional
% combined elastic net
%
% Requires that b05CreateCTREND was executed
%
% This script produces:
%   Figure C3:  Average Variable Importance
%   Figure C4:  Indicator Selection Over Time

% Clear console
clear; clc; close all;

% Set paths
sOldPath    = path;
sDataPath   = './DATA/';
addpath('./Utils/');
addpath('./LatexTables/');

% Load design choices
load('DesignChoices.mat','tCombos');

% Define baseline setting
sOutlierTreatment   = 'trunc';  % Truncation
dThreshold          = 0.005;    % 0.5% and 99.5% levels
dMinMCAP            = 1e6;      % Minimum market capitalization
dMinPrc             = 0;        % Minimum price
lExclStable         = true;     % Exclude stable coins
lUseVolume          = true;     % Use volume indicator

% Sample period
iStartDate          = 201416;
iEndDate            = 202222;

%% Analysis
% Find the baseline weekly-data setting.
iIdxDataComb = tCombos.data_setting(find( ...
    strcmpi(tCombos.cOutlierTreatment,sOutlierTreatment) & ...
    tCombos.vThreshold == dThreshold,1,'first'));

% Load weekly predictors.  The future-return availability used below comes
% from the saved OOS model artifact, not from an outlier-transformed label.
load([sDataPath,sprintf('bCharacteristicsOLHC_Combo%i.mat',iIdxDataComb)]);
fAssertWeeklyDataProvenance(sDataBuildID,rInputProvenance, ...
    sWeeklyCodeFingerprint);

vWeeklyDates = rData.yrmoda(:);
vWeeklyAssetID = rMetaData.vID(:);
mME = rData.mME;
mPrices = rData.mClose;

% Define technical indicators in the exact saved-model order.
if lUseVolume
    cTechnicalIndicators = [ ...
        cellfun(@(x)['sma_',x,'d'], ...
            sprintfc('%i',[3,5,10,20,50,100,200]),'un',false), ...
        {'macd','macd_diff_signal'}, ...
        cellfun(@(x)['volsma_',x,'d'], ...
            sprintfc('%i',[3,5,10,20,50,100,200]),'un',false), ...
        {'volmacd','volmacd_diff_signal'}, ...
        {'rsi','stochRSI','stochK','stochD'}, ...
        {'boll_low','boll_mid','boll_high','boll_width','cci','chaikin'}]';
else
    cTechnicalIndicators = [ ...
        cellfun(@(x)['sma_',x,'d'], ...
            sprintfc('%i',[3,5,10,20,50,100,200]),'un',false), ...
        {'macd','macd_diff_signal','rsi','stochRSI','stochK','stochD'}, ...
        {'boll_low','boll_mid','boll_high','boll_width','cci'}]';
end

[iNumWeeklyObs,iNumWeeklyAssets] = size(mME);
iNumChars = numel(cTechnicalIndicators);
assert(numel(vWeeklyDates) == iNumWeeklyObs && ...
    numel(vWeeklyAssetID) == iNumWeeklyAssets, ...
    'Weekly date/asset axes do not match the predictor data');

% Lag each raw predictor separately.  Do not impose joint availability
% across all 28 indicators: Figure C uses predictor-specific support.
mChars_L1 = NaN(iNumWeeklyAssets,iNumWeeklyObs,iNumChars);
parfor iIdxChar = 1:iNumChars
    mChars_L1(:,:,iIdxChar) = ...
        [NaN(1,iNumWeeklyAssets); ...
         rChars.(cTechnicalIndicators{iIdxChar})(1:end-1,:)]';
end
mME_L1 = [NaN(1,iNumWeeklyAssets);mME(1:end-1,:)];
mPrices_L1 = [NaN(1,iNumWeeklyAssets);mPrices(1:end-1,:)];

% Restrict the weekly source to the published sample before aligning it to
% the saved result axes.
lIsSample = vWeeklyDates >= iStartDate & vWeeklyDates <= iEndDate;
vWeeklyDates = vWeeklyDates(lIsSample);
mChars_L1 = mChars_L1(:,lIsSample,:);
mME_L1 = mME_L1(lIsSample,:);
mPrices_L1 = mPrices_L1(lIsSample,:);

% Ex-ante universe filters apply independently to every raw predictor.
% Subsequent-return availability is deliberately absent from this mask.
lRemoveObs = ~isfinite(mME_L1) | ~isfinite(mPrices_L1) | ...
    (mME_L1 == 0) | (mME_L1 < dMinMCAP) | ...
    (mPrices_L1 < dMinPrc);
if lExclStable
    lRemoveObs = lRemoveObs | rMetaData.lIsStable(:)';
end
lFormationEligible = ~lRemoveObs';
[mCharsUse,mRawPredictorObserved] = ...
    fRankPredictorsOwnSupport(mChars_L1,lFormationEligible);

% Load the saved model and all explicit axes. There is intentionally no
% fallback to a model-output label: Figure C uses the independently saved
% raw strict-return availability mask required by its definition.
sFilename = './Results/CTREND/CTREND_Base.mat';
rBase = load(sFilename,'mBeta','mSelected','vDates','vModelDates', ...
    'vAssetID','mRetRawObserved','cTechnicalIndicators', ...
    'sCodeFingerprint','sDataBuildID','rPredictorSupportAudit', ...
    'rForecastAudit');
fAssertSavedResultProvenance(rBase,sDataBuildID);
assert(isfield(rBase,'mRetRawObserved'), ...
    ['CTREND_Base.mat lacks mRetRawObserved (raw, untransformed future-' ...
     'return availability); rerun b05CreateCTREND.  Figure C refuses ' ...
     'to infer availability from a model-output label.']);
assert(isfield(rBase,'vModelDates') && ~isempty(rBase.vModelDates), ...
    ['CTREND_Base.mat lacks vModelDates; rerun b05CreateCTREND.  Figure C ' ...
     'refuses to infer model dates by padding a fixed number of rows.']);
assert(isfield(rBase,'rForecastAudit') && ...
       isfield(rBase.rForecastAudit,'cSelectionStatus'), ...
    ['CTREND_Base.mat lacks explicit ENet window status; rerun ' ...
     'b05CreateCTREND. Figure C refuses to infer estimator success from ' ...
     'finite component coefficients.']);
assert(isequal(cTechnicalIndicators(:), ...
    rBase.cTechnicalIndicators(:)), ...
    'Saved CTREND predictor order does not match Figure C');

% Align weekly predictors to the saved date and asset IDs explicitly.  A
% positional equality assertion would not protect against a reordered axis.
[lDateFound,vIdxWeeklyDate] = ismember( ...
    rBase.vDates(:),vWeeklyDates(:));
[lAssetFound,vIdxWeeklyAsset] = ismember( ...
    rBase.vAssetID(:),vWeeklyAssetID(:));
assert(all(lDateFound) && all(lAssetFound) && ...
    numel(unique(vIdxWeeklyDate)) == numel(vIdxWeeklyDate) && ...
    numel(unique(vIdxWeeklyAsset)) == numel(vIdxWeeklyAsset), ...
    'Saved Figure-C date/asset IDs do not map uniquely to weekly inputs');
mChars_L1 = mChars_L1(vIdxWeeklyAsset,vIdxWeeklyDate,:);
mCharsUse = mCharsUse(vIdxWeeklyAsset,vIdxWeeklyDate,:);
mRawPredictorObserved = ...
    mRawPredictorObserved(vIdxWeeklyAsset,vIdxWeeklyDate,:);
vDates = rBase.vDates(:);
vAssetID = rBase.vAssetID(:);
iNumObs = numel(vDates);
iNumAssets = numel(vAssetID);

% The explanatory calculation must use exactly the same predictor-specific
% rank variables as the saved estimator.  A common numeric range alone would
% not make two different percentile transforms interchangeable.
assert(isfield(rBase,'rPredictorSupportAudit'), ...
    ['CTREND_Base.mat lacks predictor-support provenance; rerun ' ...
     'b05CreateCTREND before Figure C']);
rRankDiagnostics = struct();
rRankDiagnostics.vNumPredictorSpecificObservations = ...
    reshape(sum(mRawPredictorObserved,[1,2]),1,[]);
rRankDiagnostics.iNumJointCompleteObservations = ...
    nnz(all(mRawPredictorObserved,3));
assert(isequal(rRankDiagnostics.vNumPredictorSpecificObservations, ...
               rBase.rPredictorSupportAudit.vObservedByPredictor) && ...
       nnz(any(mRawPredictorObserved,3)) == ...
               rBase.rPredictorSupportAudit.iUnionRows && ...
       rRankDiagnostics.iNumJointCompleteObservations == ...
               rBase.rPredictorSupportAudit.iJointRows, ...
    'Figure-C predictor support differs from the saved CTREND estimator');
vFiniteFigureRank = mCharsUse(isfinite(mCharsUse));
assert(isempty(vFiniteFigureRank) || ...
    (min(vFiniteFigureRank) >= -0.5-10*eps && ...
     max(vFiniteFigureRank) <= 0.5+10*eps), ...
    'Figure-C predictor-specific ranks left the paper scale');
rRankDiagnostics.sFigureRankRule = ...
    ['Each j is ranked on its own formation-time observed cross-section, ' ...
     'identically to the saved equation-(7) estimator'];
rRankDiagnostics.sEstimatorConsistency = ...
    ['b05 and Figure C call the same predictor-specific rank transform; ' ...
     'future-return availability is applied only after ranking'];

% The saved raw availability panel is already on the saved asset-by-time
% axes.  Reject numeric missing values before conversion to logical.
mRetRawObserved = rBase.mRetRawObserved;
assert(isequal(size(mRetRawObserved),[iNumAssets,iNumObs]) && ...
    all(isfinite(double(mRetRawObserved)),'all') && ...
    all(ismember(double(mRetRawObserved(:)),[0,1])), ...
    'mRetRawObserved must be a complete logical asset-by-time panel');
mRetRawObserved = logical(mRetRawObserved);

% Map each coefficient/selection row by its saved model date.  No blind
% 52-row prefix is added.
[lModelDateFound,vModelTimeIndex] = ismember( ...
    rBase.vModelDates(:),vDates);
assert(all(lModelDateFound) && ...
    all(diff(vModelTimeIndex) > 0) && ...
    numel(unique(vModelTimeIndex)) == numel(vModelTimeIndex), ...
    'Saved model dates do not map uniquely and monotonically to vDates');
assert(size(rBase.mBeta,1) == numel(rBase.vModelDates) && ...
    size(rBase.mBeta,2) == iNumChars && ...
    size(rBase.mBeta,3) == 2 && ...
    isequal(size(rBase.mSelected), ...
        [numel(rBase.vModelDates),iNumChars]), ...
    'Saved beta/selection dimensions do not match vModelDates/predictors');
mBeta = rBase.mBeta;
mSelected = logical(rBase.mSelected);
assert(numel(rBase.rForecastAudit.cSelectionStatus) == ...
    numel(rBase.vModelDates), ...
    'Saved ENet status count does not match vModelDates');
vModelStatusCode = strings(numel(rBase.vModelDates),1);
for iIdxModel = 1:numel(rBase.vModelDates)
    rStatusTemp = rBase.rForecastAudit.cSelectionStatus{iIdxModel};
    assert(isstruct(rStatusTemp) && isfield(rStatusTemp,'sCode'), ...
        'Saved ENet status entry %d is malformed',iIdxModel);
    vModelStatusCode(iIdxModel) = string(rStatusTemp.sCode);
end

% Appendix-C importance on predictor-specific support.  The raw future
% return is used solely as an observed/not-observed indicator.
[vImportance,rImportanceDiagnostics] = ...
    fImportanceCS_ENetPredictorSupport( ...
    mCharsUse,mRawPredictorObserved,mRetRawObserved, ...
    mBeta,mSelected,vModelTimeIndex,vModelStatusCode);
assert(any(isfinite(vImportance)), ...
    'No identified predictor importance is available for Figure C.3');
rImportanceDiagnostics.sFigureRankRule = ...
    ['Rank each j on its own formation-time observed cross-section into ' ...
     '[-0.5,0.5], before applying future-return availability'];
rImportanceDiagnostics.sEstimatorRankConsistency = ...
    ['The same predictor-specific z_j is used in equation (7), equation ' ...
     '(8), and Appendix-C partial dependence'];

[~,vSortIdx] = sort(vImportance,'descend','MissingPlacement','last');
cImportancePDP = [cTechnicalIndicators(:), ...
    sprintfc('%.2f',round(vImportance(:)*100,2))];
cImportancePDP = cImportancePDP(vSortIdx,:);
vBars = vImportance(vSortIdx);
cCharNamesSorted = flipud(cTechnicalIndicators(vSortIdx));
h1 = figure(1);
barh(flipud(vBars'),'grouped','FaceColor',[0.75,0.75,0.75]);
box off
cCharNamesSorted(strcmpi(cCharNamesSorted,'ppo')) = {'macd'};
cCharNamesSorted(strcmpi(cCharNamesSorted,'ppo_diff_signal')) = ...
    {'macd_diff_signal'};
cCharNamesSorted(strcmpi(cCharNamesSorted,'pvo')) = {'volmacd'};
cCharNamesSorted(strcmpi(cCharNamesSorted,'pvo_diff_signal')) = ...
    {'volmacd_diff_signal'};
cCharNamesSorted(strcmpi(cCharNamesSorted,'cmf')) = {'chaikin'};
yticks(1:numel(cCharNamesSorted));
cCharNamesSortedTex = fAddSlash(cCharNamesSorted,false);
yticklabels(cCharNamesSortedTex);

% Plot selection for every successfully estimated saved model date.  A
% valid all-zero selection remains in the plot and selection-frequency
% denominator; a failed model date does not.
lIsAvail = rImportanceDiagnostics.lSuccessfulModel;
assert(any(lIsAvail), ...
    'No successful saved model dates are available for Figure C.4');
h2 = figure(2);
mNotSelected = 1 - double(mSelected(lIsAvail,vSortIdx));
vDatesOOS = rBase.vModelDates(lIsAvail);
imagesc(mNotSelected');
colormap(gray);
yticks(1:numel(cCharNamesSortedTex));
yticklabels(flipud(cCharNamesSortedTex));
vYearsOOS = floor(vDatesOOS/100);
vUniqueYearsOOS = unique(vYearsOOS,'stable');
vYearTicks = arrayfun(@(y)find(vYearsOOS==y,1,'first'), ...
    vUniqueYearsOOS);
xticks(vYearTicks);
xticklabels(vUniqueYearsOOS);
box off
vFracSelected = mean(mSelected(lIsAvail,vSortIdx),1);
ax1 = gca;
ax2 = axes('Position',ax1.Position,'YAxisLocation','right', ...
    'Color','none');
ax2.XTick = [];
ax2.YLim = ax1.YLim;
ax2.YTick = 1:numel(cCharNamesSortedTex);
ax2.YTickLabel = ...
    flipud(sprintfc('%.1f',round(vFracSelected*100,1))');

% The paper contains the exact sma_20d/boll_mid construction alias.  Keep
% both paper predictors, but publish group-level selection and attribution
% diagnostics so individual penalized allocation is not over-interpreted.
iSMA20 = find(strcmp(cTechnicalIndicators,'sma_20d'));
iBollMid = find(strcmp(cTechnicalIndicators,'boll_mid'));
assert(isscalar(iSMA20) && isscalar(iBollMid), ...
    'Expected exactly one sma_20d and one boll_mid predictor');
lAliasCommonRaw = mRawPredictorObserved(:,:,iSMA20) & ...
    mRawPredictorObserved(:,:,iBollMid);
vAliasDiff = mChars_L1(:,:,iSMA20) - ...
    mChars_L1(:,:,iBollMid);
vAliasDiff = vAliasDiff(lAliasCommonRaw);
rAliasDiagnostics = struct();
rAliasDiagnostics.cMembers = {'sma_20d','boll_mid'};
rAliasDiagnostics.iNumCommonRawObservations = numel(vAliasDiff);
rAliasDiagnostics.iNumSMAOnlyObservations = nnz( ...
    mRawPredictorObserved(:,:,iSMA20) & ...
    ~mRawPredictorObserved(:,:,iBollMid));
rAliasDiagnostics.iNumBollMidOnlyObservations = nnz( ...
    ~mRawPredictorObserved(:,:,iSMA20) & ...
    mRawPredictorObserved(:,:,iBollMid));
if isempty(vAliasDiff)
    rAliasDiagnostics.dMaxAbsRawDifference = NaN;
    rAliasDiagnostics.lRawExactOnCommonSupport = false;
else
    rAliasDiagnostics.dMaxAbsRawDifference = max(abs(vAliasDiff));
    rAliasDiagnostics.lRawExactOnCommonSupport = ...
        all(vAliasDiff == 0);
end
rAliasDiagnostics.vMemberImportance = ...
    vImportance([iSMA20,iBollMid]);
rAliasDiagnostics.vMemberSelectionFrequency = mean( ...
    mSelected(lIsAvail,[iSMA20,iBollMid]),1);
rAliasDiagnostics.dGroupUnionSelectionFrequency = mean(any( ...
    mSelected(lIsAvail,[iSMA20,iBollMid]),2));
rAliasDiagnostics.iNumBothSelectedWeeks = nnz(all( ...
    mSelected(lIsAvail,[iSMA20,iBollMid]),2));
rAliasDiagnostics.iNumExactlyOneSelectedWeeks = nnz(xor( ...
    mSelected(lIsAvail,iSMA20),mSelected(lIsAvail,iBollMid)));
rAliasDiagnostics.sInterpretation = ...
    ['Keep both paper predictors.  Exact aliases may receive unstable ' ...
     'individual penalized attribution; use union selection as the group ' ...
     'diagnostic and do not reinterpret either member causally.'];
fprintf(['figureC_alias members=sma_20d,boll_mid common_raw=%d ' ...
    'raw_exact=%d max_abs_diff=%.17g union_selection_pct=%.2f\n'], ...
    rAliasDiagnostics.iNumCommonRawObservations, ...
    rAliasDiagnostics.lRawExactOnCommonSupport, ...
    rAliasDiagnostics.dMaxAbsRawDifference, ...
    100*rAliasDiagnostics.dGroupUnionSelectionFrequency);

% Save all support counts, dates, failure reasons, and alias diagnostics.
sDiagnosticsFile = './Results/FigureC3_C4_Diagnostics.mat';
sDiagnosticsTemporary = [tempname('./Results'),'.mat'];
rDiagnosticsCleanup = onCleanup(@() iDeleteIfExists( ...
    sDiagnosticsTemporary));
sCodeFingerprint = fPipelineCodeFingerprint(pwd);
sDataBuildID = rBase.sDataBuildID;
save(sDiagnosticsTemporary,'vImportance','cImportancePDP', ...
    'rImportanceDiagnostics','rAliasDiagnostics','rRankDiagnostics', ...
    'cTechnicalIndicators','vDates','vAssetID', ...
    'sCodeFingerprint','sDataBuildID');
[lMoved,sMoveMessage] = movefile( ...
    sDiagnosticsTemporary,sDiagnosticsFile,'f');
assert(lMoved,'Could not atomically publish %s: %s', ...
    sDiagnosticsFile,sMoveMessage);
clear rDiagnosticsCleanup

% Restore path
path(sOldPath);

function iDeleteIfExists(sFilename)
if exist(sFilename,'file') == 2
    delete(sFilename);
end
end
