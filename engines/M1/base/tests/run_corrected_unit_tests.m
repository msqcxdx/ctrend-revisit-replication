function iCheckGRSCase(iNumFactors)
iNumObs = 30;
vT = (1:iNumObs)';
mFactors = [sin(vT/3),cos(vT/5)];
mFactors = mFactors(:,1:iNumFactors);
mResid = [sin(vT/2)+0.1*cos(vT/7), ...
    cos(vT/4)-0.2*sin(vT/9)];
vAlpha = [0.01;-0.02];
[dActual,~] = fGRS(vAlpha,mResid,mFactors);

iNumAssets = size(mResid,2);
vMeanFactor = mean(mFactors,1)';
mCentered = mFactors-vMeanFactor';
mResidualCov = mResid'*mResid/(iNumObs-iNumFactors-1);
mFactorMoment = mCentered'*mCentered/iNumObs;
dExpected = (iNumObs/iNumAssets) * ...
    ((iNumObs-iNumAssets-iNumFactors)/(iNumObs-iNumFactors-1)) * ...
    ((vAlpha'*(mResidualCov\vAlpha)) / ...
    (1+vMeanFactor'*(mFactorMoment\vMeanFactor)));
iAssertClose(dActual,dExpected,1e-12, ...
    sprintf('exact GRS with %d factors',iNumFactors));
end

