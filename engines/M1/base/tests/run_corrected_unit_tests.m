function iTestRSI()
vMove = repmat([0.02;-0.01;0.03;-0.015;0.005],6,1);
vPrice = 100*cumprod(1+vMove);
mClose = [vPrice, (1:numel(vPrice))', flipud((1:numel(vPrice))'), ...
    ones(numel(vPrice),1)];
o = technical_indicators(mClose,mClose,mClose,mClose,ones(size(mClose)));
mRSI = o.fRelativeStrengthIndex(14);

vDiff = diff(vPrice);
vGain = max(vDiff,0);
vLoss = max(-vDiff,0);
vExpected = NaN(size(vPrice));
for t = 15:numel(vPrice)
    dGain = mean(vGain(t-14:t-1));
    dLoss = mean(vLoss(t-14:t-1));
    vExpected(t) = 100-100/(1+dGain/dLoss);
end
iAssertClose(mRSI(:,1),vExpected,1e-10,'simple 14-change RSI');
assert(all(mRSI(15:end,2) == 100), ...
    'All-gain RSI must equal 100');
assert(all(mRSI(15:end,3) == 0), ...
    'All-loss RSI must equal zero');
assert(all(isnan(mRSI(:,4))), ...
    'Flat-price RSI is undefined');

vGapPrice = vPrice;
vGapPrice(10) = NaN;
oGap = technical_indicators(vGapPrice,vGapPrice,vGapPrice,vGapPrice, ...
    ones(size(vGapPrice)));
vGapRSI = oGap.fRelativeStrengthIndex(14);
assert(isnan(vGapRSI(24)) && isfinite(vGapRSI(25)), ...
    'RSI must restart only after 15 consecutive closes following a gap');
end

function iTestOutlierReferenceUniverse()
