function test_b05_b09_baseline_results()
% Post-publication invariant for the field-matched b05/b09 baseline.

sTestDir = fileparts(mfilename('fullpath'));
sCodeDir = fileparts(sTestDir);
rDesign = load(fullfile(sCodeDir,'DesignChoices.mat'),'tCombos');
tCombos = rDesign.tCombos;
lBaseline = tCombos.vThreshold == 0.005 & ...
    strcmpi(tCombos.cOutlierTreatment,'trunc') & ...
    tCombos.vExclStable & tCombos.vMinMCAP == 1e6 & ...
    tCombos.vMinPRC == 0 & tCombos.vRetLead == 0 & ...
    tCombos.vRoll & tCombos.vNumIn == 52 & ...
    tCombos.vUseValueWts & tCombos.vUseVolume;
assert(nnz(lBaseline) == 1, ...
    'Expected exactly one field-matched b05 baseline setting');
iSetting = tCombos.setting(lBaseline);

sResults = fullfile(sCodeDir,'Results','CTREND');
rBase = load(fullfile(sResults,'CTREND_Base.mat'), ...
    'mYhat','cResults','vDates','vAssetID','sCodeFingerprint', ...
    'sDataBuildID');
rGrid = load(fullfile(sResults, ...
    sprintf('CTREND_Combo%d.mat',iSetting)), ...
    'mYhat','mTrend_5','vDates','vAssetID','cTrendNames', ...
    'sCodeFingerprint','sDataBuildID','iSetting');
iMethod = find(strcmpi(rGrid.cTrendNames,'C_ENET_SCS'));
assert(isscalar(iMethod) && rGrid.iSetting == iSetting, ...
    'Field-matched b09 payload or method identity is invalid');
assert(isequal(rBase.vDates,rGrid.vDates) && ...
       isequal(rBase.vAssetID,rGrid.vAssetID), ...
    'b05 and field-matched b09 axes differ');
assert(strcmp(char(rBase.sCodeFingerprint), ...
              char(rGrid.sCodeFingerprint)) && ...
       strcmp(char(rBase.sDataBuildID),char(rGrid.sDataBuildID)), ...
    'b05 and field-matched b09 provenance differs');

mBaseForecast = rBase.mYhat;
mGridForecast = rGrid.mYhat(:,:,iMethod);
iAssertSameFiniteValues(mBaseForecast,mGridForecast,1e-12, ...
    'b05/b09 combined OOS forecast');

vBaseFactor = rBase.cResults.VW.mPortRet(end,:)';
vGridFactor = rGrid.mTrend_5(:,iMethod);
iAssertSameFiniteValues(vBaseFactor,vGridFactor,1e-12, ...
    'b05/b09 value-weighted H-L factor');

fprintf('B05_B09_BASELINE_RESULT_TEST_OK setting=%d method=%s\n', ...
    iSetting,rGrid.cTrendNames{iMethod});
end

function iAssertSameFiniteValues(vA,vB,dTolerance,sLabel)
assert(isequal(size(vA),size(vB)) && ...
       isequal(isfinite(vA),isfinite(vB)), ...
    '%s finite support differs',sLabel);
lFinite = isfinite(vA);
if any(lFinite,'all')
    dScale = max(1,max(abs([vA(lFinite);vB(lFinite)])));
    assert(max(abs(vA(lFinite)-vB(lFinite))) <= dTolerance*dScale, ...
        '%s values differ',sLabel);
end
end
