function test_portfolio_gap_accounting()
% Lock episode accounting, tradability reweighting, and terminal reinvestment.

iTestFormationGapEpisode();
iTestKnownUntradableReallocation();
iTestLastTradeSameLegReinvestment();
fprintf('PORTFOLIO_GAP_ACCOUNTING_TEST_OK\n');
end

function iTestFormationGapEpisode()
mSort = repmat((1:4)',1,4);
mSort(:,2) = NaN;
mRet = zeros(4,4);
mME = ones(4,4);
rOptions = struct('sFreq','weekly','iMinNumCS',4, ...
    'iMinNumAssets',1,'lEnsureAllObs',true, ...
    'vTC',[0.004;0.003]);
r = fSingleSortMulti(mSort,mRet,[0;0.5;1],[],mME,rOptions);

% Initial entry is observed.  A middle formation gap and the first target
% after it have no observable transition; the following adjacent transition
% is again identified.
assert(isequal(isfinite(r.VW.mCostBaseFull(:,end))', ...
               [true,false,false,true]) && ...
       r.VW.mCostBaseFull(1,end) == 2 && ...
       r.VW.mCostBaseFull(4,end) == 0, ...
    'A formation gap was treated as a free exit or a new cash entry');
assert(~r.VW.lPayoffComplete(end,2) && ...
       r.VW.lInternalFormationGap(end,2) && ...
       r.VW.lRestartAfterGap(end,3), ...
    'Formation-gap episode diagnostics are inconsistent');
assert(isnan(r.VW.mPortRetNet(end,2)) && ...
       isnan(r.VW.mPortRetNet(end,3)) && ...
       isfinite(r.VW.mPortRetNet(end,4)), ...
    'Net returns must be fail-closed across a formation gap');
assert(r.VW.rAccountingCounts.vRestartAfterGapN(end) == 1 && ...
       r.VW.rAccountingCounts.vInternalFormationGapN(end) == 1, ...
    'Formation-gap accounting counts are wrong');
end

function iTestKnownUntradableReallocation()
mSort = repmat((1:6)',1,3);
mRet = zeros(6,3);
mRet(1,1) = NaN; % known-untradable target-week asset
mME = ones(6,3);
rOptions = struct('sFreq','weekly','iMinNumCS',5, ...
    'iMinNumAssets',1,'lEnsureAllObs',true, ...
    'vTC',[0.004;0.003]);
r = fSingleSortMulti(mSort,mRet,[0;0.5;1],[],mME,rOptions);

% Availability is treated as announcement-equivalent.  The unavailable
% asset is removed before breakpoints and the remaining holdings sum to one.
assert(all(isfinite(r.VW.mPortRet(:,1))) && ...
       all(isnan(r.VW.mWts(1,1,:)) | r.VW.mWts(1,1,:)==0,'all') && ...
       all(abs(sum(r.VW.mWts(:,1,:),1,'omitnan')-1) <= 1e-12,'all'), ...
    'Known-untradable target was not removed and reweighted at formation');
assert(r.VW.lPayoffComplete(end,1) && ...
       ~r.VW.lPriorPayoffMissingTransition(end,2), ...
    'Reallocated target was incorrectly classified as missing payoff');

lExpectedNet = isfinite(r.VW.mPortRet) & ...
    isfinite(r.VW.mCostBasePaired');
assert(isequal(isfinite(r.VW.mPortRetNet),lExpectedNet), ...
    'Finite net returns must equal gross-and-paired-cost support');
end

function iTestLastTradeSameLegReinvestment()
dt = datetime(2020,1,1)+caldays(0:20)';
vDate = year(dt)*10000+month(dt)*100+day(dt);
mClose = ones(21,4);
mClose(8:12,4) = (1.1:0.1:1.5)';
mClose(13:end,4) = NaN;
mMEEvent = ones(size(mClose));
vAssetID = (1:4)';

sTemp = tempname;
mkdir(sTemp);
rTempCleanup = onCleanup(@() rmdir(sTemp,'s')); %#ok<NASGU>
[tExit,~] = fBuildAndFreezeMechanicalExitCalendar( ...
    mClose,vDate,vAssetID,["A";"B";"C";"D"], ...
    fullfile(sTemp,'exit.csv'));
[rLedger,mRetWeekly] = fBuildWeeklyReinvestmentLedger( ...
    mClose,mMEEvent,vDate,vAssetID,tExit);

mSort = repmat((1:4)',1,3);
mRet = mRetWeekly';
mME = ones(4,3);
rOptions = struct('sFreq','weekly','iMinNumCS',4, ...
    'iMinNumAssets',1,'lEnsureAllObs',true, ...
    'vTC',[0.004;0.003], ...
    'rReinvestmentLedger',rLedger, ...
    'vLedgerWeekRow',(1:3)', ...
    'sPayoffTiming','ordinary');
r = fSingleSortMulti(mSort,mRet,[0;0.5;1],[],mME,rOptions);

% In week 2 the high leg starts 50/50 in assets 3 and 4.  Asset 4 grows
% from 1 to 1.5, is sold at its frozen terminal quote, and all 0.75 of its
% proceeds are immediately invested in surviving high-leg asset 3.  No
% wealth is left in cash and no value enters the low leg.
assert(abs(r.VW.mPortRet(2,2)-0.25) <= 1e-12 && ...
       abs(r.VW.mPortRet(end,2)-0.25) <= 1e-12 && ...
       abs(r.VW.mEndRiskyWts(3,2,2)-1) <= 1e-12 && ...
       r.VW.mEndRiskyWts(4,2,2) == 0, ...
    'Frozen terminal proceeds were not fully reinvested in the same leg');
assert(abs(r.VW.mWithinWeekTradeCostBaseFull(2,2)-1.5) <= 1e-12 && ...
       abs(r.VW.mOpeningTradeCostBaseFull(2,2)-1) <= 1e-12 && ...
       abs(r.VW.mCostBaseFull(2,2)-2.5) <= 1e-12 && ...
       abs(r.VW.mCostBaseFull(2,end)-3.5) <= 1e-12, ...
    'Opening and within-week sale/buy trades were not fully costed');
assert(r.VW.rAccountingCounts.vForcedLiquidationWeekN(2) == 1 && ...
       r.VW.cSameLegReinvestmentAudit{2}.lEndCashAlwaysZero && ...
       ~r.VW.cSameLegReinvestmentAudit{2}.lCrossLegTransfer, ...
    'Same-leg terminal accounting diagnostics are inconsistent');
end
