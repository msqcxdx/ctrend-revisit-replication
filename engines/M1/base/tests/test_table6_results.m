function test_table6_results()
% Result-level shape, support, and provenance invariants for v2 Table 6.

sTestDir = fileparts(mfilename('fullpath'));
sCodeDir = fileparts(sTestDir);
sTables = fullfile(sCodeDir,'Results','Tables');
sCommon = fullfile(sTables,'table6_strict_common_week_comparison.mat');
sPaper = fullfile(sTables,'table6_method_specific_week_counts.mat');
assert(exist(sCommon,'file') == 2 && exist(sPaper,'file') == 2, ...
    'Main Table 6 result payloads are missing');

rCommon = load(sCommon);
rPaper = load(sPaper);
cMethods = {'FM','CFM','C_ENET_SCS','POLS','CPOLS','C_ENET'};
iNumDesignCells = 6144;
iNumMethods = numel(cMethods);
iNumPairs = iNumMethods*(iNumMethods-1)/2;

assert(isequal(rCommon.cMethods(:)',cMethods) && ...
    height(rCommon.tMethodComparisonDesigns) == iNumDesignCells && ...
    isequal(size(rCommon.mOwnComparisonShp), ...
        [iNumDesignCells,iNumMethods]) && ...
    isequal(size(rCommon.mOwnComparisonN), ...
        [iNumDesignCells,iNumMethods]) && ...
    isequal(size(rCommon.mAllCommonShp), ...
        [iNumDesignCells,iNumMethods]) && ...
    isequal(size(rCommon.mAllCommonShpBalanced), ...
        [iNumDesignCells,iNumMethods]) && ...
    numel(rCommon.lAllMethodBalancedCell) == iNumDesignCells, ...
    'Strict Table 6 design or method arrays have invalid dimensions');

assert(height(rCommon.tCommonWeekCells) == ...
        iNumDesignCells*iNumMethods && ...
    height(rCommon.tPairwiseCommonWeek) == ...
        iNumDesignCells*iNumPairs && ...
    height(rCommon.tPairwiseSummary) == iNumPairs && ...
    height(rCommon.tMethodCoverageAudit) == ...
        iNumDesignCells*iNumMethods && ...
    height(rCommon.tCoverageSummary) == iNumMethods, ...
    'Strict Table 6 cell, pair, or coverage tables are incomplete');
assert(all(rCommon.vAllCommonN <= ...
        min(rCommon.mOwnComparisonN,[],2)) && ...
    all(rCommon.vAllUnionN >= ...
        max(rCommon.mOwnComparisonN,[],2)) && ...
    all(isfinite(rCommon.mAllCommonShpBalanced( ...
        rCommon.lAllMethodBalancedCell,:)),'all') && ...
    all(isnan(rCommon.mAllCommonShpBalanced( ...
        ~rCommon.lAllMethodBalancedCell,:)),'all'), ...
    'Strict Table 6 support or balanced-cell gate is inconsistent');

assert(numel(rPaper.cNMethods) == 8 && ...
    isequal(size(rPaper.mNReport),size(rPaper.mNApplicable), ...
        size(rPaper.mPaperAvailableCaseSharpe)) && ...
    nnz(rPaper.mNApplicable(:,1:iNumMethods)) == 55296 && ...
    height(rPaper.tPaperAvailableCaseCells) == nnz(rPaper.mNApplicable) && ...
    all(isfinite(rPaper.tPaperAvailableCaseCells.N)) && ...
    all(rPaper.tPaperAvailableCaseCells.N >= 0), ...
    'Paper available-case Table 6 payload is incomplete or malformed');

assert(strcmp(char(rCommon.sRequiredRunID), ...
              char(rPaper.sRequiredRunID)) && ...
    strcmp(char(rCommon.sRequiredDataBuildID), ...
           char(rPaper.sRequiredDataBuildID)) && ...
    strcmp(char(rCommon.sCurrentCodeFingerprint), ...
           char(rPaper.sCurrentCodeFingerprint)) && ...
    strcmp(char(rCommon.sOutputVariant),'main') && ...
    strcmp(char(rPaper.sOutputVariant),'main'), ...
    'Paper and strict Table 6 payload provenance differs');

fprintf(['TABLE6_RESULT_TEST_OK designs=%d methods=%d pairs=%d ' ...
    'paper_method_cells=%d common_rows=%d pair_rows=%d\n'], ...
    iNumDesignCells,iNumMethods,iNumPairs, ...
    nnz(rPaper.mNApplicable(:,1:iNumMethods)), ...
    height(rCommon.tCommonWeekCells), ...
    height(rCommon.tPairwiseCommonWeek));
end
