function test_v2_raw_data_corrections()
% Exact regression tests for the input-specific v2 correction registry.

dtDate = (datetime(2015,11,1):days(1):datetime(2021,3,11))';
vAssetID = [624,638,895,1902,2603,3468,4069,4275,5834,9040,999999];
cSymbol = {'BITCNY','TROLL','XAUR','MYB','NPXS','WFBN','BURN', ...
    'COMBO','ADD','PUNDIX','MAG'};
rMetaData = struct('vID',vAssetID(:),'cSymbol',{cSymbol(:)});

iNumDates = numel(dtDate);
iNumAssets = numel(vAssetID);
mOpen = ones(iNumDates,iNumAssets);
mHigh = ones(iNumDates,iNumAssets);
mLow = ones(iNumDates,iNumAssets);
mClose = ones(iNumDates,iNumAssets);
mME = 100*ones(iNumDates,iNumAssets);
mVolume = reshape(1:(iNumDates*iNumAssets),iNumDates,iNumAssets);

% Populate every guarded transition with the certified raw OHLC.
iSetOHLC(638,"2015-12-02", ...
    [7.02870011e-06,4.709020141e-05,5.92429978e-06,4.664829976e-05]);
iSetOHLC(895,"2016-08-22", ...
    [697.5700073242,702.3610229492,0.0588568002,0.102403]);
iSetOHLC(1902,"2018-06-07", ...
    [0.1007490009,0.1029009968,0.0871637985,0.0874598995]);
iSetOHLC(3468,"2019-04-18", ...
    [7.361495263e-05,0.00013118321594,7.337318288e-05,0.000115264514]);
iSetOHLC(4069,"2020-03-06", ...
    [0.00055718809942,0.00056509995704,0.00036796429771, ...
     0.00048669002083]);
iSetOHLC(4275,"2021-01-20", ...
    [0.00074671,0.89083416,0.00074671,0.8461456]);
iSetOHLC(5834,"2021-03-10", ...
    [0.10561535,1.84142313,0.10557218,1.44994684]);

cCap = { ...
    638,"2015-12-02",234533.774531; ...
    3468,"2019-04-18",2305290.27998; ...
    3468,"2019-04-19",1807643.752772; ...
    3468,"2019-04-20",1860213.181126; ...
    3468,"2019-04-21",1806725.720236; ...
    3468,"2019-04-22",1771751.278744; ...
    3468,"2019-04-24",1658584.10673; ...
    4069,"2020-03-06",430.0247017083; ...
    4069,"2020-03-07",332.6225317963; ...
    4069,"2020-03-08",303.4833279709};
for iRule = 1:size(cCap,1)
    mME(iDate(cCap{iRule,2}),iAsset(cCap{iRule,1})) = cCap{iRule,3};
end

% These previously disputed bitCNY observations are deliberately extreme.
% The raw-unit cleaner must preserve them because magnitude/cross-source
% disagreement is not a production missing-value rule.
cExtreme = { ...
    "2015-11-08",1.2952500582; ...
    "2015-11-09",0.6980810165; ...
    "2016-02-01",1.0631899834};
for iRule = 1:size(cExtreme,1)
    iRow = iDate(cExtreme{iRule,1});
    iColumn = iAsset(624);
    mOpen(iRow,iColumn) = cExtreme{iRule,2};
    mHigh(iRow,iColumn) = cExtreme{iRule,2};
    mLow(iRow,iColumn) = cExtreme{iRule,2};
    mClose(iRow,iColumn) = cExtreme{iRule,2};
end

% A documented 1000:1 project conversion does not splice different CMCIDs.
% Give the old and new Pundi X columns distinct paths so any cross-column
% rescale is immediately observable.
iNPXS = iAsset(2603);
iPUNDIX = iAsset(9040);
mOpen(:,iNPXS) = 2; mHigh(:,iNPXS) = 3;
mLow(:,iNPXS) = 1; mClose(:,iNPXS) = 2.5; mME(:,iNPXS) = 2603;
mOpen(:,iPUNDIX) = 20; mHigh(:,iPUNDIX) = 30;
mLow(:,iPUNDIX) = 10; mClose(:,iPUNDIX) = 25; mME(:,iPUNDIX) = 9040;

% A wholly unrelated 1,000-fold move proves that magnitude is not a repair
% rule and that an asset is not removed because its return is extreme.
iUnrelated = iAsset(999999);
iUnrelatedDate = iDate("2020-01-02");
mClose(iUnrelatedDate-1,iUnrelated) = 1;
mClose(iUnrelatedDate,iUnrelated) = 1000;
mOpen(iUnrelatedDate,iUnrelated) = 1000;
mHigh(iUnrelatedDate,iUnrelated) = 1000;
mLow(iUnrelatedDate,iUnrelated) = 1000;

mVolumeBefore = mVolume;
mBitCNYBefore = [mOpen(:,iAsset(624)),mHigh(:,iAsset(624)), ...
    mLow(:,iAsset(624)),mClose(:,iAsset(624)),mME(:,iAsset(624))];
mSeparateCMCIDBefore = [mOpen(:,[iNPXS,iPUNDIX]), ...
    mHigh(:,[iNPXS,iPUNDIX]),mLow(:,[iNPXS,iPUNDIX]), ...
    mClose(:,[iNPXS,iPUNDIX]),mME(:,[iNPXS,iPUNDIX])];
mUnrelatedBefore = [mOpen(:,iUnrelated),mHigh(:,iUnrelated), ...
    mLow(:,iUnrelated),mClose(:,iUnrelated),mME(:,iUnrelated)];

[mOpen2,mHigh2,mLow2,mClose2,mME2,mVolume2,rAudit] = ...
    fApplyV2RawDataCorrections( ...
    mOpen,mHigh,mLow,mClose,mME,mVolume,dtDate,vAssetID,rMetaData);

% Prior histories use one consistent post-event unit.
iPrior = iDate("2015-12-01");
assert(mClose2(iPrior,iAsset(638)) == 10, ...
    'Trollcoin prior-unit factor was not applied');
assert(mClose2(iDate("2016-08-21"),iAsset(895)) == 1/8000, ...
    'Xaurum prior-unit factor was not applied');
assert(mClose2(iDate("2018-06-06"),iAsset(1902)) == 1/36, ...
    'MyBit prior-unit factor was not applied');
assert(mClose2(iDate("2019-04-17"),iAsset(3468)) == 50, ...
    'Fivebalance prior-unit factor was not applied');
assert(mClose2(iDate("2020-03-05"),iAsset(4069)) == 1/100, ...
    'Blockburn prior-unit factor was not applied');
assert(mClose2(iDate("2021-01-19"),iAsset(4275)) == 1000, ...
    'COMBO prior-unit factor was not applied');
assert(mClose2(iDate("2021-03-09"),iAsset(5834)) == 10, ...
    'ADD prior-unit factor was not applied');

% Mixed-unit transition bars are corrected field by field.
iRow = iDate("2021-01-20");
assert(abs(mOpen2(iRow,iAsset(4275))-0.74671) < 1e-14 && ...
    abs(mLow2(iRow,iAsset(4275))-0.74671) < 1e-14 && ...
    mClose2(iRow,iAsset(4275)) == 0.8461456, ...
    'COMBO transition OHLC was not corrected field by field');
iRow = iDate("2016-08-22");
assert(abs(mOpen2(iRow,iAsset(895))-697.5700073242/8000) < 1e-14 && ...
    abs(mHigh2(iRow,iAsset(895))-0.102403) < 1e-14 && ...
    abs(mLow2(iRow,iAsset(895))-0.0588568002) < 1e-14 && ...
    abs(mClose2(iRow,iAsset(895))-0.102403) < 1e-14, ...
    'Xaurum transition OHLC was not corrected field by field');

assert(abs(mME2(iDate("2015-12-02"),iAsset(638))-23453.3774531) < 1e-8, ...
    'Trollcoin stale-supply market cap was not corrected');
assert(abs(mME2(iDate("2019-04-18"),iAsset(3468))-46105.8055996) < 1e-8, ...
    'Fivebalance stale-supply market cap was not corrected');
assert(abs(mME2(iDate("2020-03-06"),iAsset(4069))-43002.47017083) < 1e-8, ...
    'Blockburn stale-supply market cap was not corrected');

assert(isequal(mVolume2,mVolumeBefore), ...
    'The raw-unit correction changed volume');
assert(isequaln([mOpen2(:,iAsset(624)),mHigh2(:,iAsset(624)), ...
    mLow2(:,iAsset(624)),mClose2(:,iAsset(624)),mME2(:,iAsset(624))], ...
    mBitCNYBefore), ...
    'An extreme cross-source-disputed observation was changed or made missing');
assert(isequaln([mOpen2(:,[iNPXS,iPUNDIX]), ...
    mHigh2(:,[iNPXS,iPUNDIX]),mLow2(:,[iNPXS,iPUNDIX]), ...
    mClose2(:,[iNPXS,iPUNDIX]),mME2(:,[iNPXS,iPUNDIX])], ...
    mSeparateCMCIDBefore), ...
    'Different CMCIDs were spliced or unit-adjusted across asset columns');
assert(isequaln([mOpen2(:,iUnrelated),mHigh2(:,iUnrelated), ...
    mLow2(:,iUnrelated),mClose2(:,iUnrelated),mME2(:,iUnrelated)], ...
    mUnrelatedBefore), ...
    'An unregistered magnitude-only return was changed or removed');
assert(size(mClose2,2) == numel(vAssetID) && ...
    rAudit.iNumAssetsRemoved == 0 && ...
    rAudit.iNumPriceScaleRules == 7 && ...
    rAudit.iNumMarketCapCells == 10 && ...
    rAudit.iNumMissingPriceDates == 0 && ...
    rAudit.iNumExternalCorruptPriceDates == 0, ...
    'The correction audit is incomplete or an asset axis changed');
assert(height(rAudit.tSeparateCMCIDEvents) == 1 && ...
    rAudit.tSeparateCMCIDEvents.OldAssetID == 2603 && ...
    rAudit.tSeparateCMCIDEvents.NewAssetID == 9040 && ...
    rAudit.tSeparateCMCIDEvents.IntegerConversionRatio == 1000, ...
    'The different-CMCID no-splice policy is not explicit in the audit');

fprintf('V2_RAW_DATA_CORRECTION_TEST_OK\n');

    function iSetOHLC(iAssetID,sDate,vOHLC)
        iRowLocal = iDate(sDate);
        iColumnLocal = iAsset(iAssetID);
        mOpen(iRowLocal,iColumnLocal) = vOHLC(1);
        mHigh(iRowLocal,iColumnLocal) = vOHLC(2);
        mLow(iRowLocal,iColumnLocal) = vOHLC(3);
        mClose(iRowLocal,iColumnLocal) = vOHLC(4);
    end

    function iRow = iDate(sDate)
        iRow = find(dtDate == datetime(sDate,'InputFormat','yyyy-MM-dd'));
        assert(isscalar(iRow),'Synthetic correction date is missing');
    end

    function iColumn = iAsset(iAssetID)
        iColumn = find(vAssetID == iAssetID);
        assert(isscalar(iColumn),'Synthetic correction asset is missing');
    end
end
