function test_weekly_endpoint_pnl()
% Deterministic tests for prepared endpoint P&L and reinvestment events.

sTestDir = fileparts(mfilename('fullpath'));
sCodeDir = fileparts(sTestDir);
sOldPath = path;
addpath(fullfile(sCodeDir,'Utils'));
rCleanup = onCleanup(@() path(sOldPath)); %#ok<NASGU>

dt = (datetime(2020,1,1):caldays(1):datetime(2020,1,21))';
vDate = year(dt)*10000+month(dt)*100+day(dt);
vPrice = (101:121)';
mCloseRaw = repmat(vPrice,1,4);

% Asset 2: isolated internal missing closes.  They must use the strictly
% preceding close, never the later close.
mCloseRaw([3,10,18],2) = NaN;
% Asset 3: trading terminates on day 12.  It receives one frozen exit and
% no price may be manufactured after that date.
mCloseRaw(13:end,3) = NaN;
% Asset 4: an internal seven-day reporting gap followed by later quotes.
% Every missing day is filled forward from day 7, not backward from day 15.
mCloseRaw(8:14,4) = NaN;

mOpen = mCloseRaw;
mHigh = mCloseRaw;
mLow = mCloseRaw;
mVolume = ones(size(mCloseRaw));
vAssetID = (1:4)';
[mOpen,mHigh,mLow,mClose,mVolume,rFill] = ... %#ok<ASGLU>
    fApplyUnifiedMissingDataPreprocessing( ...
    mOpen,mHigh,mLow,mCloseRaw,mVolume,vDate,vAssetID);
assert(mClose(3,2) == 102 && mClose(10,2) == 109 && ...
       mClose(8,4) == 107 && mClose(14,4) == 107 && ...
       all(isnan(mClose(13:end,3))) && ...
       rFill.iPostTerminalPriceCellsFilled == 0, ...
    'Unified close fill is not causal or crossed a terminal boundary');

sTemp = tempname;
mkdir(sTemp);
rTempCleanup = onCleanup(@() rmdir(sTemp,'s')); %#ok<NASGU>
[tExit,~] = fBuildAndFreezeMechanicalExitCalendar( ...
    mClose,vDate,vAssetID,["A";"B";"C";"D"], ...
    fullfile(sTemp,'exit.csv'));
mME = ones(size(mClose));
[mPnl,mPnlLead,mBoundary,mFormation,vWeek,rDiag, ...
    mReinvest,mReinvestLead,rLedger] = ...
    fBuildWeeklyEndpointPnl(mClose,vDate,mME,vAssetID,tExit);

assert(isequal(vWeek,[202001;202002;202003]), ...
    'Unexpected Liu et al. weekly date keys');
iAssertClose(mBoundary(:,1),[107;114;121],0,'boundary snapshots');
iAssertClose(mFormation(:,1),[101;108;115],0,'formation snapshots');

vExpected = [NaN;114/107-1;121/114-1];
vExpectedLead = [108/101-1;115/108-1;NaN];
iAssertClose(mPnl(:,1),vExpected,1e-15,'ordinary endpoint return');
iAssertClose(mPnlLead(:,1),vExpectedLead,1e-15,'lead endpoint return');
iAssertClose(mPnl(:,2),vExpected,1e-15, ...
    'internal gaps must not erase endpoint P&L');
iAssertClose(mPnlLead(:,2),vExpectedLead,1e-15, ...
    'internal gaps must not erase lead endpoint P&L');

% Asset 3 settles at its frozen day-12 quote in week 2.  The asset-level
% payoff is finite, but the ledger explicitly requires the portfolio helper
% to reinvest the proceeds in surviving members of that same leg.
iAssertClose(mPnl(:,3),[NaN;112/107-1;NaN],1e-15, ...
    'ordinary frozen-exit payoff');
iAssertClose(mPnlLead(:,3),[108/101-1;112/108-1;NaN],1e-15, ...
    'lead frozen-exit payoff');
assert(mReinvest(2,3) && nnz(mReinvest(:,3)) == 1 && ...
       mReinvestLead(2,3) && nnz(mReinvestLead(:,3)) == 1, ...
    'Frozen terminal event was not exposed to portfolio accounting');

% Asset 4's internal gap is a zero-return carry through day 14.  The later
% day-15 price is used only from day 15 onward.
iAssertClose(mPnl(:,4),[NaN;0;121/107-1],1e-15, ...
    'ordinary internal-gap endpoint return');
iAssertClose(mPnlLead(:,4),[107/101-1;115/107-1;NaN],1e-15, ...
    'lead internal-gap endpoint return');

assert(strcmp(rLedger.sFormat, ...
           'cttrend-same-leg-reinvestment-ledger-v1') && ...
       ~rLedger.lUsesExternalSource && ...
       ~rLedger.lAllowsCashAfterExit && ...
       rDiag.iNumOrdinaryReinvestmentEvents >= 1 && ...
       rDiag.iNumLag1ReinvestmentEvents >= 1 && ...
       ~rDiag.lIntermediateMissingAffectsEndpointPayoff && ...
       rDiag.lTrailingMissingSettlesAtFrozenLastTradable && ...
       ~rDiag.lProceedsRemainCash && ...
       ~rDiag.lAppliesOutlierTransform, ...
    'Endpoint diagnostics do not certify the requested accounting rule');

iTestB02EndpointPnlDiagnosticContract(sCodeDir);
fprintf('WEEKLY_ENDPOINT_PNL_TEST_OK\n');
end

function iTestB02EndpointPnlDiagnosticContract(sCodeDir)
% Execute the exact production diagnostic block on a deterministic fixture.

% This test deliberately extracts the marked block from b02 instead of
% copying its producer/consumer statements.  A missing producer field, a
% renamed consumer, or an ordering regression therefore fails exactly where
% the full production run would fail.
sSource = fileread(fullfile(sCodeDir,'b02CalculateIndicators.m'));
sStart = '% B02_ENDPOINT_PNL_DIAGNOSTIC_CONTRACT_BEGIN';
sEnd = '% B02_ENDPOINT_PNL_DIAGNOSTIC_CONTRACT_END';
vStart = strfind(sSource,sStart);
vEnd = strfind(sSource,sEnd);
assert(isscalar(vStart) && isscalar(vEnd) && vStart < vEnd, ...
    'b02 endpoint-P&L diagnostic contract markers are missing or ambiguous');
sBlock = sSource(vStart+length(sStart):vEnd-1);

rData = struct();
rData.mPnlReturns = [0,NaN,Inf;-1,2,3];
rData.mPnlRetLead = [NaN,0;Inf,-2;5,6];
rData.mRawOutcomeObserved = ...
    [true,false,false;true,false,true];
rData.mRawOutcomeObservedLead = ...
    [false,true;false,true;false,false];
rData.mVolumeRawBoundary = [0,NaN;4,5];
rData.mVolumeRawFormationDay = [NaN,0;6,7];
rEndpointPnlDiagnostics = struct();

sPrinted = evalc('eval(sBlock);');
assert(isfield(rData,'rEndpointPnlDiagnostics') && ...
    rData.rEndpointPnlDiagnostics.iNumPnlReturnCells == ...
        nnz(isfinite(rData.mPnlReturns)) && ...
    rData.rEndpointPnlDiagnostics.iNumPnlRetLeadCells == ...
        nnz(isfinite(rData.mPnlRetLead)), ...
    'b02 did not publish exact finite endpoint-P&L cell counts');
sExpected = sprintf(['return_layers stat=%d pnl=%d pnl_only=%d ' ...
    'stat_lead=%d pnl_lead=%d pnl_only_lead=%d'], ...
    rData.rEndpointPnlDiagnostics.iNumStrictStatReturnCells, ...
    rData.rEndpointPnlDiagnostics.iNumPnlReturnCells, ...
    rData.rEndpointPnlDiagnostics.iNumPnlOnlyReturnCells, ...
    rData.rEndpointPnlDiagnostics.iNumStrictStatRetLeadCells, ...
    rData.rEndpointPnlDiagnostics.iNumPnlRetLeadCells, ...
    rData.rEndpointPnlDiagnostics.iNumPnlOnlyRetLeadCells);
assert(contains(sPrinted,sExpected), ...
    'b02 production diagnostic print did not consume the completed contract');
fprintf(['B02_ENDPOINT_PNL_DIAGNOSTIC_CONTRACT_OK fields=2 ' ...
    'production_block=1\n']);
end

function iAssertClose(vActual,vExpected,dTolerance,sName)
assert(isequal(size(vActual),size(vExpected)), ...
    '%s has inconsistent dimensions',sName);
lBothNaN = isnan(vActual) & isnan(vExpected);
lFinite = isfinite(vActual) & isfinite(vExpected);
assert(all(lBothNaN | lFinite,'all') && ...
    all(abs(vActual(lFinite)-vExpected(lFinite)) <= dTolerance), ...
    '%s differs from its deterministic reference',sName);
end
