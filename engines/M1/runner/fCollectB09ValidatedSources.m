% CTREND_REVISIT_FILE_PURPOSE: Load only hash-validated M1 b09 shard payloads into a canonical merge plan.
function rAudit = fCollectB09ValidatedSources(codeDir, shardRoot, runID)
% Validate reusable canonical and shard outputs for one b09 research run.
%
% A filename alone is never evidence of completion.  Canonical files are
% accepted only after their embedded provenance and method status pass the
% same coverage checks used by b09.  Shard files additionally require a
% completed, matching manifest row.  Canonical files not yet recorded in
% the canonical manifest are intentionally reusable: they can be files
% moved there by an interrupted merge whose final manifest publication did
% not occur.

assert(isfolder(codeDir) && isfolder(shardRoot) && ~isempty(runID), ...
    'B09 validation environment is incomplete');

addpath(fullfile(codeDir, 'Utils'));
rDesign = load(fullfile(codeDir, 'DesignChoices.mat'), 'tCombos');
tCombos = rDesign.tCombos;
nCombo = height(tCombos);
assert(isequal(tCombos.setting(:), (1:nCombo)'), ...
    'DesignChoices setting IDs must equal their row numbers');
nShards = str2double(getenv('B09_NUM_SHARDS'));
assert(isfinite(nShards) && nShards == floor(nShards) && ...
    ismember(nShards, [4, 8]), ...
    'B09_NUM_SHARDS must select an audited 4- or 8-shard profile');

codeFingerprint = fPipelineCodeFingerprint(codeDir);
callerDir = pwd;
rRestoreDir = onCleanup(@() cd(callerDir));
cd(codeDir);
dataBuildID = fGetCurrentWeeklyDataBuildID(fullfile(codeDir, 'DATA'));
cd(callerDir);
clear rRestoreDir

canonicalCTREND = fullfile(codeDir, 'Results', 'CTREND');
canonicalManifestFile = fullfile(canonicalCTREND, ...
    'ResearchDesignRunManifest.mat');
assert(isfile(canonicalManifestFile), ...
    'Canonical combo 1 manifest is missing');
rCanonical = load(canonicalManifestFile, 'rRunManifest');
assert(isfield(rCanonical, 'rRunManifest'), ...
    'Canonical manifest file has no rRunManifest');
baseManifest = rCanonical.rRunManifest;
iValidateManifestIdentity(baseManifest, runID, codeFingerprint, ...
    dataBuildID, tCombos);
assert(baseManifest.lCompleted(1), ...
    'Canonical real-data smoke combo 1 is not complete');

sourceFile = strings(nCombo, 1);
sourceShard = zeros(nCombo, 1);
sourceStatus = cell(nCombo, 1);
sourcePayloadSHA256 = strings(nCombo,1);
iMaxCandidates = (nShards + 1) * nCombo;
invalidMessages = strings(iMaxCandidates, 1);
invalidCombos = NaN(iMaxCandidates, 1);
orphanFiles = strings(nShards * nCombo, 1);
duplicateCanonicalFiles = strings(nShards * nCombo, 1);
movedShardRows = NaN(nShards * nCombo, 2);
iNumInvalid = 0;
iNumOrphan = 0;
iNumDuplicate = 0;
iNumMoved = 0;

% Inspect every canonical MAT, including files moved by a prior interrupted
% merge after the last canonical manifest update.
rFiles = dir(fullfile(canonicalCTREND, 'CTREND_Combo*.mat'));
for iFile = 1:numel(rFiles)
    combo = iParseComboFilename(rFiles(iFile).name, nCombo);
    if isnan(combo)
        continue
    end
    filename = fullfile(rFiles(iFile).folder, rFiles(iFile).name);
    try
        [status,payloadSHA256] = iLoadAndValidateCombo(filename, combo, runID, ...
            codeFingerprint, dataBuildID, baseManifest);
        if baseManifest.lCompleted(combo)
            iAssertStatusAgainstManifest(status, baseManifest, combo);
        elseif combo == 1
            error('CTREND:B09Combo1Manifest', ...
                'Canonical combo 1 is not completed in its manifest');
        end
        sourceFile(combo) = string(filename);
        sourceShard(combo) = -1;
        sourceStatus{combo} = status;
        sourcePayloadSHA256(combo) = payloadSHA256;
    catch ME
        if combo == 1
            rethrow(ME)
        end
        iNumInvalid = iNumInvalid + 1;
        invalidCombos(iNumInvalid) = combo;
        invalidMessages(iNumInvalid) = string(getReport( ...
            ME, 'basic', 'hyperlinks', 'off'));
        warning('CTREND:B09InvalidCanonical', ...
            'Ignoring invalid canonical combo %d: %s', combo, ME.message);
    end
end
assert(sourceFile(1) ~= "", ...
    'Canonical combo 1 MAT is missing or invalid');

% A completed shard manifest row is the commit record for a shard MAT.
% Missing files are allowed only when an already validated canonical copy
% proves that a previous merge moved the file successfully.
for shard = 1:nShards
    shardCTREND = fullfile(shardRoot, sprintf('shard%d', shard), 'CTREND');
    manifestFile = fullfile(shardCTREND, ...
        'ResearchDesignRunManifest.mat');
    if ~isfile(manifestFile)
        warning('CTREND:B09MissingShardManifest', ...
            'Shard %d has no manifest; it contributes no reusable files', ...
            shard);
        continue
    end
    rLoad = load(manifestFile, 'rRunManifest');
    assert(isfield(rLoad, 'rRunManifest'), ...
        'Shard %d manifest file has no rRunManifest', shard);
    manifest = rLoad.rRunManifest;
    iValidateManifestIdentity(manifest, runID, codeFingerprint, ...
        dataBuildID, tCombos);

    rShardFiles = dir(fullfile(shardCTREND, 'CTREND_Combo*.mat'));
    for iFile = 1:numel(rShardFiles)
        combo = iParseComboFilename(rShardFiles(iFile).name, nCombo);
        if ~isnan(combo) && ~manifest.lCompleted(combo)
            iNumOrphan = iNumOrphan + 1;
            orphanFiles(iNumOrphan) = string(fullfile( ...
                rShardFiles(iFile).folder, rShardFiles(iFile).name));
        end
    end

    completed = find(manifest.lCompleted(:));
    assert(~any(completed == 1), ...
        'Shard %d unexpectedly marked combo 1 complete', shard);
    for iCompleted = 1:numel(completed)
        combo = completed(iCompleted);
        filename = fullfile(shardCTREND, ...
            sprintf('CTREND_Combo%d.mat', combo));
        if ~isfile(filename)
            if sourceFile(combo) ~= "" && sourceShard(combo) == -1
                assert(sourcePayloadSHA256(combo) == string( ...
                    manifest.cPayloadSHA256{combo}), ...
                    ['Canonical payload digest disagrees with the shard ' ...
                     'commit row for moved combo %d'],combo);
                iNumMoved = iNumMoved + 1;
                movedShardRows(iNumMoved, :) = [shard, combo];
                continue
            end
            iNumInvalid = iNumInvalid + 1;
            invalidCombos(iNumInvalid) = combo;
            invalidMessages(iNumInvalid) = string(sprintf( ...
                'Shard %d completed manifest row has no MAT', shard));
            continue
        end

        try
            [status,payloadSHA256] = iLoadAndValidateCombo(filename, combo, runID, ...
                codeFingerprint, dataBuildID, manifest);
            iAssertStatusAgainstManifest(status, manifest, combo);
        catch ME
            if sourceFile(combo) ~= "" && sourceShard(combo) == -1
                warning('CTREND:B09InvalidDuplicate', ...
                    ['Ignoring invalid shard duplicate for validated ' ...
                     'canonical combo %d: %s'], combo, ME.message);
                continue
            end
            iNumInvalid = iNumInvalid + 1;
            invalidCombos(iNumInvalid) = combo;
            invalidMessages(iNumInvalid) = string(getReport( ...
                ME, 'basic', 'hyperlinks', 'off'));
            warning('CTREND:B09InvalidShardCombo', ...
                'Ignoring invalid shard %d combo %d: %s', ...
                shard, combo, ME.message);
            continue
        end

        if sourceFile(combo) ~= ""
            if sourceShard(combo) == -1
                assert(iStatusEquivalent(sourceStatus{combo}, status), ...
                    ['Canonical and shard status disagree for combo %d; ' ...
                     'refusing an ambiguous recovery source'], combo);
                assert(sourcePayloadSHA256(combo) == payloadSHA256, ...
                    ['Canonical and shard numeric payload digests disagree ' ...
                     'for combo %d'],combo);
                iNumDuplicate = iNumDuplicate + 1;
                duplicateCanonicalFiles(iNumDuplicate) = string(filename);
                continue
            end
            error('Combo %d was completed by shards %d and %d', ...
                combo, sourceShard(combo), shard);
        end
        sourceFile(combo) = string(filename);
        sourceShard(combo) = shard;
        sourceStatus{combo} = status;
        sourcePayloadSHA256(combo) = payloadSHA256;
    end
end

rAudit = struct();
rAudit.tCombos = tCombos;
rAudit.iNumCombos = nCombo;
rAudit.sCodeFingerprint = codeFingerprint;
rAudit.sDataBuildID = dataBuildID;
rAudit.sResearchDesignRunID = runID;
rAudit.sCanonicalCTREND = canonicalCTREND;
rAudit.sCanonicalManifestFile = canonicalManifestFile;
rAudit.rBaseManifest = baseManifest;
rAudit.cSourceFile = sourceFile;
rAudit.vSourceShard = sourceShard;
rAudit.cSourceStatus = sourceStatus;
rAudit.cPayloadSHA256 = sourcePayloadSHA256;
rAudit.vInvalidCombo = invalidCombos(1:iNumInvalid);
rAudit.cInvalidMessage = invalidMessages(1:iNumInvalid);
rAudit.cOrphanFile = orphanFiles(1:iNumOrphan);
rAudit.cDuplicateCanonicalFile = ...
    duplicateCanonicalFiles(1:iNumDuplicate);
rAudit.mMovedShardRow = movedShardRows(1:iNumMoved, :);
rAudit.lValid = sourceFile ~= "";
end

function combo = iParseComboFilename(name, nCombo)
token = regexp(name, '^CTREND_Combo([1-9][0-9]*)\.mat$', ...
    'tokens', 'once');
if isempty(token)
    combo = NaN;
    return
end
combo = str2double(token{1});
if ~isfinite(combo) || combo < 1 || combo > nCombo || ...
        combo ~= floor(combo)
    combo = NaN;
end
end

function [status,payloadSHA256] = iLoadAndValidateCombo(filename, combo, runID, ...
        codeFingerprint, dataBuildID, manifest)
if manifest.lCompleted(combo)
    sExpectedPayloadSHA256 = manifest.cPayloadSHA256{combo};
else
    sExpectedPayloadSHA256 = '';
end
payloadSHA256 = string(fAssertB09PayloadDigest( ...
    filename,combo,sExpectedPayloadSHA256));
requiredVariables = {'mYhat', 'vDates', 'vAssetID', 'cTrendNames', ...
    'mTrend_5', 'mTrend_3', 'mLTW', 'sResearchDesignRunID', ...
    'sCodeFingerprint', 'sDataBuildID', ...
    'sPredictionSourceFingerprint', 'rMethodStatus','iSetting'};
rInfo = whos('-file', filename);
cVariables = {rInfo.name};
assert(all(ismember(requiredVariables, cVariables)), ...
    'Combo %d MAT schema is incomplete', combo);

r = load(filename, 'vDates', 'vAssetID', 'cTrendNames', ...
    'sResearchDesignRunID', 'sCodeFingerprint', 'sDataBuildID', ...
    'sPredictionSourceFingerprint', 'rMethodStatus','iSetting');
assert(strcmp(char(r.sResearchDesignRunID), runID) && ...
    strcmp(char(r.sCodeFingerprint), codeFingerprint) && ...
    strcmp(char(r.sDataBuildID), dataBuildID) && ...
    strcmp(char(r.sPredictionSourceFingerprint), codeFingerprint), ...
    'Combo %d provenance mismatch', combo);
assert(isscalar(r.iSetting) && r.iSetting == combo, ...
    'Combo filename and embedded setting disagree for combo %d',combo);
assert(isequal(r.cTrendNames(:)', manifest.cMethodNames(:)'), ...
    'Combo %d method names disagree with its manifest', combo);

nDates = numel(r.vDates);
nAssets = numel(r.vAssetID);
nMethods = numel(manifest.cMethodNames);
iAssertVariableSize(rInfo, 'mYhat', [nAssets, nDates, nMethods], combo);
iAssertVariableSize(rInfo, 'mTrend_5', [nDates, nMethods], combo);
iAssertVariableSize(rInfo, 'mTrend_3', [nDates, nMethods], combo);
rLTW = rInfo(strcmp(cVariables, 'mLTW'));
assert(numel(rLTW) == 1 && numel(rLTW.size) == 2 && ...
    rLTW.size(1) == nDates && rLTW.size(2) >= 1, ...
    'Combo %d mLTW dimensions are invalid', combo);

status = r.rMethodStatus;
requiredStatus = {'cMethodNames', 'lApplicable', 'lCompleted', ...
    'vFinitePredictionWeeks', 'vFiniteFactorWeeks5', ...
    'vFiniteFactorWeeks3', 'vScheduledWeeks', ...
    'vEligiblePredictionWeeks', 'vEstimatedWeeks', ...
    'vEligibleFactorWeeks5', 'vEligibleFactorWeeks3', ...
    'vFailedPredictionWeeks', 'vFailedFactorWeeks5', ...
    'vFailedFactorWeeks3', 'vUnexpectedFailureWeeks', ...
    'vEstimatorFailureWeeks','vExpectedPredictionAssetWeeks', ...
    'vFinitePredictionAssetWeeks','vPredictionCoverageRatio', ...
    'vPredictionAssetCoverageRatio','vFactorCoverageRatio5', ...
    'vFactorCoverageRatio3', 'cFailureIdentifier', ...
    'cFailureMessage','cCoverage'};
assert(isstruct(status) && isscalar(status) && ...
    all(isfield(status, requiredStatus)), ...
    'Combo %d method-status schema is incomplete', combo);
assert(isequal(status.cMethodNames(:)', manifest.cMethodNames(:)') && ...
    numel(status.lApplicable) == nMethods && ...
    all(logical(status.lApplicable(:))), ...
    'Combo %d method applicability is invalid', combo);

logicalFields = {'lCompleted'};
numericFields = {'vFinitePredictionWeeks', 'vFiniteFactorWeeks5', ...
    'vFiniteFactorWeeks3', 'vScheduledWeeks', ...
    'vEligiblePredictionWeeks', 'vEstimatedWeeks', ...
    'vEligibleFactorWeeks5', 'vEligibleFactorWeeks3', ...
    'vFailedPredictionWeeks', 'vFailedFactorWeeks5', ...
    'vFailedFactorWeeks3', 'vUnexpectedFailureWeeks', ...
    'vEstimatorFailureWeeks','vExpectedPredictionAssetWeeks', ...
    'vFinitePredictionAssetWeeks','vPredictionCoverageRatio', ...
    'vPredictionAssetCoverageRatio','vFactorCoverageRatio5', ...
    'vFactorCoverageRatio3'};
for iField = 1:numel(logicalFields)
    value = status.(logicalFields{iField});
    assert(numel(value) == nMethods && all(logical(value(:))), ...
        'Combo %d has incomplete method completion flags', combo);
end
for iField = 1:numel(numericFields)
    value = status.(numericFields{iField});
    assert(isnumeric(value) && numel(value) == nMethods && ...
        all(isfinite(value(:))), ...
        'Combo %d status field %s is invalid', ...
        combo, numericFields{iField});
end
assert(numel(status.cFailureIdentifier) == nMethods && ...
    numel(status.cFailureMessage) == nMethods, ...
    'Combo %d failure diagnostics have invalid dimensions', combo);

scheduled = status.vScheduledWeeks(:);
eligiblePrediction = status.vEligiblePredictionWeeks(:);
eligible5 = status.vEligibleFactorWeeks5(:);
eligible3 = status.vEligibleFactorWeeks3(:);
finitePrediction = status.vFinitePredictionWeeks(:);
finite5 = status.vFiniteFactorWeeks5(:);
finite3 = status.vFiniteFactorWeeks3(:);
expectedAsset = status.vExpectedPredictionAssetWeeks(:);
finiteAsset = status.vFinitePredictionAssetWeeks(:);
audited5 = NaN(nMethods,1);
audited3 = NaN(nMethods,1);
for iMethod = 1:nMethods
    coverage = status.cCoverage{iMethod};
    assert(isstruct(coverage) && ...
        isfield(coverage,'vFactor5WeekStatus') && ...
        isfield(coverage,'vFactor3WeekStatus'), ...
        'Combo %d method %d lacks per-week coverage evidence', ...
        combo,iMethod);
    audited5(iMethod) = nnz(coverage.vFactor5WeekStatus == 3);
    audited3(iMethod) = nnz(coverage.vFactor3WeekStatus == 3);
end
assert(all(scheduled >= eligiblePrediction & ...
           scheduled >= eligible5 & scheduled >= eligible3) && ...
    all(eligiblePrediction > 0 & eligible5 > 0 & eligible3 > 0) && ...
    all(finitePrediction >= 0 & finitePrediction <= eligiblePrediction) && ...
    all(expectedAsset > 0 & finiteAsset >= 0 & ...
        finiteAsset <= expectedAsset) && ...
    all(finite5 >= 0 & finite5 <= eligible5) && ...
    all(finite3 >= 0 & finite3 <= eligible3) && ...
    all(status.vEstimatedWeeks(:) == finitePrediction) && ...
    all(status.vFailedPredictionWeeks(:) == ...
        eligiblePrediction - finitePrediction) && ...
    all(status.vFailedFactorWeeks5(:) == eligible5 - audited5) && ...
    all(status.vFailedFactorWeeks3(:) == eligible3 - audited3) && ...
    all(status.vUnexpectedFailureWeeks(:) == 0), ...
    'Combo %d method counts are internally inconsistent', combo);

ratioPrediction = finitePrediction ./ eligiblePrediction;
ratioPredictionAsset = finiteAsset ./ expectedAsset;
ratio5 = audited5 ./ eligible5;
ratio3 = audited3 ./ eligible3;
assert(all(abs(status.vPredictionCoverageRatio(:) - ...
               ratioPrediction) < 1e-12) && ...
    all(abs(status.vPredictionAssetCoverageRatio(:) - ...
               ratioPredictionAsset) < 1e-12) && ...
    all(abs(status.vFactorCoverageRatio5(:) - ratio5) < 1e-12) && ...
    all(abs(status.vFactorCoverageRatio3(:) - ratio3) < 1e-12) && ...
    all(ratioPrediction >= manifest.dMinCoverageRatio) && ...
    all(ratioPredictionAsset >= manifest.dMinCoverageRatio) && ...
    all(ratio5 >= manifest.dMinCoverageRatio) && ...
    all(ratio3 >= manifest.dMinCoverageRatio), ...
    'Combo %d method coverage is incomplete or inconsistent', combo);
end

function iAssertVariableSize(rInfo, name, expected, combo)
idx = strcmp({rInfo.name}, name);
assert(nnz(idx) == 1 && isequal(rInfo(idx).size, expected), ...
    'Combo %d variable %s has invalid dimensions', combo, name);
end

function iAssertStatusAgainstManifest(status, manifest, row)
assert(manifest.lCompleted(row), ...
    'Combo %d is not completed in the source manifest', row);
mapping = { ...
    'mMethodCompleted', 'lCompleted'; ...
    'mFinitePredictionWeeks', 'vFinitePredictionWeeks'; ...
    'mFiniteFactorWeeks5', 'vFiniteFactorWeeks5'; ...
    'mFiniteFactorWeeks3', 'vFiniteFactorWeeks3'; ...
    'mScheduledWeeks', 'vScheduledWeeks'; ...
    'mEligiblePredictionWeeks', 'vEligiblePredictionWeeks'; ...
    'mEstimatedWeeks', 'vEstimatedWeeks'; ...
    'mEligibleFactorWeeks5', 'vEligibleFactorWeeks5'; ...
    'mEligibleFactorWeeks3', 'vEligibleFactorWeeks3'; ...
    'mFailedPredictionWeeks', 'vFailedPredictionWeeks'; ...
    'mFailedFactorWeeks5', 'vFailedFactorWeeks5'; ...
    'mFailedFactorWeeks3', 'vFailedFactorWeeks3'; ...
    'mUnexpectedFailureWeeks', 'vUnexpectedFailureWeeks'; ...
    'mEstimatorFailureWeeks', 'vEstimatorFailureWeeks'; ...
    'mExpectedPredictionAssetWeeks', 'vExpectedPredictionAssetWeeks'; ...
    'mFinitePredictionAssetWeeks', 'vFinitePredictionAssetWeeks'; ...
    'mPredictionCoverageRatio', 'vPredictionCoverageRatio'; ...
    'mPredictionAssetCoverageRatio', 'vPredictionAssetCoverageRatio'; ...
    'mFactorCoverageRatio5', 'vFactorCoverageRatio5'; ...
    'mFactorCoverageRatio3', 'vFactorCoverageRatio3'; ...
    'cMethodFailureIdentifier', 'cFailureIdentifier'; ...
    'cMethodFailureMessage', 'cFailureMessage'};
for iField = 1:size(mapping, 1)
    assert(isequaln(manifest.(mapping{iField, 1})(row, :), ...
        status.(mapping{iField, 2})(:).'), ...
        'Combo %d and manifest status field %s disagree', ...
        row, mapping{iField, 1});
end
end

function tf = iStatusEquivalent(left, right)
fields = {'cMethodNames', 'lCompleted', 'vFinitePredictionWeeks', ...
    'vFiniteFactorWeeks5', 'vFiniteFactorWeeks3', ...
    'vScheduledWeeks', 'vEligiblePredictionWeeks', ...
    'vEstimatedWeeks', 'vEligibleFactorWeeks5', ...
    'vEligibleFactorWeeks3', 'vFailedPredictionWeeks', ...
    'vFailedFactorWeeks5', 'vFailedFactorWeeks3', ...
    'vUnexpectedFailureWeeks', 'vPredictionCoverageRatio', ...
    'vEstimatorFailureWeeks','vExpectedPredictionAssetWeeks', ...
    'vFinitePredictionAssetWeeks','vPredictionAssetCoverageRatio', ...
    'vFactorCoverageRatio5', 'vFactorCoverageRatio3', ...
    'cFailureIdentifier', 'cFailureMessage','cCoverage'};
tf = true;
for iField = 1:numel(fields)
    tf = tf && isequaln(left.(fields{iField}), right.(fields{iField}));
end
end

function iValidateManifestIdentity(manifest, runID, codeFingerprint, ...
        dataBuildID, tCombos)
required = {'sResearchDesignRunID', 'sCodeFingerprint', 'sDataBuildID', ...
    'iNumCombos', 'tCombos', 'cMethodNames', 'lCompleted', ...
    'mMethodCompleted', 'mScheduledWeeks', 'mEligiblePredictionWeeks', ...
    'mEstimatedWeeks', 'mFinitePredictionWeeks', ...
    'mEligibleFactorWeeks5', 'mEligibleFactorWeeks3', ...
    'mFiniteFactorWeeks5', 'mFiniteFactorWeeks3', ...
    'mFailedPredictionWeeks', 'mFailedFactorWeeks5', ...
    'mFailedFactorWeeks3', 'mUnexpectedFailureWeeks', ...
    'mEstimatorFailureWeeks','mExpectedPredictionAssetWeeks', ...
    'mFinitePredictionAssetWeeks','mPredictionCoverageRatio', ...
    'mPredictionAssetCoverageRatio','mFactorCoverageRatio5', ...
    'mFactorCoverageRatio3', 'cMethodFailureIdentifier', ...
    'cMethodFailureMessage','cPayloadSHA256', ...
    'dMinCoverageRatio', 'lComplete'};
assert(isstruct(manifest) && isscalar(manifest) && ...
    all(isfield(manifest, required)), 'Manifest schema is incomplete');
assert(strcmp(char(manifest.sResearchDesignRunID), runID), ...
    'Research run ID mismatch');
assert(strcmp(char(manifest.sCodeFingerprint), codeFingerprint), ...
    'Code fingerprint mismatch');
assert(strcmp(char(manifest.sDataBuildID), dataBuildID), ...
    'Data build ID mismatch');
assert(manifest.iNumCombos == height(tCombos) && ...
    isequaln(manifest.tCombos, tCombos), 'DesignChoices mismatch');
assert(manifest.dMinCoverageRatio == 0.50, ...
    'Coverage threshold must equal the predeclared 50%% audit floor');

nCombo = height(tCombos);
nMethods = numel(manifest.cMethodNames);
assert(isequal(size(manifest.lCompleted), [nCombo, 1]), ...
    'Manifest completion-vector dimensions are invalid');
assert(isequal(size(manifest.cPayloadSHA256),[nCombo,1]), ...
    'Manifest payload-digest vector dimensions are invalid');
matrixFields = {'mMethodCompleted', 'mScheduledWeeks', ...
    'mEligiblePredictionWeeks', 'mEstimatedWeeks', ...
    'mFinitePredictionWeeks', 'mEligibleFactorWeeks5', ...
    'mEligibleFactorWeeks3', 'mFiniteFactorWeeks5', ...
    'mFiniteFactorWeeks3', 'mFailedPredictionWeeks', ...
    'mFailedFactorWeeks5', 'mFailedFactorWeeks3', ...
    'mUnexpectedFailureWeeks','mEstimatorFailureWeeks', ...
    'mExpectedPredictionAssetWeeks','mFinitePredictionAssetWeeks', ...
    'mPredictionCoverageRatio','mPredictionAssetCoverageRatio', ...
    'mFactorCoverageRatio5', 'mFactorCoverageRatio3', ...
    'cMethodFailureIdentifier', 'cMethodFailureMessage'};
for iField = 1:numel(matrixFields)
    assert(isequal(size(manifest.(matrixFields{iField})), ...
        [nCombo, nMethods]), ...
        'Manifest field %s dimensions are invalid', matrixFields{iField});
end
end
