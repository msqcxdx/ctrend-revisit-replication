% CTREND_REVISIT_FILE_PURPOSE: Merge validated M1 b09 shard files into the canonical complete 3072-design result tree.
function merge_b09_shards()
% Validate isolated b09 shards and atomically publish one complete manifest.

codeDir = getenv('B09_CANONICAL_CODE_DIR');
shardRoot = getenv('B09_SHARD_RESULTS_ROOT');
runID = getenv('B09_RESEARCH_RUN_ID');
assert(isfolder(codeDir) && isfolder(shardRoot) && ~isempty(runID), ...
    'B09 merge environment is incomplete');

rAudit = fCollectB09ValidatedSources(codeDir, shardRoot, runID);
nCombo = rAudit.iNumCombos;
missing = find(~rAudit.lValid);
if ~isempty(missing)
    error('Missing %d combos; first missing combo is %d', ...
        numel(missing),missing(1));
end
nShards = str2double(getenv('B09_NUM_SHARDS'));
assert(isfinite(nShards) && nShards == floor(nShards) && ...
    ismember(nShards, [4, 8]), 'B09_NUM_SHARDS is invalid');
sourceCounts = arrayfun(@(shard)nnz(rAudit.vSourceShard == shard), ...
    (1:nShards)');
canonicalSourceCount = nnz(rAudit.vSourceShard == -1);

% All sources and all completed manifest rows have been validated before
% the first mutation.  Move (do not copy) each shard MAT into canonical
% storage so merging does not require another 24 GB result copy.  A crash
% here leaves some validated files canonical and the remainder in shards;
% fCollectB09ValidatedSources accepts that exact interrupted state.
for combo = 1:nCombo
    if rAudit.vSourceShard(combo) == -1
        continue
    end
    destination = fullfile(rAudit.sCanonicalCTREND, ...
        sprintf('CTREND_Combo%d.mat', combo));
    sourceDigest = [char(rAudit.cSourceFile(combo)),'.sha256'];
    destinationDigest = [destination,'.sha256'];
    temporaryDigest = [destinationDigest,'.merge_tmp'];
    [ok,message] = copyfile(sourceDigest,temporaryDigest,'f');
    assert(ok,'Could not stage combo %d payload digest: %s', ...
        combo,message);
    [ok,message] = movefile(temporaryDigest,destinationDigest,'f');
    assert(ok,'Could not publish combo %d payload digest: %s', ...
        combo,message);
    [ok, message] = movefile(char(rAudit.cSourceFile(combo)), ...
        destination, 'f');
    assert(ok, 'Could not move combo %d into canonical results: %s', ...
        combo, message);
    if isfile(sourceDigest)
        delete(sourceDigest);
    end
end

% Re-open every destination after the moves.  This both verifies publication
% and makes a rerun after an interrupted merge use canonical files whose
% completion rows are still only present in the shard manifests.
rPublished = fCollectB09ValidatedSources(codeDir, shardRoot, runID);
assert(all(rPublished.lValid) && ...
    all(rPublished.vSourceShard == -1), ...
    'Not every combo was validated at its canonical destination');

merged = iEmptyMergedManifest(rPublished.rBaseManifest);
for combo = 1:nCombo
    merged = iStoreMethodStatus(merged, ...
        rPublished.cSourceStatus{combo}, combo);
    merged.cPayloadSHA256{combo} = ...
        char(rPublished.cPayloadSHA256(combo));
    merged.lCompleted(combo) = true;
end
merged.lComplete = all(merged.lCompleted);
merged.sUpdatedAt = char(datetime('now', ...
    'Format','yyyy-MM-dd''T''HH:mm:ss'));
assert(merged.lComplete && all(merged.mMethodCompleted(:)), ...
    'Merged manifest is not complete');

% The complete manifest is the sole publication commit and is always last.
% If publication is interrupted before this rename, all moved MATs remain
% reusable but downstream Table 6 still sees an incomplete manifest.
temporaryManifest = [rPublished.sCanonicalManifestFile,'.merge_tmp'];
rRunManifest = merged;
save(temporaryManifest,'rRunManifest');
[ok,message] = movefile(temporaryManifest, ...
    rPublished.sCanonicalManifestFile,'f');
assert(ok,'Could not publish merged manifest: %s',message);

fprintf('B09_MERGE_OK combos=%d run_id=%s code=%s data=%s\n', ...
    nCombo,runID,rPublished.sCodeFingerprint,rPublished.sDataBuildID);
fprintf('source_counts canonical=%d', canonicalSourceCount);
for shard = 1:nShards
    fprintf(' shard%d=%d', shard, sourceCounts(shard));
end
fprintf('\n');
end

function merged = iEmptyMergedManifest(base)
merged = base;
merged.lCompleted(:) = false;
matrixFields = {'mMethodCompleted','mFinitePredictionWeeks', ...
    'mFiniteFactorWeeks5','mFiniteFactorWeeks3','mScheduledWeeks', ...
    'mEligiblePredictionWeeks','mEstimatedWeeks', ...
    'mEligibleFactorWeeks5','mEligibleFactorWeeks3', ...
    'mFailedPredictionWeeks','mFailedFactorWeeks5', ...
    'mFailedFactorWeeks3','mUnexpectedFailureWeeks', ...
    'mEstimatorFailureWeeks','mExpectedPredictionAssetWeeks', ...
    'mFinitePredictionAssetWeeks','mPredictionCoverageRatio', ...
    'mPredictionAssetCoverageRatio','mFactorCoverageRatio5', ...
    'mFactorCoverageRatio3'};
for k = 1:numel(matrixFields)
    field = matrixFields{k};
    if islogical(merged.(field))
        merged.(field)(:) = false;
    else
        merged.(field)(:) = NaN;
    end
end
merged.cMethodFailureIdentifier(:) = {''};
merged.cMethodFailureMessage(:) = {''};
merged.cPayloadSHA256(:) = {''};
merged.lComplete = false;
end

function merged = iStoreMethodStatus(merged,status,row)
mapping = { ...
    'mMethodCompleted', 'lCompleted'; ...
    'mFinitePredictionWeeks', 'vFinitePredictionWeeks'; ...
    'mFiniteFactorWeeks5', 'vFiniteFactorWeeks5'; ...
    'mFiniteFactorWeeks3', 'vFiniteFactorWeeks3'; ...
    'mScheduledWeeks', 'vScheduledWeeks'; ...
    'mEligiblePredictionWeeks', 'vEligiblePredictionWeeks'; ...
    'mEstimatedWeeks', 'vEstimatedWeeks'; ...
    'mEligibleFactorWeeks5', 'vEligibleFactorWeeks5'; ...
    'mEligibleFactorWeeks3', 'vEligibleFactorWeeks3'; ...
    'mFailedPredictionWeeks', 'vFailedPredictionWeeks'; ...
    'mFailedFactorWeeks5', 'vFailedFactorWeeks5'; ...
    'mFailedFactorWeeks3', 'vFailedFactorWeeks3'; ...
    'mUnexpectedFailureWeeks', 'vUnexpectedFailureWeeks'; ...
    'mEstimatorFailureWeeks', 'vEstimatorFailureWeeks'; ...
    'mExpectedPredictionAssetWeeks', 'vExpectedPredictionAssetWeeks'; ...
    'mFinitePredictionAssetWeeks', 'vFinitePredictionAssetWeeks'; ...
    'mPredictionCoverageRatio', 'vPredictionCoverageRatio'; ...
    'mPredictionAssetCoverageRatio', 'vPredictionAssetCoverageRatio'; ...
    'mFactorCoverageRatio5', 'vFactorCoverageRatio5'; ...
    'mFactorCoverageRatio3', 'vFactorCoverageRatio3'; ...
    'cMethodFailureIdentifier', 'cFailureIdentifier'; ...
    'cMethodFailureMessage', 'cFailureMessage'};
for k = 1:size(mapping,1)
    merged.(mapping{k,1})(row,:) = status.(mapping{k,2})(:).';
end
end
