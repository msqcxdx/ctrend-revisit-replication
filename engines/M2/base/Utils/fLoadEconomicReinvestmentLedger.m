function [rLedger,vLedgerWeekRow] = fLoadEconomicReinvestmentLedger( ...
    sDataPath,rReference,vAssetID,vWeekDate)
% Load and authenticate the separately stored economic event ledger.

arguments
    sDataPath {mustBeTextScalar}
    rReference (1,1) struct
    vAssetID (:,1) {mustBeNumeric}
    vWeekDate (:,1) {mustBeNumeric}
end
cRequired = {'sFormat','sFilename','sSHA256','sDataBuildID', ...
    'lUsesExternalSource','lAllowsCashAfterExit'};
assert(all(isfield(rReference,cRequired)) && ...
    ~rReference.lUsesExternalSource && ...
    ~rReference.lAllowsCashAfterExit, ...
    'Weekly data lack the authenticated no-cash economic-ledger reference');
sFile = fullfile(char(sDataPath),char(rReference.sFilename));
assert(isfile(sFile) && ...
    strcmp(fFileSHA256(sFile),char(rReference.sSHA256)), ...
    'Economic reinvestment ledger is missing or has changed');
rLoaded = load(sFile);
assert(isfield(rLoaded,'rEconomicReinvestmentLedger'), ...
    'Economic ledger MAT lacks its required payload');
rLedger = rLoaded.rEconomicReinvestmentLedger;
if isfield(rLoaded,'sDataBuildID')
    sBuildID = char(rLoaded.sDataBuildID);
elseif isfield(rLoaded,'sEconomicLedgerBuildID')
    sBuildID = char(rLoaded.sEconomicLedgerBuildID);
else
    error('Economic ledger MAT lacks a build ID');
end
assert(strcmp(sBuildID,char(rReference.sDataBuildID)) && ...
    strcmp(rLedger.sFormat,char(rReference.sFormat)) && ...
    isequal(double(rLedger.vAssetID(:)),double(vAssetID(:))), ...
    'Economic ledger build ID, format, or asset axis does not match');
[lWeek,vLedgerWeekRow] = ismember(vWeekDate(:),rLedger.vWeekDate(:));
assert(all(lWeek) && numel(unique(vLedgerWeekRow)) == numel(vWeekDate) && ...
    all(diff(vLedgerWeekRow) > 0), ...
    'Requested weeks are not a unique increasing subset of the ledger');
end
