function [mOpen,mHigh,mLow,mClose,mME,mVolume, ...
        vAssetIDPrice,vAssetIDME,vAssetIDVolume,rMetaData,rAudit] = ...
        fApplyConfiguredGlobalAssetExclusion( ...
        mOpen,mHigh,mLow,mClose,mME,mVolume, ...
        vAssetIDPrice,vAssetIDME,vAssetIDVolume,rMetaData)
% Remove the frozen D-axis asset set before any scientific transformation.
%
% The immutable vendor files are validated before this function is called.
% The exclusion CSV and its expected digest are supplied by the sealed
% experiment launcher.  Every listed CMCID must occur exactly once and its
% symbol must match metadata.  The same columns are then removed from all six
% raw panels and every metadata field.  No price, market cap, or volume value
% is edited.

arguments
    mOpen (:,:) {mustBeNumeric}
    mHigh (:,:) {mustBeNumeric}
    mLow (:,:) {mustBeNumeric}
    mClose (:,:) {mustBeNumeric}
    mME (:,:) {mustBeNumeric}
    mVolume (:,:) {mustBeNumeric}
    vAssetIDPrice (:,1) {mustBeNumeric}
    vAssetIDME (:,1) {mustBeNumeric}
    vAssetIDVolume (:,1) {mustBeNumeric}
    rMetaData (1,1) struct
end

vAssetIDPrice = vAssetIDPrice(:);
vAssetIDME = vAssetIDME(:);
vAssetIDVolume = vAssetIDVolume(:);
iNumAssets = numel(vAssetIDPrice);
assert(isequal(vAssetIDPrice,vAssetIDME) && ...
       isequal(vAssetIDPrice,vAssetIDVolume) && ...
       isfield(rMetaData,'vID') && isfield(rMetaData,'cSymbol') && ...
       isequal(vAssetIDPrice,rMetaData.vID(:)), ...
    'Configured exclusion requires identical raw-panel and metadata axes');
assert(all(cellfun(@(m)size(m,2) == iNumAssets, ...
    {mOpen,mHigh,mLow,mClose,mME,mVolume})), ...
    'Configured exclusion received a raw panel with the wrong asset axis');

sDataID = string(strtrim(getenv('CTTREND_DATA_TREATMENT_ID')));
sFile = string(strtrim(getenv('CTTREND_ASSET_EXCLUSION_FILE')));
sExpectedSHA = lower(string(strtrim( ...
    getenv('CTTREND_ASSET_EXCLUSION_SHA256'))));
assert(isscalar(sDataID) && ismember(sDataID,["D1","D2"]), ...
    'Configured exclusion is allowed only for D1 or D2');
assert(isscalar(sFile) && strlength(sFile) > 0 && isfile(sFile), ...
    'The frozen exclusion CSV is absent');
sFile = string(char(java.io.File(char(sFile)).getCanonicalPath()));
sObservedSHA = string(fFileSHA256(sFile));
assert(isscalar(sExpectedSHA) && strlength(sExpectedSHA) == 64 && ...
       sObservedSHA == sExpectedSHA, ...
    'The frozen exclusion CSV SHA-256 does not match the launcher');

tExclude = readtable(sFile,'TextType','string', ...
    'VariableNamingRule','preserve');
cRequired = {'asset_id','symbol','exclusion_basis'};
assert(all(ismember(cRequired,tExclude.Properties.VariableNames)), ...
    'The exclusion CSV lacks a required column');
assert(height(tExclude) > 0 && all(isfinite(tExclude.asset_id)) && ...
       all(tExclude.asset_id == floor(tExclude.asset_id)) && ...
       numel(unique(tExclude.asset_id)) == height(tExclude), ...
    'The exclusion CSV must contain unique integer CMCIDs');
if sDataID == "D1"
    assert(height(tExclude) == 1 && tExclude.asset_id == 3787, ...
        'D1 must exclude exactly CMCID 3787 / INNBCL');
elseif sDataID == "D2"
    assert(height(tExclude) == 28 && any(tExclude.asset_id == 3787), ...
        'D2 must contain INNBCL plus exactly 27 frozen same-CMCID event assets');
end

vExcludedAssetID = tExclude.asset_id(:);
lExclude = ismember(vAssetIDPrice,vExcludedAssetID);
assert(nnz(lExclude) == height(tExclude), ...
    'Every configured CMCID must occur exactly once in the raw universe');
for iRow = 1:height(tExclude)
    iColumn = find(vAssetIDPrice == tExclude.asset_id(iRow));
    assert(isscalar(iColumn) && ...
        strcmpi(string(rMetaData.cSymbol(iColumn)),tExclude.symbol(iRow)), ...
        'Configured symbol does not match CMCID %d',tExclude.asset_id(iRow));
end

cMetadataFields = fieldnames(rMetaData);
for iIdxField = 1:numel(cMetadataFields)
    sField = cMetadataFields{iIdxField};
    assert(numel(rMetaData.(sField)) == iNumAssets, ...
        'Metadata field %s does not have one element per raw asset',sField);
end

rAudit = struct();
rAudit.sFormat = 'cttrend-configured-global-asset-exclusion-v1';
rAudit.sDataTreatmentID = char(sDataID);
rAudit.sExclusionFile = char(sFile);
rAudit.sExclusionFileSHA256 = char(sObservedSHA);
rAudit.sCounterfactual = ...
    'listed CMCIDs never exist in the project research data';
rAudit.sInterpretation = ...
    'full-history named-asset sensitivity; not an implementable OOS screen';
rAudit.lArtificialData = false;
rAudit.vExcludedAssetID = vExcludedAssetID;
rAudit.cExcludedName = rMetaData.cName(lExclude);
rAudit.cExcludedSymbol = rMetaData.cSymbol(lExclude);
rAudit.iInputAssets = iNumAssets;
rAudit.iExcludedAssets = nnz(lExclude);
rAudit.vFiniteRawCellsBefore = [ ...
    nnz(isfinite(mOpen(:,lExclude))), ...
    nnz(isfinite(mHigh(:,lExclude))), ...
    nnz(isfinite(mLow(:,lExclude))), ...
    nnz(isfinite(mClose(:,lExclude))), ...
    nnz(isfinite(mME(:,lExclude))), ...
    nnz(isfinite(mVolume(:,lExclude)))];
rAudit.cRawPanelOrder = ...
    {'open','high','low','close','market_cap','volume'};
rAudit.sApplicationBoundary = [ ...
    'After immutable raw-input validation/hash and exact axis checks; ' ...
    'before sanitation, synchronization, returns, market series, ' ...
    'characteristics, technical indicators, models, and portfolios'];

mOpen(:,lExclude) = [];
mHigh(:,lExclude) = [];
mLow(:,lExclude) = [];
mClose(:,lExclude) = [];
mME(:,lExclude) = [];
mVolume(:,lExclude) = [];
vAssetIDPrice(lExclude) = [];
vAssetIDME(lExclude) = [];
vAssetIDVolume(lExclude) = [];
for iIdxField = 1:numel(cMetadataFields)
    sField = cMetadataFields{iIdxField};
    vField = rMetaData.(sField);
    vField(lExclude) = [];
    rMetaData.(sField) = vField;
end

rAudit.iOutputAssets = numel(vAssetIDPrice);
rAudit.iFinalB01Assets = rAudit.iOutputAssets;
rAudit.iDownstreamRuleExcludedAssets = 0;
rAudit.vDownstreamRuleExcludedAssetID = zeros(0,1);
rAudit.lExcludedIDsAbsentAfter = ...
    ~any(ismember(vAssetIDPrice,vExcludedAssetID)) && ...
    ~any(ismember(vAssetIDME,vExcludedAssetID)) && ...
    ~any(ismember(vAssetIDVolume,vExcludedAssetID)) && ...
    ~any(ismember(rMetaData.vID(:),vExcludedAssetID));
assert(rAudit.iOutputAssets == iNumAssets-height(tExclude) && ...
       rAudit.lExcludedIDsAbsentAfter && ...
       isequal(vAssetIDPrice,vAssetIDME) && ...
       isequal(vAssetIDPrice,vAssetIDVolume) && ...
       isequal(vAssetIDPrice,rMetaData.vID(:)) && ...
       all(cellfun(@(m)size(m,2) == rAudit.iOutputAssets, ...
           {mOpen,mHigh,mLow,mClose,mME,mVolume})), ...
    'Configured asset exclusion did not preserve aligned post-removal axes');
end
