#!/usr/bin/env python3
"""Reconcile archived validation snapshots with narrowly scoped source edits.

Historical artifact manifests describe the source present at their validation
date; they are not overwritten to claim that existing outputs were generated by
different bytes. This read-only checker permits only the three run-path adapters
and the additive E11 coverage fields described below. It compares executable
syntax, verifies the historical blob against its recorded digest, and checks
that the path adapters still select the same complete runs. Any other code
change must be investigated rather than accepted by refreshing a checksum.

This helper is for the controlled archive, whose Git history and local accepted
run index are available. It is not part of the public clone's offline checks.
"""
from __future__ import annotations

import ast
import copy
from hashlib import sha256
from pathlib import Path
import subprocess

from accepted_run_roots import accepted_roots

REPO = Path(__file__).resolve().parents[2]
SNAPSHOT_COMMIT = "498332a2b02fdcb6bffefcd3941bd2cb2e0dd88a"
PATH_ADAPTERS = {
    "analyze_e02.py": ("RUNS", 0),
    "analyze_e03_oos.py": ("RUNS", 1),
    "extract_e08_asset_contributions.py": ("M0_RUNS", 0),
}
ADDED_COVERAGE_FIELDS = {
    "training_calendar_weeks", "scheduled_oos_weeks", "pair_oos_n",
    "pair_full_calendar_coverage", "pair_scheduled_oos_coverage",
}


def syntax(node: ast.AST) -> str:
    """Ignore comments/locations, but retain every executable expression."""
    return ast.dump(node, include_attributes=False)


def assignment(tree: ast.Module, name: str) -> ast.Assign:
    nodes = [n for n in tree.body if isinstance(n, ast.Assign)
             and len(n.targets) == 1 and isinstance(n.targets[0], ast.Name)
             and n.targets[0].id == name]
    if len(nodes) != 1:
        raise ValueError(f"Expected one assignment to {name}")
    return nodes[0]


def replace_statement(tree: ast.Module, before: str, after: str = "") -> None:
    """Replace one explicitly named adapter statement, never arbitrary code."""
    target = ast.parse(before).body[0]
    replacement = ast.parse(after).body
    matches = 0

    class Replace(ast.NodeTransformer):
        def visit(self, node):
            nonlocal matches
            if isinstance(node, ast.stmt) and syntax(node) == syntax(target):
                matches += 1
                return copy.deepcopy(replacement)
            return super().visit(node)

    Replace().visit(tree)
    if matches != 1:
        raise ValueError(f"Adapter statement is missing or ambiguous: {before}")


def path_projection(name: str, old: ast.Module, current: ast.Module) -> dict[str, str]:
    """Undo only input-location plumbing; all numerical syntax must remain."""
    variable, method = PATH_ADAPTERS[name]
    prior = assignment(old, variable)
    previous_paths = ast.literal_eval(prior.value)
    expected_ids = tuple(f"P{p}_M{method}_D{d}" for p in (0, 1) for d in (0, 1, 2))
    if tuple(previous_paths) != expected_ids:
        raise ValueError(f"Historical experiment selection differs: {name}")
    current_assignment = assignment(current, variable)
    expected = ast.parse(
        f'tuple(f"P{{p}}_M{method}_D{{d}}" for p in (0, 1) for d in (0, 1, 2))',
        mode="eval").body
    if syntax(current_assignment.value) != syntax(expected):
        raise ValueError(f"Changed experiment selection: {name}")
    current_assignment.value = copy.deepcopy(prior.value)
    replace_statement(current, "from accepted_run_roots import accepted_roots")
    main = next(n for n in current.body if isinstance(n, ast.FunctionDef) and n.name == "main")
    if name in ("analyze_e02.py", "analyze_e03_oos.py"):
        loops = [n for n in main.body if isinstance(n, ast.For)
                 and syntax(n.iter) == syntax(ast.parse("accepted_roots(RUNS).items()", mode="eval").body)]
        if len(loops) != 1 or syntax(loops[0].target) != syntax(
                ast.parse("for experiment, run in x:\n pass").body[0].target):
            raise ValueError(f"Unexpected accepted-run loop: {name}")
        loop = loops[0]
        loop.target = ast.parse("for experiment, run_text in x:\n pass").body[0].target
        loop.iter = ast.parse("RUNS.items()", mode="eval").body
        if name == "analyze_e02.py":
            replace_statement(current, "rows, source_paths = analyze_one(experiment, run)",
                              "rows, source_paths = analyze_one(experiment, Path(run_text))")
        else:
            loop.body.insert(0, ast.parse("run = Path(run_text)").body[0])
    else:
        replace_statement(current, "accepted_m0_runs = accepted_roots(M0_RUNS)")
        replace_statement(current, "run = accepted_m0_runs[experiment]",
                          "run = Path(M0_RUNS[experiment])")
    return previous_paths


def coverage_projection(old: ast.Module, current: ast.Module) -> None:
    """Remove E11's additive output fields; do not normalize return formulas."""
    definitions = [n for n in current.body if isinstance(n, ast.FunctionDef) and n.name == "coverage"]
    if len(definitions) != 1:
        raise ValueError("Expected one E11 coverage helper")
    expected_helper = ast.parse('''
def coverage(pair_mask: np.ndarray, training_weeks: int) -> dict[str, float | int]:
    n_calendar = len(pair_mask)
    if not 0 <= training_weeks < n_calendar:
        raise ValueError("Invalid design-specific training-calendar length")
    n_oos = n_calendar-training_weeks
    n_pair_oos = int(pair_mask[training_weeks:].sum())
    return dict(training_calendar_weeks=training_weeks,
                scheduled_oos_weeks=n_oos, pair_oos_n=n_pair_oos,
                pair_full_calendar_coverage=float(pair_mask.mean()),
                pair_scheduled_oos_coverage=n_pair_oos/n_oos)
''').body[0]
    helper = copy.deepcopy(definitions[0])
    if (helper.body and isinstance(helper.body[0], ast.Expr)
            and isinstance(helper.body[0].value, ast.Constant)
            and isinstance(helper.body[0].value.value, str)):
        helper.body.pop(0)
    if syntax(helper) != syntax(expected_helper):
        raise ValueError("E11 coverage helper differs from the checked denominator definitions")
    current.body.remove(definitions[0])
    fields = assignment(current, "FIELDS")
    values = ast.literal_eval(fields.value)
    previous = ast.literal_eval(assignment(old, "FIELDS").value)
    if len(values) != len(set(values)) or set(values)-set(previous) != ADDED_COVERAGE_FIELDS:
        raise ValueError("Unexpected E11 schema change")
    fields.value = ast.parse(repr([f for f in values if f not in ADDED_COVERAGE_FIELDS]), mode="eval").body
    worker = next(n for n in current.body if isinstance(n, ast.FunctionDef) and n.name == "worker")
    if worker.args.args[-1].arg != "training_weeks":
        raise ValueError("Unexpected E11 worker arguments")
    worker.args.args.pop()
    replace_statement(current,
        'if mask[:training_weeks[combo-1]].any():\n'
        '    raise RuntimeError("Paired factor became finite inside its training schedule")')
    additions = 0
    for node in ast.walk(worker):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == "dict":
            for keyword in list(node.keywords):
                if keyword.arg is None and syntax(keyword.value) == syntax(
                        ast.parse("coverage(mask, training_weeks[combo-1])", mode="eval").body):
                    node.keywords.remove(keyword)
                    additions += 1
    if additions != 1:
        raise ValueError("Unexpected E11 coverage insertion")
    replace_statement(current,
        'with (OUT / "design_choices_M1.csv").open(newline="", encoding="utf-8") as f:\n'
        '    designs = list(csv.DictReader(f))')
    replace_statement(current,
        'if len(designs) != 3072 or any(int(row["b09_combo_id"]) != i\n'
        '        for i, row in enumerate(designs, start=1)):\n'
        '    raise RuntimeError("Design-choice rows are not the canonical combo order")')
    replace_statement(current, 'training_weeks = [int(row["vNumIn"]) for row in designs]')
    submissions = [n for n in ast.walk(current) if isinstance(n, ast.Call)
                   and syntax(n.func) == syntax(ast.parse("pool.submit", mode="eval").body)]
    if len(submissions) != 1 or syntax(submissions[0].args[-1]) != syntax(ast.Name(id="training_weeks", ctx=ast.Load())):
        raise ValueError("Unexpected E11 task submission")
    submissions[0].args.pop()


def compare_sources(name: str, old_bytes: bytes, current_bytes: bytes) -> dict:
    """Verify the whole module, allowing only the listed adapter projection."""
    old, current = ast.parse(old_bytes), ast.parse(current_bytes)
    paths = {}
    if name in PATH_ADAPTERS:
        paths = path_projection(name, old, current)
        scope = "input_location_only"
    elif name == "analyze_e11.py":
        coverage_projection(old, current)
        scope = "additive_coverage_schema_existing_statistics_unchanged"
    else:
        raise ValueError(f"No source-compatibility proof for {name}")
    if syntax(old) != syntax(current):
        raise ValueError(f"Executable source changed beyond the checked scope: {name}")
    return {"scope": scope, "previous_paths": paths}


def read_snapshot(relative: str, expected_sha: str) -> bytes:
    """Identify historical bytes without declaring them to be today's source."""
    path = Path(relative)
    if path.parent != Path("scripts"):
        raise ValueError(f"Unsupported source path: {relative}")
    blob = subprocess.check_output(
        ["git", "show", f"{SNAPSHOT_COMMIT}:followup_research/{path.as_posix()}"], cwd=REPO)
    if sha256(blob).hexdigest() != expected_sha:
        raise ValueError(f"Historical source does not match its artifact manifest: {relative}")
    return blob


def check_source_compatibility(relative: str, expected_sha: str) -> dict:
    """Read verified Git history and check the real path adapters, without writes."""
    path = Path(relative)
    blob = read_snapshot(relative, expected_sha)
    checked = compare_sources(path.name, blob, (REPO / "followup_research" / path).read_bytes())
    previous = checked.pop("previous_paths")
    if previous:
        resolved = accepted_roots(tuple(previous))
        if any(Path(root).resolve() != resolved[eid] for eid, root in previous.items()):
            raise ValueError(f"Input-location adapter selects different runs: {relative}")
        checked["same_accepted_runs"] = len(previous)
    return checked
